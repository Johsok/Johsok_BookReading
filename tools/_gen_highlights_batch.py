def validate(book_id: str, texts: list[str], ban_extra: list[str] | None = None) -> list[str]:
    if len(texts) != 150:
        raise SystemExit(f"{book_id} count={len(texts)}")
    if len(set(texts)) != 150:
        raise SystemExit(f"{book_id} duplicate bodies")
    bans = FORBIDDEN + (ban_extra or [])
    for i, body in enumerate(texts, 1):
        if len(body) < 12:
            raise SystemExit(f"{book_id} #{i} too short: {body}")
        if re.match(r"^第\d+步[，,]", body):
            raise SystemExit(f"{book_id} #{i} step prefix")
        for f in bans:
            if f in body:
                raise SystemExit(f"{book_id} #{i} forbidden {f}")
        m = re.match(r"^([^：:]{1,12})[：:]", body)
        if m and not m.group(1).endswith(("是", "為", "在於", "說", "問", "提醒", "表示", "指出")):
            # allow up to 2; checked globally below
            pass
    starts = Counter(b[:18] for b in texts if len(b) >= 18)
    if starts and starts.most_common(1)[0][1] >= 4:
        raise SystemExit(f"{book_id} repeated starts: {starts.most_common(3)}")
    short_colon = 0
    for body in texts:
        m = re.match(r"^([^：:]{1,12})[：:]", body)
        if m and not m.group(1).endswith(("是", "為", "在於", "說", "問", "提醒", "表示", "指出")):
            short_colon += 1
    if short_colon >= 3:
        raise SystemExit(f"{book_id} short colon={short_colon}")
    return [f"{i:03d}、{t}" for i, t in enumerate(texts, 1)]


def write_result(book_id: str, highlights: list[str]) -> Path:
    path = TOOLS / f".findbook_results_grok_{book_id}.json"
    path.write_text(
        json.dumps({"id": book_id, "highlights": highlights}, ensure_ascii=False, indent=2) + "\n",
        encoding="utf-8",
    )
    return path


