def scrub(bodies: list[str]) -> list[str]:
    """Strip and reject empty lines."""
    cleaned = [item.strip() for item in bodies if item.strip()]
    return cleaned


def extra_checks(book_id: str, title: str, author: str, bodies: list[str]) -> None:
    """Flag leftover English fragments and likely simplified characters."""
    latin = re.compile(r"[A-Za-z]{3,}")
    for index, body in enumerate(bodies, 1):
        if len(body) < 12:
            raise ValueError(f"{book_id} 第 {index} 點過短：{body} ({len(body)})")
        if latin.search(body):
            raise ValueError(f"{book_id} 第 {index} 點含英文片段：{body}")
        if "｜" in body or "**" in body or "`" in body:
            raise ValueError(f"{book_id} 第 {index} 點含禁用符號")
        if any(token in body for token in FORBIDDEN):
            raise ValueError(f"{book_id} 第 {index} 點含禁用前綴")
        if title and title in body:
            raise ValueError(f"{book_id} 第 {index} 點含完整書名")
        if author and author in body:
            raise ValueError(f"{book_id} 第 {index} 點含完整作者")


def main() -> None:
    """Validate and write one results JSON per book."""
    written = []
    for book_id, title, author, raw in BOOKS:
        bodies = scrub(raw)
        extra_checks(book_id, title, author, bodies)
        print(f"count\t{book_id}\t{len(bodies)}")
        highlights = [f"{index:03d}、{body}" for index, body in enumerate(bodies, 1)]
        validate_highlights(book_id, highlights, title, author)
        payload = {"id": book_id, "highlights": highlights}
        out = TOOLS / f".findbook_results_grok_{book_id}.json"
        out.write_text(json.dumps(payload, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
        written.append((book_id, len(highlights), out.name))
        print(f"ready\t{book_id}\t{len(highlights)}")
    print(f"files={len(written)}")


if __name__ == "__main__":
    main()




