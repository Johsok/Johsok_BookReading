def validate(bodies: list[str]) -> None:
    if len(bodies) != 150:
        raise SystemExit(f"count {len(bodies)}")
    forbidden = ("本書", "作者指出", "本章", "這一章", "｜")
    short_colon = []
    for i, body in enumerate(bodies, 1):
        if "\n" in body or "\r" in body:
            raise SystemExit(f"newline {i}")
        if any(p in body for p in forbidden):
            raise SystemExit(f"forbidden {i}")
        if len(body) < 12:
            raise SystemExit(f"short {i} {len(body)}")
        if re.search(r".{1,8}面第\d+步[，,]", body) or re.match(r"^第\d+步[，,]", body):
            raise SystemExit(f"step {i}")
        m = re.match(r"^([^：:]{1,12})[：:]", body)
        if m and not m.group(1).endswith(("是", "為", "在於", "說", "問", "提醒", "表示", "指出")):
            short_colon.append((i, m.group(1)))
        if TITLE in body:
            raise SystemExit(f"title {i}")
    if len(short_colon) >= 3:
        raise SystemExit(f"short colon {short_colon}")
    if len(set(bodies)) != len(bodies):
        dups = [b for b, c in Counter(bodies).items() if c > 1]
        raise SystemExit(f"dup {dups[:3]}")
    starts = Counter(b[:18] for b in bodies if len(b) >= 18)
    bad = [(k, v) for k, v in starts.items() if v >= 4]
    if bad:
        raise SystemExit(f"starts {bad}")
    if sum(AUTHOR in b for b in bodies) >= 2:
        raise SystemExit("author")
    print("ok", len(bodies), "maxstart", starts.most_common(1)[0][1], "colon", short_colon)


