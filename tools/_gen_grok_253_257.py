def numbered(bodies: list[str]) -> list[str]:
    return [f"{i:03d}、{b}" for i, b in enumerate(bodies, 1)]


def load_forbidden_bodies(book_id: str) -> set[str]:
    out: set[str] = set()
    for path in FORBIDDEN_FILES.get(book_id, []):
        if not path.exists():
            continue
        data = json.loads(path.read_text(encoding="utf-8-sig"))
        for line in data.get("chatgptHighlights") or []:
            if "、" in line:
                out.add(line.split("、", 1)[1].strip())
    return out


def extra_checks(book_id: str, bodies: list[str], title: str, author: str) -> None:
    banned = load_forbidden_bodies(book_id)
    overlap = [b for b in bodies if b in banned]
    if overlap:
        raise SystemExit(f"{book_id} copied {len(overlap)} sentences, first={overlap[0]}")
    starts = Counter(b[:18] for b in bodies if len(b) >= 18)
    worst = starts.most_common(1)[0]
    if worst[1] >= 4:
        raise SystemExit(f"{book_id} prefix {worst}")
    for label, value in (("title", title), ("author", author)):
        if value and sum(value in b for b in bodies) >= 2:
            raise SystemExit(f"{book_id} repeats {label}")
    # catch leftover english token
    for i, b in enumerate(bodies, 1):
        if any(ch.isascii() and ch.isalpha() for ch in b):
            raise SystemExit(f"{book_id} #{i} has latin letters: {b}")


def write_and_complete(book_id: str, bodies: list[str], title: str, author: str) -> None:
    if len(bodies) != 150:
        raise SystemExit(f"{book_id} bodies={len(bodies)} != 150")
    extra_checks(book_id, bodies, title, author)
    highlights = numbered(bodies)
    validate_highlights(book_id, highlights, title, author)
    out = TOOLS / f".findbook_results_grok_{book_id}.json"
    out.write_text(
        json.dumps({"id": book_id, "highlights": highlights}, ensure_ascii=False, indent=2) + "\n",
        encoding="utf-8",
    )
    cmd = [
        sys.executable,
        str(TOOLS / "findbook_writer.py"),
        "complete",
        "--category-id",
        CAT,
        "--results",
        str(out),
    ]
    proc = subprocess.run(cmd, cwd=str(ROOT), capture_output=True, text=True)
    print(proc.stdout)
    if proc.returncode != 0:
        print(proc.stderr)
        raise SystemExit(f"complete failed: {book_id}")
    saved = json.loads((ROOT / "Books" / CAT / f"{book_id}.json").read_text(encoding="utf-8-sig"))
    assert saved.get("highlightsSource") == "grok"
    assert saved.get("chatgptStatus") == "complete"
    assert len(saved.get("chatgptHighlights") or []) == 150
    print(f"OK\t{book_id}\t{len(saved['chatgptHighlights'])}")


def main() -> None:
    only = sys.argv[1:] or list(BOOKS)
    for book_id in only:
        meta = BOOKS[book_id]
        write_and_complete(book_id, meta["bodies"], meta["title"], meta["author"])


if __name__ == "__main__":
    main()
