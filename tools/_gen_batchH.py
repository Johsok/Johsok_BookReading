def numbered(bodies: list[str]) -> list[str]:
    return [f"{i:03d}、{body}" for i, body in enumerate(bodies, 1)]


def precheck(name: str, bodies: list[str], title: str, author: str) -> None:
    print(f"{name} count={len(bodies)} unique={len(set(bodies))} min={min(len(b) for b in bodies)}")
    starts = Counter(b[:18] for b in bodies if len(b) >= 18)
    bad = [(k, n) for k, n in starts.items() if n >= 4]
    if bad:
        print("  repeated starts", bad)
    for i, b in enumerate(bodies, 1):
        if "｜" in b or "本書" in b or "作者指出" in b or "本章" in b or "這一章" in b:
            print(f"  forbidden {i}: {b}")
        if title and title in b:
            print(f"  title leak {i}")
        if author and author in b:
            print(f"  author leak {i}")
        if "新地點 palce" in b or "reciprocal" in b:
            print(f"  garbage {i}: {b}")


