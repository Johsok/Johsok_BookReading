def numbered(bodies: list[str]) -> list[str]:
    return [f"{i:03d}、{body.strip()}" for i, body in enumerate(bodies, 1)]


def report(book_id: str, bodies: list[str], title: str, author: str) -> None:
    print(f"{book_id} count={len(bodies)} unique={len(set(bodies))}")
    if len(bodies) != 150:
        raise SystemExit(f"{book_id} need 150, got {len(bodies)}")
    highlights = numbered(bodies)
    validate_highlights(book_id, highlights, title, author)


def write_and_complete(book_id: str, bodies: list[str], title: str, author: str) -> None:
    report(book_id, bodies, title, author)
    payload = {"id": book_id, "highlights": numbered(bodies)}
    path = ROOT / "tools" / f".findbook_results_grok_{book_id}.json"
    path.write_text(json.dumps(payload, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    cmd = [
        sys.executable,
        str(ROOT / "tools" / "findbook_writer.py"),
        "complete",
        "--category-id",
        "02_psychology_growth",
        "--results",
        str(path),
    ]
    completed = subprocess.run(cmd, cwd=str(ROOT), check=False, text=True, capture_output=True)
    sys.stdout.write(completed.stdout)
    sys.stderr.write(completed.stderr)
    if completed.returncode != 0:
        raise SystemExit(completed.returncode)


def assert_distinct_from_87(bodies: list[str]) -> None:
    book87 = ROOT / "Books" / "02_psychology_growth" / "02_psychology_growth-20260717-87.json"
