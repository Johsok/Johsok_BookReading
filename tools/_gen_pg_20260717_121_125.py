    old_bodies = {line.split("、", 1)[-1].strip() for line in old if isinstance(line, str)}
    overlap = [body for body in bodies if body in old_bodies]
    if overlap:
        raise SystemExit(f"125 overlaps 87: {overlap[:3]}")


