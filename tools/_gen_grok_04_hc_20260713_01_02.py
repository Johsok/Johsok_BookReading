EXTRA_FORBIDDEN = ("本書", "作者指出", "本章", "這一章", "｜")
CHAPTER_RE = __import__("re").compile(r"第[0-9一二三四五六七八九十百]+章")


def to_lines(bodies: list[str]) -> list[str]:
    if len(bodies) != 150:
        raise SystemExit(f"count {len(bodies)} != 150")
    return [f"{i:03d}、{body}" for i, body in enumerate(bodies, 1)]


def extra_checks(book_id: str, bodies: list[str], title: str, author: str) -> None:
    starts = Counter(b[:18] for b in bodies)
    bad = [(s, n) for s, n in starts.items() if n >= 4]
    if bad:
        raise SystemExit(f"{book_id} repeated starts: {bad[:8]}")
    for i, body in enumerate(bodies, 1):
        for token in EXTRA_FORBIDDEN:
            if token in body:
                raise SystemExit(f"{book_id} #{i} forbidden {token}")
        if CHAPTER_RE.search(body):
            raise SystemExit(f"{book_id} #{i} chapter wording")
        if " " in body[:8] and body.startswith(" fort"):
            raise SystemExit(f"{book_id} #{i} english leak {body[:40]}")
    if title and sum(title in b for b in bodies) >= 2:
        raise SystemExit(f"{book_id} title repeated")
    if author and sum(author in b for b in bodies) >= 2:
        raise SystemExit(f"{book_id} author repeated")


def write_results(book_id: str, lines: list[str]) -> Path:
    path = ROOT / "tools" / f".findbook_results_grok_{book_id}.json"
    write_json_atomic(path, {"id": book_id, "highlights": lines})
    return path


