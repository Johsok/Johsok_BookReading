PUNCT_FORBIDDEN = ("｜",)
FORBIDDEN_PREFIXES = ("本書", "作者指出", "本章", "這一章")
BAD_TEMPLATES = (
    "以「商業理財」作為",
    "落到具體情境，再用可觀察的結果確認做法是否有效",
    "先界定目標，再把",
)
NATURAL_COLON_SUFFIXES = ("是", "為", "在於", "說", "問", "提醒", "表示", "指出")


def validate(title: str, author: str, bodies: list[str]) -> list[str]:
    short_colon = []
    cleaned = []
    for i, body in enumerate(bodies, 1):
        if len(body) < 12:
            raise ValueError(f"too short {i}: {body}")
        if any(x in body for x in PUNCT_FORBIDDEN):
            raise ValueError(f"forbidden punct {i}")
        if any(p in body for p in FORBIDDEN_PREFIXES):
            raise ValueError(f"forbidden prefix {i}")
        if any(t in body for t in BAD_TEMPLATES):
            raise ValueError(f"bad template {i}")
        if re.search(r".{1,8}面第\d+步[，,]", body) or re.match(r"^第\d+步[，,]", body):
            raise ValueError(f"step wording {i}")
        if "優惠價" in body or "870" in body:
            raise ValueError(f"price author leak {i}")
        m = re.match(r"^([^：:]{1,12})[：:]", body)
        if m and not m.group(1).endswith(NATURAL_COLON_SUFFIXES):
            short_colon.append(i)
        cleaned.append(f"{i:03d}、{body}")
    if len(short_colon) >= 3:
        raise ValueError(f"short colon {short_colon}")
    if len(set(bodies)) != len(bodies):
        raise ValueError("duplicate bodies")
    starts = Counter(b[:18] for b in bodies if len(b) >= 18)
    if starts and starts.most_common(1)[0][1] >= 4:
        raise ValueError(f"repeat starts {starts.most_common(3)}")
    for label, value in (("title", title), ("author", author)):
        if value and sum(value in b for b in bodies) >= 2:
            raise ValueError(f"repeat {label}")
    # full title / real author name soft checks from user rules
    if sum(TITLE in b for b in bodies) >= 2:
        raise ValueError("full title too often")
    return cleaned


def main() -> None:
    highlights = validate(TITLE, AUTHOR, BODIES)
    out = Path(__file__).with_name(f".findbook_results_grok_{BOOK_ID}.json")
    out.write_text(
        json.dumps({"id": BOOK_ID, "highlights": highlights}, ensure_ascii=False, indent=2) + "\n",
        encoding="utf-8",
    )
    print(f"wrote {out} count={len(highlights)}")


if __name__ == "__main__":
    main()
