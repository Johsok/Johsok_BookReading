def _check_extra(book_id: str, bodies: list[str], title: str, author: str) -> None:
    if len(bodies) != 150:
        raise SystemExit(f"{book_id} count={len(bodies)}")
    if len(set(bodies)) != 150:
        raise SystemExit(f"{book_id} duplicate bodies")
    starts = [b[:18] for b in bodies]
    bad = [k for k, v in Counter(starts).items() if v >= 4]
    if bad:
        raise SystemExit(f"{book_id} repeated starts: {bad[:5]}")
    forbidden = ("本書", "作者指出", "本章", "這一章", "｜")
    templates = (
        "閱讀時可先確認作者如何定義問題",
        "可把觀點轉成一個具體案例",
        "應比較支持證據與可能反例",
        "實際運用時可先做小規模嘗試",
        "整理筆記時宜區分核心主張",
    )
    for i, body in enumerate(bodies, 1):
        if len(body) < 12:
            raise SystemExit(f"{book_id} {i:03d} too short")
        if any(x in body for x in forbidden):
            raise SystemExit(f"{book_id} {i:03d} forbidden")
        if any(x in body for x in templates):
            raise SystemExit(f"{book_id} {i:03d} template")
        if re.search(r"第\d+章", body):
            raise SystemExit(f"{book_id} {i:03d} chapter")
        if "instant" in body or "nightmare" in body or " co-use" in body or "enticing" in body or " dup " in body:
            raise SystemExit(f"{book_id} {i:03d} leftover english: {body}")
        simp = SIMP_RE.findall(body)
        if simp:
            raise SystemExit(f"{book_id} {i:03d} simplified {simp} :: {body}")
    if title and sum(title in b for b in bodies) >= 2:
        raise SystemExit(f"{book_id} title repeated")
    if author and sum(author in b for b in bodies) >= 2:
        raise SystemExit(f"{book_id} author repeated")


