def validate(title: str, author: str, bodies: list[str]) -> list[str]:
    short = []
    for i, b in enumerate(bodies, 1):
        if len(b) < 12:
            raise ValueError(f"short {i}")
        if "｜" in b:
            raise ValueError(f"bar {i}")
        for p in ("本書", "作者指出", "本章", "這一章"):
            if p in b:
                raise ValueError(f"prefix {i} {b}")
        for t in (
            "以「商業理財」作為",
            "落到具體情境，再用可觀察的結果確認做法是否有效",
            "先界定目標，再把",
        ):
            if t in b:
                raise ValueError("tmpl")
        if re.search(r".{1,8}面第\d+步[，,]", b) or re.match(r"^第\d+步[，,]", b):
            raise ValueError("step")
        m = re.match(r"^([^：:]{1,12})[：:]", b)
        if m and not m.group(1).endswith(("是", "為", "在於", "說", "問", "提醒", "表示", "指出")):
            short.append(i)
    if len(short) >= 3:
        raise ValueError(short)
    if len(set(bodies)) != len(bodies):
        raise ValueError("dup")
    starts = Counter(b[:18] for b in bodies if len(b) >= 18)
    if starts and starts.most_common(1)[0][1] >= 4:
        raise ValueError(starts.most_common(3))
    if sum(title in b for b in bodies) >= 2:
        raise ValueError("title")
    if sum(author in b for b in bodies) >= 2:
        raise ValueError("author")
    return [f"{i:03d}、{b}" for i, b in enumerate(bodies, 1)]


def main() -> None:
    # fix simplified char if any
    bodies = [b.replace("复用", "複用") for b in BODIES]
    hs = validate(TITLE, AUTHOR, bodies)
    out = Path(__file__).with_name(f".findbook_results_grok_{BOOK_ID}.json")
    out.write_text(
        json.dumps({"id": BOOK_ID, "highlights": hs}, ensure_ascii=False, indent=2) + "\n",
        encoding="utf-8",
    )
    print("wrote", out, len(hs))


if __name__ == "__main__":
    main()
