from __future__ import annotations

import json
import re
import subprocess
import sys
from collections import Counter
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
WRITER = ROOT / "tools" / "findbook_writer.py"
NUMBER_RE = re.compile(r"^\d{3}、")
NATURAL_COLON_SUFFIXES = ("是", "為", "在於", "說", "問", "提醒", "表示", "指出")
FORBIDDEN_PREFIXES = ("本書", "作者指出", "本章", "這一章")


def validate(book_id: str, lines: list[str], title: str, author: str) -> None:
    if len(lines) != 150:
        raise ValueError(f"{book_id} count={len(lines)}")
    short_colon = []
    bodies = []
    for i, line in enumerate(lines, 1):
        expected = f"{i:03d}、"
        if not line.startswith(expected):
            raise ValueError(f"{book_id} #{i} numbering")
        if "\n" in line or "\r" in line or "｜" in line:
            raise ValueError(f"{book_id} #{i} forbidden format")
        if any(ch in line for ch in "*#`"):
            raise ValueError(f"{book_id} #{i} markdown")
        body = NUMBER_RE.sub("", line, count=1).strip()
        if len(body) < 12:
            raise ValueError(f"{book_id} #{i} too short: {body}")
        if any(p in body for p in FORBIDDEN_PREFIXES):
            raise ValueError(f"{book_id} #{i} forbidden prefix")
        if re.search(r".{1,8}面第\d+步[，,]", body) or re.match(r"^第\d+步[，,]", body):
            raise ValueError(f"{book_id} #{i} step wording")
        match = re.match(r"^([^：:]{1,12})[：:]", body)
        if match and not match.group(1).endswith(NATURAL_COLON_SUFFIXES):
            short_colon.append(i)
        bodies.append(body)
    if len(short_colon) >= 3:
        raise ValueError(f"{book_id} short-colon {short_colon}")
    if len(set(bodies)) != len(bodies):
        raise ValueError(f"{book_id} exact duplicates")
    starts = Counter(b[:18] for b in bodies if len(b) >= 18)
    bad = [(k, v) for k, v in starts.items() if v >= 4]
    if bad:
        raise ValueError(f"{book_id} repeated starts {bad[:5]}")
    for label, value in (("title", title), ("author", author)):
        if value and sum(value in b for b in bodies) >= 2:
            raise ValueError(f"{book_id} repeats {label}")


def pack(raw: list[str]) -> list[str]:
    return [f"{i:03d}、{text}" for i, text in enumerate(raw, 1)]


def write_and_complete(book_id: str, title: str, author: str, raw: list[str]) -> str:
    lines = pack(raw)
    validate(book_id, lines, title, author)
    out = ROOT / "tools" / f".findbook_results_grok_{book_id}.json"
    out.write_text(
        json.dumps({"id": book_id, "highlights": lines}, ensure_ascii=False, indent=2) + "\n",
        encoding="utf-8",
    )
    result = subprocess.run(
        [
            sys.executable,
            str(WRITER),
            "complete",
            "--category-id",
            "02_psychology_growth",
            "--results",
            str(out),
        ],
        cwd=ROOT,
        capture_output=True,
        text=True,
        encoding="utf-8",
        errors="replace",
        check=False,
    )
    output = (result.stdout or "") + (result.stderr or "")
    if result.returncode != 0:
        raise RuntimeError(f"{book_id} writer failed:\n{output}")
    return output.strip()


