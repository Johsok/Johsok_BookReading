def validate(highlights: list[str]) -> None:
    if len(highlights) != 150:
        raise SystemExit(f"count={len(highlights)}")
    if len(BODIES) != 150:
        raise SystemExit(f"bodies={len(BODIES)}")
    short_colon = []
    bodies = []
    for index, line in enumerate(highlights, 1):
        expected = f"{index:03d}、"
        if not line.startswith(expected):
            raise SystemExit(f"number {index}")
        if "\n" in line or "\r" in line or "｜" in line:
            raise SystemExit(f"format {index}")
        body = NUMBER_RE.sub("", line, count=1).strip()
        if len(body) < 12:
            raise SystemExit(f"short {index}: {body}")
        if any(prefix in body for prefix in FORBIDDEN_PREFIXES):
            raise SystemExit(f"forbidden {index}")
        if re.search(r"第\d+章", body):
            raise SystemExit(f"chapter {index}")
        if re.search(r".{1,8}面第\d+步[，,]", body) or re.match(r"^第\d+步[，,]", body):
            raise SystemExit(f"step {index}")
        match = re.match(r"^([^：:]{1,12})[：:]", body)
        if match and not match.group(1).endswith(NATURAL_COLON_SUFFIXES):
            short_colon.append(index)
        bodies.append(body)
    if len(short_colon) >= 3:
        raise SystemExit(f"short colon {short_colon}")
    if len(set(bodies)) != len(bodies):
        dup = [b for b, n in Counter(bodies).items() if n > 1]
        raise SystemExit(f"dup {dup[:3]}")
    starts = Counter(b[:18] for b in bodies if len(b) >= 18)
    worst = starts.most_common(1)[0]
    if worst[1] >= 4:
        raise SystemExit(f"repeat start {worst}")
    for label, value in (("title", TITLE), ("author", AUTHOR)):
        if sum(value in b for b in bodies) >= 1:
            raise SystemExit(f"{label} mentioned")
    start_hits = Counter()
    for b in bodies:
        for token in BAD_STARTS:
            if b.startswith(token):
                start_hits[token] += 1
    if any(n >= 4 for n in start_hits.values()):
        raise SystemExit(f"bad starts {dict(start_hits)}")
    print("local_ok", len(highlights), "worst_start", worst)


def main() -> int:
    highlights = [f"{i:03d}、{body}" for i, body in enumerate(BODIES, 1)]
    validate(highlights)
    payload = {"id": BOOK_ID, "highlights": highlights}
    OUT.write_text(json.dumps(payload, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    print("wrote", OUT)
    return 0


