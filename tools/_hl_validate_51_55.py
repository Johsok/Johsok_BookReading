def main() -> int:
    tools = ROOT / "tools"
    errors: list[str] = []
    for book_id, title, author, bodies in META:
        print(f"{book_id} count={len(bodies)}")
        if len(bodies) != 150:
            errors.append(f"{book_id} count {len(bodies)}")
            continue
        highlights = numbered(bodies)
        try:
            validate_highlights(book_id, highlights, title, author)
        except ValueError as exc:
            errors.append(str(exc))
            continue
        payload = {"id": book_id, "highlights": highlights}
        path = tools / f".findbook_results_grok_{book_id}.json"
        path.write_text(json.dumps(payload, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
        print(f"wrote {path.name}")
    if errors:
        print("ERRORS:")
        for item in errors:
            print(item)
        return 1
    return 0


