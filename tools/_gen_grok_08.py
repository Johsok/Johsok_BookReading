def validate(bodies: list[str]) -> None:
    """Validate highlight bodies against writer rules."""
    if len(bodies) != 150:
        raise SystemExit(f"count={len(bodies)}")
    short_colon = []
    suffixes = ("是", "為", "在於", "說", "問", "提醒", "表示", "指出")
    for i, body in enumerate(bodies, 1):
        if len(body) < 12:
            raise SystemExit(f"short {i} {body}")
        if "｜" in body:
            raise SystemExit(f"bar {i}")
        for prefix in ("本書", "作者指出", "本章", "這一章"):
            if prefix in body:
                raise SystemExit(f"prefix {i}")
        if re.search(r".{1,8}面第\d+步[，,]", body) or re.match(r"^第\d+步[，,]", body):
            raise SystemExit(f"step {i}")
        match = re.match(r"^([^：:]{1,12})[：:]", body)
        if match and not match.group(1).endswith(suffixes):
            short_colon.append((i, match.group(1), body))
        for bad in (
            "以「商業理財」作為",
            "落到具體情境，再用可觀察的結果確認做法是否有效",
            "先界定目標，再把",
        ):
            if bad in body:
                raise SystemExit(f"template {i}")
        if "because" in body or "consumptive" in body:
            raise SystemExit(f"english {i} {body}")
    if len(short_colon) >= 3:
        out = ROOT / "tools" / "_short_colon_08.txt"
        out.write_text("\n".join(f"{a}\t{b}\t{c}" for a, b, c in short_colon), encoding="utf-8")
        raise SystemExit(f"short_colon {len(short_colon)} -> {out}")
    if len(set(bodies)) != 150:
        raise SystemExit("duplicate")
    repeated = Counter(body[:18] for body in bodies if len(body) >= 18)
    if repeated and repeated.most_common(1)[0][1] >= 4:
        raise SystemExit(f"starts {repeated.most_common(5)}")
    if sum(TITLE in body for body in bodies) >= 2:
        raise SystemExit("title repeat")
    if sum(AUTHOR in body for body in bodies) >= 2:
        raise SystemExit("author repeat")


def main() -> None:
    """Write results JSON for the writer."""
    validate(BODIES)
    highlights = [f"{i:03d}、{body}" for i, body in enumerate(BODIES, 1)]
    out = ROOT / "tools" / f".findbook_results_grok_{BOOK_ID}.json"
    out.write_text(
        json.dumps({"id": BOOK_ID, "highlights": highlights}, ensure_ascii=False, indent=2) + "\n",
        encoding="utf-8",
    )
    print(f"wrote {out} count={len(highlights)}")


if __name__ == "__main__":
    main()
