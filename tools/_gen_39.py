NAT = ("是", "為", "在於", "說", "問", "提醒", "表示", "指出")
forbid = ["落到具體情境，再用可觀察的結果確認做法是否有效", "作為判斷線索時", "先界定目標，再把", "先盤點條件，再把", "本書", "作者指出", "本章", "這一章", "｜"]

def validate(bodies):
    if len(set(bodies)) != 150:
        raise SystemExit("dup")
    colon = []
    for i, b in enumerate(bodies, 1):
        if len(b) < 12:
            raise SystemExit(f"short {i} {b}")
        for f in forbid:
            if f in b:
                raise SystemExit(f"forbid {f}")
        m = re.match(r"^([^：:]{1,12})[：:]", b)
        if m and not m.group(1).endswith(NAT):
            colon.append((i, b))
    if len(colon) >= 3:
        raise SystemExit(f"colon {colon}")
    worst = Counter(b[:18] for b in bodies if len(b) >= 18).most_common(1)
    if worst and worst[0][1] >= 4:
        raise SystemExit(f"starts {worst}")
    for label, value in (("title", TITLE), ("author", AUTHOR)):
        if sum(value in b for b in bodies) >= 2:
            raise SystemExit(f"{label} too many")
    print("ok", worst)

