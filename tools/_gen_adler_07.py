def main():
    """Validate and write the results JSON."""
    assert len(BODIES) == 150, len(BODIES)
    opens = [b[:2] for b in BODIES]
    dup_open = {k: v for k, v in Counter(opens).items() if v > 1}
    # Unique openings preferred; allow same 2-char only if rare and content differs.
    # Require unique first 3 chars where possible.
    opens3 = [b[:3] for b in BODIES]
    d3 = {k: v for k, v in Counter(opens3).items() if v > 1}
    if d3:
        for i, b in enumerate(BODIES, 1):
            if opens3.count(b[:3]) > 1:
                print(f"DUP3 {i:03d} {b[:3]} {b}")
        raise SystemExit(f"duplicate openings: {d3}")

    highlights = []
    for i, body in enumerate(BODIES, 1):
        n = len(body)
        assert 25 <= n <= 70, (i, n, body)
        for bad in ("本書", "作者指出", "本章", "｜", "面第"):
            assert bad not in body, (i, bad)
        highlights.append(f"{i:03d}、{body}")

    assert len(set(highlights)) == 150
    out = Path(__file__).with_name(
        ".findbook_results_grok_02_psychology_growth-20260709-07.json"
    )
    out.write_text(
        json.dumps(
            {"id": "02_psychology_growth-20260709-07", "highlights": highlights},
            ensure_ascii=False,
            indent=2,
        )
        + "\n",
        encoding="utf-8",
    )
    lens = [len(b) for b in BODIES]
    print(f"OK 150 {out}")
    print(f"min={min(lens)} max={max(lens)} dup2={dup_open or None}")


if __name__ == "__main__":
    main()
