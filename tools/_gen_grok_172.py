def complete_book(book_id: str, title: str, author: str, bodies: list[str]) -> None:
    if len(bodies) != 150:
        raise SystemExit(f"{book_id} need 150 got {len(bodies)}")
    highlights = [f"{i:03d}、{b}" for i, b in enumerate(bodies, 1)]
    validate_highlights(book_id, highlights, title, author)
    payload = {"id": book_id, "highlights": highlights}
    results = TOOLS / f".findbook_results_grok_{book_id}.json"
    results.write_text(json.dumps(payload, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    proc = subprocess.run(
        [
            sys.executable,
            str(TOOLS / "findbook_writer.py"),
            "complete",
            "--category-id",
            "02_psychology_growth",
            "--results",
            str(results),
        ],
        cwd=str(ROOT),
        capture_output=True,
        text=True,
        encoding="utf-8",
    )
    sys.stdout.write(proc.stdout or "")
    if proc.returncode != 0:
        sys.stderr.write(proc.stderr or "")
        raise SystemExit(proc.returncode)
    book = json.loads(
        (ROOT / "Books" / "02_psychology_growth" / f"{book_id}.json").read_text(encoding="utf-8-sig")
    )
    print(f"confirm\t{book['id']}\t{len(book['chatgptHighlights'])}\t{book.get('highlightsSource')}")


