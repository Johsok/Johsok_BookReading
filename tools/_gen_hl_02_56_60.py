def numbered(bodies: list[str]) -> list[str]:
    return [f"{i:03d}、{body}" for i, body in enumerate(bodies, 1)]


def extra_checks(book_id: str, title: str, author: str, bodies: list[str]) -> None:
    starts = Counter(b[:18] for b in bodies)
    bad = [(s, n) for s, n in starts.items() if n >= 4]
    if bad:
        raise ValueError(f"{book_id} repeated starts: {bad[:8]}")
    if len(set(bodies)) != len(bodies):
        raise ValueError(f"{book_id} duplicate bodies")
    for i, b in enumerate(bodies, 1):
        if len(b) < 12:
            raise ValueError(f"{book_id} #{i} short")
        if "｜" in b or "|" in b or "*" in b or "#" in b:
            raise ValueError(f"{book_id} #{i} markdown/pipe")
        if "本書" in b or "作者指出" in b or "本章" in b or "這一章" in b:
            raise ValueError(f"{book_id} #{i} forbidden prefix")
    if title and sum(title in b for b in bodies) >= 2:
        raise ValueError(f"{book_id} title repeated")
    if author and sum(author in b for b in bodies) >= 2:
        raise ValueError(f"{book_id} author repeated")


def write_one(book_id: str, payload: dict) -> Path:
    bodies = payload["highlights"]
    extra_checks(book_id, payload["title"], payload["author"], bodies)
    lines = numbered(bodies)
    validate_highlights(book_id, lines, payload["title"], payload["author"])
    path = TOOLS / f".findbook_results_grok_{book_id}.json"
    path.write_text(
        json.dumps({"id": book_id, "highlights": lines}, ensure_ascii=False, indent=2) + "\n",
        encoding="utf-8",
    )
    return path


