def validate(bodies):
    if len(bodies) != 150:
        raise SystemExit(f"count {len(bodies)}")
    if len(set(bodies)) != 150:
        raise SystemExit("dup")
    for i, b in enumerate(bodies, 1):
        if len(b) < 12:
            raise SystemExit(f"short {i} {b}")
        for f in forbid:
            if f in b:
                raise SystemExit(f"forbid {i} {f}")
        if re.search(r".{1,8}面第\d+步[，,]", b) or re.match(r"^第\d+步[，,]", b):
            raise SystemExit(f"step {i}")
    colon = []
    for i, b in enumerate(bodies, 1):
        m = re.match(r"^([^：:]{1,12})[：:]", b)
        if m and not m.group(1).endswith(NAT):
            colon.append((i, b))
    if len(colon) >= 3:
        raise SystemExit(f"colon {colon}")
    worst = Counter(b[:18] for b in bodies if len(b) >= 18).most_common(3)
    if worst and worst[0][1] >= 4:
        raise SystemExit(f"starts {worst}")
    for label, value in (("title", TITLE), ("author", AUTHOR)):
        hits = sum(value in b for b in bodies)
        if hits >= 2:
            raise SystemExit(f"{label} hits {hits}")
    print("ok", worst)


