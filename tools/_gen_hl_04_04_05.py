def extra_checks(book_id: str, bodies: list[str], title: str, author: str) -> None:
    """Catch extra style rules beyond the writer validator."""
    if len(bodies) != 150:
        raise SystemExit(f"{book_id} count={len(bodies)}")
    starts = Counter(b[:18] for b in bodies)
    bad_starts = [item for item in starts.items() if item[1] >= 4]
    if bad_starts:
        raise SystemExit(f"{book_id} repeated starts: {bad_starts[:5]}")
    for i, body in enumerate(bodies, 1):
        if "｜" in body:
            raise SystemExit(f"{book_id} #{i} pipe")
        if re.search(r"第[一二三四五六七八九十0-9]+章", body):
            raise SystemExit(f"{book_id} #{i} chapter")
        if any(x in body for x in ("本書", "作者指出", "本章", "這一章")):
            raise SystemExit(f"{book_id} #{i} forbidden prefix")
        if len(body) < 12:
            raise SystemExit(f"{book_id} #{i} short")
    for label, value in (("title", title), ("author", author)):
        if value and sum(value in b for b in bodies) >= 2:
            raise SystemExit(f"{book_id} repeats {label}")


def numbered(bodies: list[str]) -> list[str]:
    return [f"{i:03d}、{body}" for i, body in enumerate(bodies, 1)]


def write_results(book_id: str, highlights: list[str]) -> Path:
    path = ROOT / "tools" / f".findbook_results_grok_{book_id}.json"
    path.write_text(
        json.dumps({"id": book_id, "highlights": highlights}, ensure_ascii=False, indent=2) + "\n",
        encoding="utf-8",
    )
    return path


