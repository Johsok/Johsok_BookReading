def pack(book_id: str, bodies: list[str], title: str, author: str) -> Path:
    if len(bodies) != 150:
        raise SystemExit(f"{book_id} need 150 got {len(bodies)}")
    highlights = [f"{i:03d}、{b}" for i, b in enumerate(bodies, 1)]
    validate_highlights(book_id, highlights, title, author)
    path = ROOT / f".findbook_results_grok_{book_id}.json"
    write_json_atomic(path, {"id": book_id, "highlights": highlights})
    print(f"ok\t{book_id}\t{len(highlights)}\t{highlights[0]}\t{highlights[-1]}\t{path}")
    return path


