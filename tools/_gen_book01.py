from collections import Counter
import re

NATURAL = ("是", "為", "在於", "說", "問", "提醒", "表示", "指出")


def fix_short_colon(body: str) -> str:
    """Replace short-label colons with comma to pass writer validation."""
    match = re.match(r"^([^：:]{1,12})[：:]", body)
    if match and not match.group(1).endswith(NATURAL):
        return re.sub(r"^([^：:]{1,12})[：:]", r"\1，", body, count=1)
    return body


