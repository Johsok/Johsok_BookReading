def numbered(name: str, bodies: list[str]) -> list[str]:
    if len(bodies) != 150:
        raise SystemExit(f"{name} expected 150, got {len(bodies)}")
    return [f"{i:03d}、{body}" for i, body in enumerate(bodies, 1)]


