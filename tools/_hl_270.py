def load_bodies(book_id: str) -> set[str]:
    path = ROOT / "Books" / "02_psychology_growth" / f"{book_id}.json"
    data = json.loads(path.read_text(encoding="utf-8-sig"))
    out = set()
    for line in data.get("chatgptHighlights", []):
        if "、" in str(line):
            out.add(str(line).split("、", 1)[1])
    return out


def main() -> None:
    assert len(BODIES) == 150, len(BODIES)
    highlights = [f"{i:03d}、{body}" for i, body in enumerate(BODIES, 1)]
    validate_highlights(BOOK_ID, highlights, TITLE, AUTHOR)
    for other in (
        "02_psychology_growth-20260716-133",
        "02_psychology_growth-20260716-260",
    ):
        overlap = [b for b in BODIES if b in load_bodies(other)]
        if overlap:
            raise SystemExit(f"overlap with {other}: {overlap[:3]}")
    out = ROOT / "tools" / f".findbook_results_grok_{BOOK_ID}.json"
    out.write_text(
        json.dumps({"id": BOOK_ID, "highlights": highlights}, ensure_ascii=False, indent=2) + "\n",
        encoding="utf-8",
    )
    print(f"wrote {out}")
    cmd = [
        sys.executable,
        str(ROOT / "tools" / "findbook_writer.py"),
        "complete",
        "--category-id",
        "02_psychology_growth",
        "--results",
        str(out),
    ]
    print(subprocess.check_output(cmd, text=True, encoding="utf-8", errors="replace"))


if __name__ == "__main__":
    main()
