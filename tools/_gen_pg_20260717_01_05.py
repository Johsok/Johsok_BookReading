def write_and_complete(book: dict) -> None:
    """Validate, write results JSON, and run findbook_writer complete."""
    highlights = pack(book["points"])
    validate(book["id"], highlights, book["title"], book["author"])
    out = TOOLS / f".findbook_results_grok_{book['id']}.json"
    out.write_text(
        json.dumps({"id": book["id"], "highlights": highlights}, ensure_ascii=False, indent=2),
        encoding="utf-8",
    )
    cmd = [
        sys.executable,
        str(WRITER),
        "complete",
        "--category-id",
        "02_psychology_growth",
        "--results",
        str(out),
    ]
    subprocess.check_call(cmd, cwd=str(ROOT))


def main() -> int:
    """Generate and write all five books."""
    errors = []
    written = []
    for book in BOOKS:
        try:
            n = len(book["points"])
            if n != 150:
                raise ValueError(f"{book['id']} points={n}")
            write_and_complete(book)
            written.append(book["id"])
        except Exception as exc:
            errors.append(f"{book['id']}: {exc}")
            print(f"ERROR\t{book['id']}\t{exc}", file=sys.stderr)
    for book_id in written:
        print(f"written\t{book_id}")
    if errors:
        print("errors:")
        for item in errors:
            print(item)
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())


