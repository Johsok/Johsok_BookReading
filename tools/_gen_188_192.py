def write_and_complete(book_id: str) -> None:
    item = BOOKS[book_id]
    bodies = item["bodies"]
    highlights = [f"{i:03d}、{body}" for i, body in enumerate(bodies, 1)]
    validate_highlights(book_id, highlights, item["title"], item["author"])
    out = ROOT / "tools" / f".findbook_results_grok_{book_id}.json"
    out.write_text(
        json.dumps({"id": book_id, "highlights": highlights}, ensure_ascii=False, indent=2)
        + "\n",
        encoding="utf-8",
    )
    cmd = [
        sys.executable,
        str(ROOT / "tools" / "findbook_writer.py"),
        "complete",
        "--category-id",
        "02_psychology_growth",
        "--results",
        str(out),
    ]
    subprocess.check_call(cmd, cwd=str(ROOT))


def main() -> None:
    target = sys.argv[1] if len(sys.argv) > 1 else "all"
    order = [
        "02_psychology_growth-20260716-188",
        "02_psychology_growth-20260716-189",
        "02_psychology_growth-20260716-190",
        "02_psychology_growth-20260716-191",
        "02_psychology_growth-20260716-192",
    ]
    ids = order if target == "all" else [target]
    for book_id in ids:
        item = BOOKS[book_id]
        print(f"count\t{book_id}\t{len(item['bodies'])}")
        starts = Counter(b[:18] for b in item["bodies"] if len(b) >= 18)
        bad = [(k, v) for k, v in starts.items() if v >= 4]
        if bad:
            raise SystemExit(f"{book_id} repeated starts {bad[:5]}")
        write_and_complete(book_id)


if __name__ == "__main__":
    main()


