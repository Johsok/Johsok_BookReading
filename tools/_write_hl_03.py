NUMBER_RE = re.compile(r"^\d{3}、")
NATURAL_COLON_SUFFIXES = ("是", "為", "在於", "說", "問", "提醒", "表示", "指出")
FORBIDDEN_PREFIXES = ("本書", "作者指出", "本章", "這一章")
BANNED_NAMES = ("工頭堅", "邱德夫", "日威酒徒時光")
SIMP = re.compile(
    r"[发对产国会后时这个来说还开关门问题现点长经规范酿岁号厂业与从达设备实验术为于当种样体着无万干东车马风龙门头]"
)


def validate(highlights: list[str]) -> list[str]:
    errors: list[str] = []
    if len(highlights) != 150:
        errors.append(f"count={len(highlights)} (need 150)")
    short_colon = []
    bodies = []
    for index, line in enumerate(highlights, 1):
        expected = f"{index:03d}、"
        if not line.startswith(expected):
            errors.append(f"{index} bad number")
            continue
        if "\n" in line or "\r" in line or "｜" in line:
            errors.append(f"{index} banned format")
        if any(ch in line for ch in "*#_`"):
            errors.append(f"{index} markdown")
        body = NUMBER_RE.sub("", line, count=1).strip()
        if len(body) < 20:
            errors.append(f"{index} short {len(body)}")
        if any(prefix in body for prefix in FORBIDDEN_PREFIXES):
            errors.append(f"{index} forbidden prefix")
        match = re.match(r"^([^：:]{1,12})[：:]", body)
        if match and not match.group(1).endswith(NATURAL_COLON_SUFFIXES):
            short_colon.append(index)
        simp_hits = SIMP.findall(body)
        if simp_hits:
            errors.append(f"{index} simp {''.join(simp_hits)}")
        bodies.append(body)
    if len(short_colon) >= 3:
        errors.append(f"short-colon x{len(short_colon)}: {short_colon[:10]}")
    if len(set(bodies)) != len(bodies):
        dup = [b[:24] for b, c in Counter(bodies).items() if c > 1]
        errors.append(f"dup bodies {dup[:3]}")
    bad_starts = [(s, n) for s, n in Counter(b[:18] for b in bodies).items() if n >= 4]
    if bad_starts:
        errors.append(f"start18 x4 {bad_starts[:5]}")
    for name in BANNED_NAMES:
        n = sum(name in b for b in bodies)
        if n:
            errors.append(f"{name} x{n}")
    if TITLE and sum(TITLE in b for b in bodies) >= 2:
        errors.append("full title repeated")
    if AUTHOR and sum(AUTHOR in b for b in bodies) >= 2:
        errors.append("full author repeated")
    return errors


