def validate(bodies: list[str]) -> None:
    """Validate highlight bodies against project rules."""
    if len(bodies) != 150:
        raise SystemExit(f"count={len(bodies)}")
    if len(set(bodies)) != 150:
        raise SystemExit("duplicate bodies")
    text = "\n".join(bodies)
    for bad in (
        "以「商業理財」作為",
        "落到具體情境，再用可觀察的結果確認做法是否有效",
        "先界定目標，再把",
    ):
        if bad in text:
            raise SystemExit(f"bad template: {bad}")
    starts = Counter(b[:18] for b in bodies if len(b) >= 18)
    if starts and starts.most_common(1)[0][1] >= 4:
        raise SystemExit(f"repeated starts: {starts.most_common(3)}")
    short = []
    for i, body in enumerate(bodies, 1):
        if len(body) < 12:
            raise SystemExit(f"short {i}")
        if "｜" in body or any(p in body for p in ("本書", "作者指出", "本章", "這一章")):
            raise SystemExit(f"forbidden {i}")
        match = re.match(r"^([^：:]{1,12})[：:]", body)
        if match and not match.group(1).endswith(
            ("中", "上", "下", "內", "外", "時", "前", "後", "間", "來", "去", "到", "起", "止", "年", "月", "日")
        ):
            short.append(i)
    if len(short) >= 3:
        raise SystemExit(f"short colon lines: {short}")
    if sum(TITLE in b for b in bodies) >= 2:
        raise SystemExit("title repeated")
    if sum(AUTHOR in b for b in bodies) >= 2:
        raise SystemExit("author repeated")


def main() -> None:
    """Write results JSON for findbook_writer."""
    validate(BODIES)
    highlights = [f"{i:03d}、{body}" for i, body in enumerate(BODIES, 1)]
    out = Path(__file__).resolve().parent / f".findbook_results_grok_{BOOK_ID}.json"
    out.write_text(
        json.dumps({"id": BOOK_ID, "highlights": highlights}, ensure_ascii=False, indent=2),
        encoding="utf-8",
    )
    print(f"wrote {out} n={len(highlights)}")


if __name__ == "__main__":
    main()
