def pack_validate(book_id: str, title: str, author: str, items: list[str]) -> list[str]:
    if len(items) != 150:
        raise ValueError(f"{book_id} count={len(items)}")
    if len(set(items)) != 150:
        dups = [x for x in items if items.count(x) > 1]
        raise ValueError(f"{book_id} item dups {dups[:3]}")
    highlights = [f"{i:03d}、{t}" for i, t in enumerate(items, 1)]
    short = []
    bodies = []
    for i, line in enumerate(highlights, 1):
        if not line.startswith(f"{i:03d}、"):
            raise ValueError(f"{book_id} num {i}")
        if "｜" in line or "\n" in line or "\r" in line:
            raise ValueError(f"{book_id} fmt {i}")
        body = NUMBER_RE.sub("", line, count=1).strip()
        if len(body) < 12:
            raise ValueError(f"{book_id} short {i} {body}")
        if any(p in body for p in FORBIDDEN):
            raise ValueError(f"{book_id} forbid {i} {body}")
        if re.search(r".{1,8}面第\d+步[，,]", body) or re.match(r"^第\d+步[，,]", body):
            raise ValueError(f"{book_id} step {i}")
        m = re.match(r"^([^：:]{1,12})[：:]", body)
        if m and not m.group(1).endswith(NATURAL):
            short.append((i, body[:40]))
        bodies.append(body)
    if len(short) >= 3:
        raise ValueError(f"{book_id} colon {short}")
    starts = Counter(b[:18] for b in bodies)
    if starts.most_common(1)[0][1] >= 4:
        raise ValueError(f"{book_id} starts {starts.most_common(5)}")
    if sum(title in b for b in bodies) >= 2:
        raise ValueError(f"{book_id} title repeat")
    if sum(author in b for b in bodies) >= 2:
        raise ValueError(f"{book_id} author repeat")
    md = [i for i, b in enumerate(bodies, 1) if any(ch in b for ch in "*#`")]
    if md:
        raise ValueError(f"{book_id} markdown {md[:5]}")
    return highlights


def write_one(book_id: str, title: str, author: str, items: list[str]) -> None:
    highlights = pack_validate(book_id, title, author, items)
    out = TOOLS / f".findbook_results_grok_{book_id}.json"
    out.write_text(
        json.dumps({"id": book_id, "highlights": highlights}, ensure_ascii=False, indent=2)
        + "\n",
        encoding="utf-8",
    )
    proc = subprocess.run(
        [
            sys.executable,
            str(TOOLS / "findbook_writer.py"),
            "complete",
            "--category-id",
            CATEGORY,
            "--results",
            str(out),
        ],
        cwd=str(ROOT),
        capture_output=True,
        text=True,
        encoding="utf-8",
    )
    sys.stdout.write(proc.stdout or "")
    sys.stderr.write(proc.stderr or "")
    if proc.returncode != 0:
        raise SystemExit(f"{book_id} writer failed: {proc.stderr}")
    print(f"DONE\t{book_id}\t{len(highlights)}")


