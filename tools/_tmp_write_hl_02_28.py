def main() -> None:
    assert len(BODIES) == 150, len(BODIES)
    lines = [f"{i:03d}、{body}" for i, body in enumerate(BODIES, 1)]
    issues: list[str] = []
    starts2: dict[str, list[int]] = defaultdict(list)
    starts4: dict[str, list[int]] = defaultdict(list)
    seen: dict[str, int] = {}
    for i, (line, body) in enumerate(zip(lines, BODIES, strict=True), 1):
        n = len(CJK.findall(body))
        if n < 20:
            issues.append(f"short {i} {n} {body}")
        if "：" in body[:12] or ":" in body[:12]:
            prefix = re.split(r"[：:]", body, maxsplit=1)[0]
            if len(CJK.findall(prefix)) <= 12 and not prefix.endswith(
                ("是", "為", "在於", "說", "問", "提醒", "表示", "指出")
            ):
                issues.append(f"colon {i} {prefix}")
        for ban in BANS:
            if ban in line:
                issues.append(f"ban {i} {ban}")
        if TITLE_FRAG in line:
            issues.append(f"title {i}")
        if "｜" in line or "|" in line:
            issues.append(f"pipe {i}")
        if re.search(r".面第\d+步|第\d+步，|.面向，|面向\d+", body):
            issues.append(f"step {i}")
        found = [ch for ch in body if ch in SIMP]
        if found:
            issues.append(f"simp {i} {found} {body[:40]}")
        cjk = "".join(CJK.findall(body))
        starts2[cjk[:2]].append(i)
        starts4[cjk[:4]].append(i)
        if cjk in seen:
            issues.append(f"dupbody {seen[cjk]}-{i}")
        seen[cjk] = i
        if re.search(r"[A-Za-z]", body):
            issues.append(f"eng {i} {body}")
        if "：" in body or ":" in body:
            issues.append(f"anycolon {i}")
    for s, idxs in starts4.items():
        if len(idxs) > 1:
            issues.append(f"dup4 {s} {idxs}")
    dups2 = {s: idxs for s, idxs in starts2.items() if len(idxs) > 1}
    text = "\n".join(lines) + "\n"
    OUT.write_text(text, encoding="utf-8")
    split_n = len(text.splitlines())
    print(f"wrote {OUT} count={len(lines)} splitlines={split_n}")
