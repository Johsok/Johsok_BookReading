def write_and_complete(book_id: str, title: str, author: str, bodies: list[str]) -> None:
    highlights = [f"{i:03d}、{body}" for i, body in enumerate(bodies, 1)]
    validate_highlights(book_id, highlights, title, author)
    results_path = TOOLS / f".findbook_results_grok_{book_id}.json"
    payload = {"id": book_id, "highlights": highlights}
    results_path.write_text(
        json.dumps(payload, ensure_ascii=False, indent=2) + "\n",
        encoding="utf-8",
    )
    subprocess.check_call(
        [
            sys.executable,
            str(TOOLS / "findbook_writer.py"),
            "complete",
            "--category-id",
            "02_psychology_growth",
            "--results",
            str(results_path),
        ],
        cwd=str(ROOT),
    )


def main() -> None:
    target = sys.argv[1] if len(sys.argv) > 1 else ""
    written = []
    for book_id, title, author, bodies in BOOKS:
        if target and book_id != target and not book_id.endswith(target):
            continue
        write_and_complete(book_id, title, author, bodies)
        written.append(book_id)
        print(f"ok\t{book_id}\t{len(bodies)}")
    if not written:
        raise SystemExit("no book matched")


if __name__ == "__main__":
    main()

