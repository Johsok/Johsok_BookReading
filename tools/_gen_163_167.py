def load_book29_bodies() -> list[str]:
    path = ROOT / "Books" / "02_psychology_growth" / "02_psychology_growth-20260716-29.json"
    data = json.loads(path.read_text(encoding="utf-8-sig"))
    bodies = []
    for line in data.get("chatgptHighlights") or []:
        bodies.append(NUMBER_RE.sub("", line, count=1).strip())
    return bodies


def assert_not_copying_29(bodies: list[str]) -> None:
    banned = load_book29_bodies()
    banned_set = set(banned)
    for i, b in enumerate(bodies, 1):
        if b in banned_set:
            raise ValueError(f"163 #{i} exact copy of book 29")
        for other in banned:
            if len(other) >= 16 and other in b:
                raise ValueError(f"163 #{i} contains book 29 sentence")
            if len(b) >= 16 and b in other:
                raise ValueError(f"163 #{i} contained in book 29 sentence")


def longest_common_prefix_issue(bodies: list[str]) -> None:
    starts = Counter(b[:18] for b in bodies if len(b) >= 18)
    bad = [(k, v) for k, v in starts.items() if v >= 4]
    if bad:
        raise ValueError(f"repeated starts: {bad}")


def write_and_complete(book_id: str, bodies: list[str], title: str, author: str) -> str:
    extra_checks(book_id, bodies)
    longest_common_prefix_issue(bodies)
    highlights = numbered(bodies)
    validate_highlights(book_id, highlights, title, author)
    payload = {"id": book_id, "highlights": highlights}
    results = TOOLS / f".findbook_results_grok_{book_id}.json"
    results.write_text(json.dumps(payload, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    proc = subprocess.run(
        [
            sys.executable,
            str(TOOLS / "findbook_writer.py"),
            "complete",
            "--category-id",
            "02_psychology_growth",
            "--results",
            str(results),
        ],
        cwd=str(ROOT),
        capture_output=True,
        text=True,
        encoding="utf-8",
    )
    sys.stdout.write(proc.stdout or "")
    if proc.returncode != 0:
        sys.stderr.write(proc.stderr or "")
        raise SystemExit(proc.returncode)
    saved = json.loads(
        (ROOT / "Books" / "02_psychology_growth" / f"{book_id}.json").read_text(encoding="utf-8-sig")
    )
    n = len(saved.get("chatgptHighlights") or [])
    src = saved.get("highlightsSource")
    line = f"written/{book_id}/{n}/{src}"
    print(line)
    return line


