def numbered(bodies: list[str]) -> list[str]:
    return [f"{i:03d}、{b}" for i, b in enumerate(bodies, 1)]


def extra_checks(book_id: str, bodies: list[str], banned_substrings: list[str] | None = None) -> None:
    if len(bodies) != 150:
        raise ValueError(f"{book_id} need 150 got {len(bodies)}")
    if len(set(bodies)) != 150:
        raise ValueError(f"{book_id} exact duplicate")
    starts = Counter(b[:18] for b in bodies if len(b) >= 18)
    bad = [item for item in starts.items() if item[1] >= 4]
    if bad:
        raise ValueError(f"{book_id} prefix {bad[:3]}")
    for i, b in enumerate(bodies, 1):
        if len(b) < 12:
            raise ValueError(f"{book_id} #{i} too short")
        if any(ch in b for ch in ("｜", "*", "`", "#", "\n")):
            raise ValueError(f"{book_id} #{i} bad char")
    if banned_substrings:
        for i, b in enumerate(bodies, 1):
            for banned in banned_substrings:
                if banned and (b == banned or banned in b):
                    raise ValueError(f"{book_id} #{i} copies banned sentence")


