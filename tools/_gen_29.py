def scrub(body: str) -> str:
    natural = ("是", "為", "在於", "說", "問", "提醒", "表示", "指出")
    m = re.match(r"^([^：:]{1,12})[：:](.*)$", body)
    if m and not m.group(1).endswith(natural):
        return m.group(1) + "，" + m.group(2).lstrip()
    return body


