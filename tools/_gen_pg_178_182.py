NATURAL = ("是", "為", "在於", "說", "問", "提醒", "表示", "指出")


def fix_colons(bodies: list[str]) -> list[str]:
    out = []
    for body in bodies:
        match = re.match(r"^([^：:]{1,12})[：:]", body)
        if match and not match.group(1).endswith(NATURAL):
            body = re.sub(r"^([^：:]{1,12})[：:]", r"\1，", body, count=1)
        out.append(body)
    return out


def assert_quality(book_id: str, title: str, author: str, bodies: list[str]) -> None:
    if len(bodies) != 150:
        raise SystemExit(f"{book_id} count={len(bodies)}")
    if len(set(bodies)) != 150:
        raise SystemExit(f"{book_id} duplicate bodies")
    for index, body in enumerate(bodies, 1):
        if len(body) < 12:
            raise SystemExit(f"{book_id} #{index} too short")
        if "｜" in body or "\n" in body or "*" in body or "`" in body:
            raise SystemExit(f"{book_id} #{index} bad format")
        if any(bad in body for bad in ("本書", "作者指出", "本章", "這一章")):
            raise SystemExit(f"{book_id} #{index} forbidden prefix")
    starts = Counter(body[:18] for body in bodies)
    worst, count = starts.most_common(1)[0]
    if count >= 4:
        raise SystemExit(f"{book_id} start x{count}: {worst}")
    for label, value in (("title", title), ("author", author)):
        if value and sum(value in body for body in bodies) >= 2:
            raise SystemExit(f"{book_id} leaks {label}")


def write_one(book_id: str, title: str, author: str, bodies: list[str]) -> str:
    bodies = fix_colons(bodies)
    assert_quality(book_id, title, author, bodies)
    highlights = [f"{i:03d}、{body}" for i, body in enumerate(bodies, 1)]
    validate_highlights(book_id, highlights, title, author)
    out = TOOLS / f".findbook_results_grok_{book_id}.json"
    out.write_text(
        json.dumps({"id": book_id, "highlights": highlights}, ensure_ascii=False, indent=2) + "\n",
        encoding="utf-8",
    )
    proc = subprocess.run(
        [
            sys.executable,
            str(TOOLS / "findbook_writer.py"),
            "complete",
            "--category-id",
            "02_psychology_growth",
            "--results",
            str(out),
        ],
        cwd=str(ROOT),
        capture_output=True,
        text=True,
        encoding="utf-8",
    )
    text = (proc.stdout or "") + (proc.stderr or "")
    print(text.strip())
    if proc.returncode != 0:
        raise SystemExit(f"{book_id} writer failed: {text}")
    saved = json.loads(
        (ROOT / "Books" / "02_psychology_growth" / f"{book_id}.json").read_text(encoding="utf-8-sig")
    )
    n = len(saved.get("chatgptHighlights") or [])
    src = saved.get("highlightsSource")
    print(f"OK\t{book_id}\t{n}\t{src}")
    return f"written/{book_id}/{n}/{src}"


