def numbered(lines: list[str]) -> list[str]:
    return [f"{index:03d}、{line}" for index, line in enumerate(lines, 1)]


def validate_local(book_id: str, highlights: list[str], title: str, author: str) -> None:
    if len(highlights) != 150:
        raise AssertionError((book_id, "count", len(highlights)))
    short_colon = []
    bodies = []
    for index, line in enumerate(highlights, 1):
        expected = f"{index:03d}、"
        if not line.startswith(expected):
            raise AssertionError((book_id, index, line[:40]))
        if "\n" in line or "\r" in line or "｜" in line:
            raise AssertionError((book_id, index, "bad format"))
        if any(ch in line for ch in "*_`#"):
            raise AssertionError((book_id, index, "markdown"))
        body = NUMBER_RE.sub("", line, count=1).strip()
        if len(body) < 12:
            raise AssertionError((book_id, index, body))
        for prefix in FORBIDDEN:
            if prefix in body:
                raise AssertionError((book_id, index, prefix))
        if re.search(r".{1,8}面第\d+步[，,]", body) or re.match(r"^第\d+步[，,]", body):
            raise AssertionError((book_id, index, "step wording"))
        match = re.match(r"^([^：:]{1,12})[：:]", body)
        if match and not match.group(1).endswith(NATURAL_COLON_SUFFIXES):
            short_colon.append(index)
        bodies.append(body)
    if len(short_colon) >= 3:
        raise AssertionError((book_id, "short colon", short_colon))
    if len(set(bodies)) != 150:
        dup = [item for item, count in Counter(bodies).items() if count > 1]
        raise AssertionError((book_id, "dup", dup[:5]))
    starts = Counter(body[:18] for body in bodies if len(body) >= 18)
    top = starts.most_common(3)
    if top and top[0][1] >= 4:
        raise AssertionError((book_id, "repeat start", top))
    for label, value in (("title", title), ("author", author)):
        if value and sum(value in body for body in bodies) >= 2:
            raise AssertionError(f"{book_id} repeats {label}")


def write_and_complete(book_id: str, lines: list[str], title: str, author: str) -> str:
    highlights = numbered(lines)
    validate_local(book_id, highlights, title, author)
    path = ROOT / "tools" / f".findbook_results_grok_{book_id}.json"
    path.write_text(
        json.dumps({"id": book_id, "highlights": highlights}, ensure_ascii=False, indent=2) + "\n",
        encoding="utf-8",
    )
    cmd = [
        sys.executable,
        str(ROOT / "tools" / "findbook_writer.py"),
        "complete",
        "--category-id",
        "02_psychology_growth",
        "--results",
        str(path),
    ]
    print("RUN", book_id)
    subprocess.run(cmd, cwd=str(ROOT), check=True)
    return book_id


