    only = sys.argv[1:]
    written = []
    failed = []
    all_bodies = []
    for book in BOOKS:
        print("COUNT", book["id"], len(book["lines"]))
        all_bodies.extend(book["lines"])
    overlap = [body for body, count in Counter(all_bodies).items() if count > 1]
