def main() -> None:
    out_dir = ROOT / "tools"
    errors = []
    written = []
    for book_id, title, author, bodies in BOOKS:
        print(f"count {book_id}: {len(bodies)}")
        highlights = numbered(bodies)
        try:
            validate_highlights(book_id, highlights, title, author)
        except ValueError as exc:
            errors.append(str(exc))
            # Extra diagnostics
            starts = Counter(b[:18] for b in bodies if len(b) >= 18)
            dups = [k for k, v in starts.items() if v >= 2]
            print(f"FAIL {book_id}: {exc}")
            if dups:
                print(" repeated starts:", starts.most_common(8))
            short = [i + 1 for i, b in enumerate(bodies) if len(b) < 12]
            if short:
                print(" short:", short)
            continue
        path = out_dir / f".findbook_results_grok_{book_id}.json"
        path.write_text(
            json.dumps({"id": book_id, "highlights": highlights}, ensure_ascii=False, indent=2)
            + "\n",
            encoding="utf-8",
        )
        written.append(str(path))
        print(f"OK {book_id} -> {path.name}")
    if errors:
        raise SystemExit("validation failed:\n" + "\n".join(errors))
    print("all ok", len(written))


if __name__ == "__main__":
    main()
