def validate(bodies: list[str]) -> None:
    """Validate highlight bodies against writer and task rules."""
    forbidden = [
        "本書",
        "作者指出",
        "本章",
        "這一章",
        "｜",
        "以「商業理財」作為",
        "落到具體情境，再用可觀察的結果確認做法是否有效",
        "先界定目標，再把",
    ]
    short_colon_lines = []
    for index, body in enumerate(bodies, 1):
        assert len(body) >= 12, (index, body)
        for token in forbidden:
            assert token not in body, (index, token)
        assert not re.search(r".{1,8}面第\d+步[，,]", body), index
        assert not re.match(r"^第\d+步[，,]", body), index
        match = re.match(r"^([^：:]{1,12})[：:]", body)
        if match and not match.group(1).endswith(NATURAL_COLON_SUFFIXES):
            short_colon_lines.append((index, match.group(1), body[:40]))
    assert len(short_colon_lines) < 3, short_colon_lines
    assert len(set(bodies)) == 150
    starts = Counter(body[:18] for body in bodies if len(body) >= 18)
    assert starts.most_common(1)[0][1] < 4, starts.most_common(5)
    assert sum(TITLE in body for body in bodies) < 2
    assert sum(AUTHOR in body for body in bodies) < 2


def main() -> None:
    """Write results JSON for book 33."""
    validate(BODIES)
    highlights = [f"{index:03d}、{body}" for index, body in enumerate(BODIES, 1)]
    out = ROOT / "tools" / f".findbook_results_grok_{BOOK_ID}.json"
    out.write_text(
        json.dumps({"id": BOOK_ID, "highlights": highlights}, ensure_ascii=False, indent=2),
        encoding="utf-8",
    )
    print(f"wrote {out} count={len(highlights)}")


if __name__ == "__main__":
    main()
