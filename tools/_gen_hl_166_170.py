def numbered(lines: list[str]) -> list[str]:
    if len(lines) != 150:
        raise SystemExit(f"expected 150, got {len(lines)}")
    return [f"{i:03d}、{text}" for i, text in enumerate(lines, 1)]


def main() -> None:
    out_dir = ROOT / "tools"
    for book_id, payload in BOOKS.items():
        highlights = numbered(payload["lines"])
        validate_highlights(book_id, highlights, payload["title"], payload["author"])
        path = out_dir / f".findbook_results_grok_{book_id}.json"
        path.write_text(
            json.dumps({"id": book_id, "highlights": highlights}, ensure_ascii=False, indent=2)
            + "\n",
            encoding="utf-8",
        )
        print(f"ok\t{book_id}\t{path}")


if __name__ == "__main__":
    main()
