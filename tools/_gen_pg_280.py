def main() -> None:
    if len(POINTS) != 150:
        raise SystemExit(f"count={len(POINTS)}")
    for i, body in enumerate(POINTS, 1):
        if SIMP.search(body):
            raise SystemExit(f"simplified {i}: {body} chars={SIMP.findall(body)}")
        if TITLE in body or AUTHOR in body:
            raise SystemExit(f"title/author leak {i}")
    starts = Counter(b[:18] for b in POINTS)
    bad = [(k, v) for k, v in starts.items() if v >= 4]
    if bad:
        raise SystemExit(f"repeated starts {bad}")
    highlights = [f"{i:03d}、{b}" for i, b in enumerate(POINTS, 1)]
    validate_highlights(BOOK_ID, highlights, TITLE, AUTHOR)
    out = TOOLS / f".findbook_results_grok_{BOOK_ID}.json"
    out.write_text(
        json.dumps({"id": BOOK_ID, "highlights": highlights}, ensure_ascii=False, indent=2) + "\n",
        encoding="utf-8",
    )
    proc = subprocess.run(
        [
            sys.executable,
            str(TOOLS / "findbook_writer.py"),
            "complete",
            "--category-id",
            "02_psychology_growth",
            "--results",
            str(out),
        ],
        cwd=str(ROOT),
        capture_output=True,
        text=True,
    )
    print(proc.stdout or proc.stderr)
    if proc.returncode != 0:
        raise SystemExit(proc.returncode)
    saved = json.loads((ROOT / "Books" / "02_psychology_growth" / f"{BOOK_ID}.json").read_text(encoding="utf-8-sig"))
    print(f"OK\t{BOOK_ID}\t{len(saved['chatgptHighlights'])}\t{saved.get('highlightsSource')}")


if __name__ == "__main__":
    main()
