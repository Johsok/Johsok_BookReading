def to_highlights(lines: list[str]) -> list[str]:
    return [f"{i:03d}、{line.strip()}" for i, line in enumerate(lines, 1)]


def main() -> None:
    tools = ROOT / "tools"
    for book in BOOKS:
        lines = [ln.strip() for ln in book["lines"] if ln.strip()]
        print(f"{book['id']} count={len(lines)}")
        if len(lines) != 150:
            counts = Counter(lines)
            dups = [k for k, v in counts.items() if v > 1]
            print("  dups", dups[:10])
            starts = Counter(x[:18] for x in lines)
            print("  start dups", starts.most_common(5))
        hs = to_highlights(lines)
        try:
            validate_highlights(book["id"], hs, book["title"], book["author"])
            print("  validate ok")
        except ValueError as exc:
            print(f"  VALIDATE {exc}")
            starts = Counter(x[:18] for x in lines)
            print("  start dups", [(k, v) for k, v in starts.most_common(8) if v > 1])
            counts = Counter(lines)
            print("  exact dups", [k for k, v in counts.items() if v > 1][:8])
            continue
        out = tools / f".findbook_results_grok_{book['id']}.json"
        out.write_text(
            json.dumps({"id": book["id"], "highlights": hs}, ensure_ascii=False, indent=2)
            + "\n",
            encoding="utf-8",
        )
        print(f"  wrote {out.name}")


if __name__ == "__main__":
    main()
