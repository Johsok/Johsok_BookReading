def numbered(bodies: list[str]) -> list[str]:
    return [f"{i:03d}、{body}" for i, body in enumerate(bodies, 1)]


def write_results(book_id: str, bodies: list[str], title: str, author: str) -> Path:
    highlights = numbered(bodies)
    print(f"count\t{book_id}\t{len(highlights)}")
    validate_highlights(book_id, highlights, title, author)
    path = ROOT / "tools" / f".findbook_results_grok_{book_id}.json"
    write_json_atomic(path, {"id": book_id, "highlights": highlights})
    print(f"validated\t{book_id}\t{len(highlights)}")
    return path


