def pad(base: list[str], extra: list[str], n: int = 150) -> list[str]:
    out = list(base)
    for item in extra:
        if len(out) >= n:
            break
        if item not in out:
            out.append(item)
    if len(out) < n:
        raise SystemExit(f"still short {len(out)}")
    return out[:n]


