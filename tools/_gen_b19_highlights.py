def validate(bodies: list[str]) -> None:
    assert len(set(bodies)) == 150
    short_colon = []
    natural = ("是", "為", "在於", "說", "問", "提醒", "表示", "指出")
    for i, body in enumerate(bodies, 1):
        assert len(body) >= 12, (i, body)
        assert "｜" not in body
        for bad in ("本書", "作者指出", "本章", "這一章", "以「商業理財」作為", "落到具體情境，再用可觀察的結果確認做法是否有效", "先界定目標，再把"):
            assert bad not in body, (i, bad)
        assert not re.search(r".{1,8}面第\d+步[，,]", body)
        assert not re.match(r"^第\d+步[，,]", body)
        m = re.match(r"^([^：:]{1,12})[：:]", body)
        if m and not m.group(1).endswith(natural):
            short_colon.append((i, body))
    assert sum(AUTHOR in b for b in bodies) < 2
    assert sum(TITLE in b for b in bodies) < 2
    for name in AUTHOR.split("、"):
        assert sum(name in b for b in bodies) < 2, name
    assert len(short_colon) < 3, short_colon
    starts = Counter(b[:18] for b in bodies if len(b) >= 18)
    assert starts.most_common(1)[0][1] < 4, starts.most_common(3)


