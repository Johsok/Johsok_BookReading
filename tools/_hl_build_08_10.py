from __future__ import annotations

import json
from pathlib import Path

import re
from collections import Counter

NUMBER_RE = re.compile(r"^\d{3}、")
NATURAL_COLON_SUFFIXES = ("是", "為", "在於", "說", "問", "提醒", "表示", "指出")
FORBIDDEN_PREFIXES = ("本書", "作者指出", "本章", "這一章")


def validate(book_id: str, highlights: list, title: str = "", author: str = "") -> None:
    if not isinstance(highlights, list) or len(highlights) != 150:
        raise ValueError(f"{book_id} 必須剛好 150 點")
    short_colon_lines = []
    bodies = []
    for index, line in enumerate(highlights, 1):
        expected = f"{index:03d}、"
        if not isinstance(line, str) or not line.startswith(expected):
            raise ValueError(f"{book_id} 第 {index} 點編號錯誤")
        if "\n" in line or "\r" in line or "｜" in line:
            raise ValueError(f"{book_id} 第 {index} 點含禁用格式")
        body = NUMBER_RE.sub("", line, count=1).strip()
        if not body:
            raise ValueError(f"{book_id} 第 {index} 點沒有正文")
        if len(body) < 12:
            raise ValueError(f"{book_id} 第 {index} 點正文過短")
        if any(prefix in body for prefix in FORBIDDEN_PREFIXES):
            raise ValueError(f"{book_id} 第 {index} 點含禁用來源前綴")
        if re.search(r"第[一二三四五六七八九十零〇0-9]+章", body):
            raise ValueError(f"{book_id} 第 {index} 點含第X章")
        if re.search(r".{1,8}面第\d+步[，,]", body) or re.match(r"^第\d+步[，,]", body):
            raise ValueError(f"{book_id} 第 {index} 點含面向／步驟贅詞")
        match = re.match(r"^([^：:]{1,12})[：:]", body)
        if match and not match.group(1).endswith(NATURAL_COLON_SUFFIXES):
            short_colon_lines.append(index)
        bodies.append(body)
    if len(short_colon_lines) >= 3:
        raise ValueError(f"{book_id} 有 {len(short_colon_lines)} 點疑似短標籤加冒號: {short_colon_lines[:10]}")
    if len(set(bodies)) != len(bodies):
        raise ValueError(f"{book_id} 含完全重複重點")
    starts = [body[:18] for body in bodies if len(body) >= 18]
    repeated_starts = Counter(starts)
    bad = [(k, v) for k, v in repeated_starts.items() if v >= 4]
    if bad:
        raise ValueError(f"{book_id} 有大量重複固定開頭: {bad[:5]}")
    almost = [(k, v) for k, v in repeated_starts.items() if v >= 3]
    if almost:
        print(f"WARN {book_id} 開頭出現3次: {almost}")
    for label, value in (("書名", title), ("作者", author)):
        normalized = str(value).strip()
        if normalized:
            n = sum(normalized in body for body in bodies)
            if n >= 2:
                raise ValueError(f"{book_id} 正文反覆出現完整{label} x{n}")
            if n:
                print(f"INFO {book_id} {label} 出現 {n} 次")
    print(f"OK {book_id} count={len(highlights)}")
    print(f"  first: {highlights[0]}")
    print(f"  last:  {highlights[-1]}")

ROOT = Path(__file__).resolve().parents[1]
TOOLS = Path(__file__).resolve().parent


def numbered(lines: list[str]) -> list[str]:
    if len(lines) != 150:
        raise ValueError(f"need 150, got {len(lines)}")
    out = []
    for i, text in enumerate(lines, 1):
        body = text.strip()
        out.append(f"{i:03d}、{body}")
    return out


def dump(book_id: str, lines: list[str], title: str, author: str) -> Path:
    highlights = numbered(lines)
    validate(book_id, highlights, title, author)
    path = TOOLS / f".findbook_results_grok_{book_id}.json"
    path.write_text(
        json.dumps({"id": book_id, "highlights": highlights}, ensure_ascii=False, indent=2) + "\n",
        encoding="utf-8",
    )
    print(f"wrote {path}")
    return path


