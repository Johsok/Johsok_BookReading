def main() -> None:
    assert len(BODIES) == 150, len(BODIES)
    highlights = [f"{i:03d}、{body}" for i, body in enumerate(BODIES, 1)]
    validate_highlights(BOOK_ID, highlights, TITLE, AUTHOR)
    avoid = (ROOT / "tools" / "_avoid_191.txt").read_text(encoding="utf-8").splitlines()
    overlap = set(BODIES) & set(avoid)
    if overlap:
        raise SystemExit(f"overlap 191: {overlap}")
    # near-copy: first 18 chars
    a18 = {x[:18] for x in avoid if len(x) >= 18}
    near = [b for b in BODIES if len(b) >= 18 and b[:18] in a18]
    if near:
        raise SystemExit(f"near-start 191: {near[:3]}")
    out = ROOT / "tools" / f".findbook_results_grok_{BOOK_ID}.json"
    out.write_text(
        json.dumps({"id": BOOK_ID, "highlights": highlights}, ensure_ascii=False, indent=2) + "\n",
        encoding="utf-8",
    )
    cmd = [
        sys.executable,
        str(ROOT / "tools" / "findbook_writer.py"),
        "complete",
        "--category-id",
        "02_psychology_growth",
        "--results",
        str(out),
    ]
    print(subprocess.check_output(cmd, text=True, encoding="utf-8", errors="replace"))


if __name__ == "__main__":
    main()
