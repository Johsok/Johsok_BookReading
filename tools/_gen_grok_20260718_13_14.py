def to_lines(bodies: list[str]) -> list[str]:
    if len(bodies) != 150:
        raise SystemExit(f"expected 150, got {len(bodies)}")
    return [f"{i:03d}、{body}" for i, body in enumerate(bodies, 1)]


def write_results(book_id: str, bodies: list[str], title: str, author: str) -> Path:
    lines = to_lines(bodies)
    validate_highlights(book_id, lines, title, author)
    path = ROOT / "tools" / f".findbook_results_grok_{book_id}.json"
    path.write_text(
        json.dumps({"id": book_id, "highlights": lines}, ensure_ascii=False, indent=2) + "\n",
        encoding="utf-8",
    )
    return path


def complete(book_id: str, results_path: Path) -> str:
    proc = subprocess.run(
        [
            sys.executable,
            str(WRITER),
            "complete",
            "--category-id",
            "02_psychology_growth",
            "--results",
            str(results_path),
        ],
        cwd=str(ROOT),
        capture_output=True,
        text=True,
        encoding="utf-8",
    )
    output = (proc.stdout or "") + (proc.stderr or "")
    if proc.returncode != 0:
        raise SystemExit(output or f"complete failed for {book_id}")
    return output.strip()


def main() -> None:
    jobs = [
        (
            "02_psychology_growth-20260718-13",
            "你不睡，貓都知道",
            "Juno주노",
            BOOK_13,
        ),
        (
            "02_psychology_growth-20260718-14",
            "我沒有成為很厲害的大人",
            "5m",
            BOOK_14,
        ),
    ]
    for book_id, title, author, bodies in jobs:
        path = write_results(book_id, bodies, title, author)
        print(complete(book_id, path))


if __name__ == "__main__":
    main()
