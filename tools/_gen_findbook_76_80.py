def pack(book_id: str, bodies: list[str]) -> dict:
    if len(bodies) != 150:
        raise SystemExit(f"{book_id} count={len(bodies)}")
    highlights = [f"{i:03d}、{body}" for i, body in enumerate(bodies, 1)]
    validate_highlights(book_id, highlights)
    return {"id": book_id, "highlights": highlights}


def write_result(payload: dict) -> Path:
    path = ROOT / "tools" / f".findbook_results_grok_{payload['id']}.json"
    path.write_text(json.dumps(payload, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    return path


