def scrub(bodies: list[str]) -> list[str]:
    """Rewrite short-colon labels into commas for writer compliance."""
    out = []
    for body in bodies:
        match = re.match(r"^([^：:]{1,12})[：:](.*)$", body)
        if match and not match.group(1).endswith(NATURAL):
            body = f"{match.group(1)}，{match.group(2)}"
        out.append(body)
    return out


def validate(bodies: list[str]) -> None:
    """Validate against findbook_writer rules."""
    if len(bodies) != 150:
        raise SystemExit(f"count={len(bodies)}")
    if len(set(bodies)) != 150:
        raise SystemExit("dup")
    text = "\n".join(bodies)
    for bad in (
        "以「商業理財」作為",
        "落到具體情境，再用可觀察的結果確認做法是否有效",
        "先界定目標，再把",
    ):
        if bad in text:
            raise SystemExit(bad)
    short = []
    for i, body in enumerate(bodies, 1):
        if len(body) < 12:
            raise SystemExit(f"short {i}")
        if "｜" in body or any(p in body for p in ("本書", "作者指出", "本章", "這一章")):
            raise SystemExit(f"forbid {i}: {body}")
        match = re.match(r"^([^：:]{1,12})[：:]", body)
        if match and not match.group(1).endswith(NATURAL):
            short.append(i)
    if len(short) >= 3:
        raise SystemExit(f"colon {short}")
    starts = Counter(b[:18] for b in bodies if len(b) >= 18)
    if starts.most_common(1)[0][1] >= 4:
        raise SystemExit(starts.most_common(3))
    if sum(TITLE in b for b in bodies) >= 2 or sum(AUTHOR in b for b in bodies) >= 2:
        raise SystemExit("title/author")


