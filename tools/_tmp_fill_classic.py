def garbled(text: str) -> bool:
    if not text:
        return True
    if "\ufffd" in text or "锟斤拷" in text or "ï¿½" in text:
        return True
    if "&#x" in text or "&amp;" in text:
        return True
    return False


def main() -> None:
    existing = s.load_existing_keys(ROOT)
    payload: dict[str, list[dict]] = {cat: [] for cat in CATS}
    seen: dict[str, set[str]] = {cat: set() for cat in CATS}
    for cat, source_name, title, author, prod_id, published in POOL:
        if len(payload[cat]) >= BUFFER:
            continue
        item = {
            "title": title,
            "author": author,
            "sourceUrl": f"https://www.taaze.tw/products/{prod_id}.html",
            "published": published,
            "sourceSite": "讀冊",
            "sourceName": source_name,
        }
        if garbled(title) or garbled(author):
            continue
        key = s._accept_item(item, existing, seen[cat], FROM_DATE, TO_DATE, cat)
        if not key:
            continue
        seen[cat].add(key)
        payload[cat].append(s.to_candidate(item, cat, FROM_DATE, TO_DATE))

    OUT.write_text(json.dumps(payload, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    print("candidates", {k: len(v) for k, v in payload.items()}, flush=True)
    for cat, items in payload.items():
        for i, item in enumerate(items, 1):
            print(f"{cat} {i}. {item['title']} | {item['author']} | {item.get('published')}", flush=True)

    short = [cat for cat in CATS if len(payload[cat]) < QUOTA]
    if short:
        raise SystemExit(f"quota short: { {k: len(payload[k]) for k in short} }")

    results = []
    for cat in CATS:
        committed = []
        for item in payload[cat]:
            if len(committed) >= QUOTA:
                break
            cand = dict(item)
            cand["workId"] = WORK_ID
            result = w.reserve_one(ROOT, cat, cand, FROM_DATE, TO_DATE)
            print(result, flush=True)
            if result.get("status") == "committed":
                committed.append(result)
        if len(committed) != QUOTA:
            raise SystemExit(f"{cat} committed {len(committed)}")
        results.extend(committed)
    print("reserved", [item["id"] for item in results], flush=True)


if __name__ == "__main__":
    main()
