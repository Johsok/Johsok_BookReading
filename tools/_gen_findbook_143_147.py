def validate(book_id: str, title: str, author: str, highlights: list[str]) -> None:
    if len(highlights) != 150:
        raise ValueError(f"{book_id} count {len(highlights)}")
    short_colon = []
    bodies = []
    for index, line in enumerate(highlights, 1):
        expected = f"{index:03d}、"
        if not line.startswith(expected):
            raise ValueError(f"{book_id} #{index} numbering")
        if "\n" in line or "\r" in line or "｜" in line:
            raise ValueError(f"{book_id} #{index} format")
        body = NUMBER_RE.sub("", line, count=1).strip()
        if len(body) < 12:
            raise ValueError(f"{book_id} #{index} short: {body}")
        if any(p in body for p in FORBIDDEN):
            raise ValueError(f"{book_id} #{index} prefix")
        if re.search(r".{1,8}面第\d+步[，,]", body) or re.match(r"^第\d+步[，,]", body):
            raise ValueError(f"{book_id} #{index} step")
        match = re.match(r"^([^：:]{1,12})[：:]", body)
        if match and not match.group(1).endswith(NATURAL):
            short_colon.append(index)
        bodies.append(body)
    if len(short_colon) >= 3:
        raise ValueError(f"{book_id} short-colon {short_colon}")
    if len(set(bodies)) != len(bodies):
        dup = [b for b, n in Counter(bodies).items() if n > 1]
        raise ValueError(f"{book_id} dup {dup[:3]}")
    starts = Counter(b[:18] for b in bodies if len(b) >= 18)
    if starts and starts.most_common(1)[0][1] >= 4:
        raise ValueError(f"{book_id} starts {starts.most_common(5)}")
    for label, value in (("書名", title), ("作者", author)):
        if value and sum(value in b for b in bodies) >= 2:
            raise ValueError(f"{book_id} {label} leaked")


def write_and_complete(book_id: str, title: str, author: str, items: list[str]) -> str:
    highlights = [f"{i:03d}、{t}" for i, t in enumerate(items, 1)]
    validate(book_id, title, author, highlights)
    out = TOOLS / f".findbook_results_grok_{book_id}.json"
    out.write_text(
        json.dumps({"id": book_id, "highlights": highlights}, ensure_ascii=False, indent=2)
        + "\n",
        encoding="utf-8",
    )
    proc = subprocess.run(
        [
            sys.executable,
            str(TOOLS / "findbook_writer.py"),
            "complete",
            "--category-id",
            "02_psychology_growth",
            "--results",
            str(out),
        ],
        cwd=str(ROOT),
        capture_output=True,
        text=True,
        encoding="utf-8",
    )
    sys.stdout.write(proc.stdout or "")
    sys.stderr.write(proc.stderr or "")
    if proc.returncode != 0:
        raise SystemExit(proc.returncode)
    return book_id


