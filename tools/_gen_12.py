from __future__ import annotations
import json, re
from collections import Counter
from pathlib import Path

def validate_and_write(book_id: str, title: str, author: str, bodies: list[str]) -> Path:
    assert len(bodies) == 150, len(bodies)
    natural = ("是", "為", "在於", "說", "問", "提醒", "表示", "指出")
    highlights = [f"{i:03d}、{b}" for i, b in enumerate(bodies, 1)]
    forb = ["落到具體情境，再用可觀察的結果確認做法是否有效","作為判斷線索時","先界定目標，再把","先盤點條件，再把","本書","作者指出","本章","這一章","｜"]
    text = "\n".join(highlights)
    for f in forb:
        assert f not in text, f
    sc = []
    for i, b in enumerate(bodies, 1):
        assert len(b) >= 12, (i, b)
        assert "第" not in b[:4] or not re.match(r"^第\d+步[，,]", b)
        m = re.match(r"^([^：:]{1,12})[：:]", b)
        if m and not m.group(1).endswith(natural):
            sc.append((i, b[:50]))
    assert len(set(bodies)) == 150
    c = Counter(b[:18] for b in bodies)
    assert c.most_common(1)[0][1] < 4, c.most_common(5)
    assert sum(title in b for b in bodies) < 2
    assert sum(author in b for b in bodies) < 2
    assert len(sc) < 3, sc
    # also forbid step pattern
    for i, b in enumerate(bodies, 1):
        if re.search(r".{1,8}面第\d+步[，,]", b) or re.match(r"^第\d+步[，,]", b):
            raise AssertionError(f"step {i}")
    out = Path(r"C:\Users\johso\OneDrive\Desktop\Johsok_BookReading\tools") / f".findbook_results_grok_{book_id}.json"
    out.write_text(json.dumps({"id": book_id, "highlights": highlights}, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    print("ok", book_id, "top", c.most_common(2))
    return out

