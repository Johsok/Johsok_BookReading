def complete_one(book: dict) -> str:
    book_id = book["id"]
    bodies = book["bodies"]
    if len(bodies) != 150:
        raise ValueError(f"{book_id} count={len(bodies)}")
    highlights = pack(bodies)
    validate_highlights(book_id, highlights, book["title"], book["author"])
    out = ROOT / "tools" / f".findbook_results_grok_{book_id}.json"
    payload = {"id": book_id, "highlights": highlights}
    out.write_text(json.dumps(payload, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    cmd = [
        sys.executable,
        str(ROOT / "tools" / "findbook_writer.py"),
        "complete",
        "--category-id",
        "02_psychology_growth",
        "--results",
        str(out),
    ]
    result = subprocess.run(cmd, cwd=ROOT, capture_output=True, text=True, encoding="utf-8")
    text = (result.stdout or "") + (result.stderr or "")
    if result.returncode != 0 or f"written\t{book_id}" not in text:
        raise RuntimeError(text.strip() or "writer failed")
    return book_id


def main() -> int:
    written = []
    errors = []
    for book in BOOKS:
        try:
            book_id = complete_one(book)
            written.append(book_id)
            print(f"written\t{book_id}")
        except Exception as exc:
            errors.append(f"{book['id']}\t{exc}")
            print(f"error\t{book['id']}\t{exc}")
    print(f"ok={len(written)} err={len(errors)}")
    for row in errors:
        print(row)
    return 0 if not errors else 1


