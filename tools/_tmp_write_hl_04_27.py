FORBIDDEN = ("本書", "作者指出", "本章", "這一章", "第X章", "｜", "|")
TITLE_BITS = ("萬病之王", "一部癌症的傳記", "以及我們與它搏鬥", "辛達塔", "穆克吉")
STEP_RE = re.compile(r".面第\d+步|第\d+步，|.面向，|面向\d+")
NUMBER_RE = re.compile(r"^\d{3}、")
PUNCT_RE = re.compile(r"[\s\W_]+", re.UNICODE)
NATURAL_COLON_SUFFIXES = ("是", "為", "在於", "說", "問", "提醒", "表示", "指出")
CJK_RE = re.compile(r"[\u4e00-\u9fff]")


def norm_key(text: str) -> str:
    text = unicodedata.normalize("NFKC", text).casefold()
    return PUNCT_RE.sub("", text)


def main() -> int:
    errors: list[str] = []
    if len(BODIES) != 150:
        errors.append(f"body count {len(BODIES)}")

    lines = [f"{i:03d}、{body}" for i, body in enumerate(BODIES, 1)]
    short_colon: list[int] = []
    keys: list[str] = []
    prefixes = Counter()

    for i, (line, body) in enumerate(zip(lines, BODIES), 1):
        if not line.startswith(f"{i:03d}、"):
            errors.append(f"{i} bad number")
        if "\n" in line or "\r" in line:
            errors.append(f"{i} newline")
        for bad in FORBIDDEN + TITLE_BITS:
            if bad in line:
                errors.append(f"{i} forbidden {bad}")
        if STEP_RE.search(body):
            errors.append(f"{i} step tag")
        if len(body) < 20:
            errors.append(f"{i} short {len(body)}")
        if len(CJK_RE.findall(body)) < 20:
            errors.append(f"{i} cjk {len(CJK_RE.findall(body))}")
        match = re.match(r"^([^：:]{1,12})[：:]", body)
        if match and not match.group(1).endswith(NATURAL_COLON_SUFFIXES):
            short_colon.append(i)
        keys.append(norm_key(body))
        prefixes[body[:4]] += 1

    if len(short_colon) >= 3:
        errors.append(f"short colon {short_colon}")
    dup = [k for k, c in Counter(keys).items() if c > 1]
    if dup:
        errors.append(f"dup keys {len(dup)}")
    heavy = [p for p, c in prefixes.items() if c >= 4]
    if heavy:
        errors.append(f"repeat prefix {heavy}")

    if BOOK04.exists():
        old = json.loads(BOOK04.read_text(encoding="utf-8-sig"))
        old_bodies = [NUMBER_RE.sub("", x, 1) for x in old.get("chatgptHighlights", [])]
        old_keys = {norm_key(x) for x in old_bodies}
        overlap = [i for i, k in enumerate(keys, 1) if k in old_keys]
        if overlap:
            errors.append(f"exact overlap book04 {overlap}")
        old_norms = [norm_key(x) for x in old_bodies]
        near = []
        for i, k in enumerate(keys, 1):
            s_new = set(k[j:j + 6] for j in range(max(0, len(k) - 5)))
            if not s_new:
                continue
            for oldk in old_norms:
                s_old = set(oldk[j:j + 6] for j in range(max(0, len(oldk) - 5)))
                if not s_old:
                    continue
                jacc = len(s_new & s_old) / len(s_new | s_old)
                if jacc >= 0.62:
                    near.append((i, round(jacc, 2)))
                    break
        if near:
            errors.append(f"near book04 {near}")
        report = Path(r"C:\Users\johso\AppData\Local\Temp\hl_04_27_qa.txt")
