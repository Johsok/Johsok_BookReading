def pack(book_id: str, title: str, author: str, bodies: list[str]) -> list[str]:
    if len(bodies) != 150:
        raise SystemExit(f"{book_id} count={len(bodies)}")
    highlights = [f"{i:03d}、{body}" for i, body in enumerate(bodies, 1)]
    validate_highlights(book_id, highlights, title, author)
    return highlights


def dump_and_complete(book_id: str, highlights: list[str]) -> None:
    out = ROOT / "tools" / f".findbook_results_grok_{book_id}.json"
    out.write_text(
        json.dumps({"id": book_id, "highlights": highlights}, ensure_ascii=False, indent=2)
        + "\n",
        encoding="utf-8",
        newline="\n",
    )
    print(f"wrote results {out.name}")


