def main() -> None:
    seen = set()
    uniq = []
    for b in BODIES:
        b = b.replace("冲动", "衝動")
        if "本書" in b or "｜" in b:
            continue
        if b not in seen:
            seen.add(b)
            uniq.append(b)
    bodies = uniq[:150]
    if len(bodies) < 150:
        raise SystemExit(f"only {len(bodies)}")
    short = []
    for i, b in enumerate(bodies, 1):
        if len(b) < 12:
            raise ValueError(f"short {i} {b}")
        m = re.match(r"^([^：:]{1,12})[：:]", b)
        if m and not m.group(1).endswith(("是", "為", "在於", "說", "問", "提醒", "表示", "指出")):
            short.append(i)
    if len(short) >= 3:
        raise ValueError(short)
    if len(set(bodies)) != 150:
        raise ValueError("dup")
    starts = Counter(b[:18] for b in bodies if len(b) >= 18)
    if starts.most_common(1)[0][1] >= 4:
        raise ValueError(starts.most_common(3))
    if sum(TITLE in b for b in bodies) >= 2:
        raise ValueError("title")
    if sum(AUTHOR in b for b in bodies) >= 2:
        raise ValueError("author")
    hs = [f"{i:03d}、{b}" for i, b in enumerate(bodies, 1)]
    out = Path(__file__).with_name(f".findbook_results_grok_{BOOK_ID}.json")
    out.write_text(json.dumps({"id": BOOK_ID, "highlights": hs}, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    print("wrote", out, len(hs))


if __name__ == "__main__":
    main()
