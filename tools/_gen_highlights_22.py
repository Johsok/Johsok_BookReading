def validate(title, author, bodies):
    short_colon = []
    cleaned = []
    for i, body in enumerate(bodies, 1):
        if len(body) < 12: raise ValueError(f"short {i}")
        if "｜" in body or "\n" in body: raise ValueError(f"fmt {i}")
        for p in ("本書", "作者指出", "本章", "這一章"):
            if p in body: raise ValueError(f"prefix {i} {p}")
        for t in ("以「商業理財」作為", "落到具體情境，再用可觀察的結果確認做法是否有效", "先界定目標，再把"):
            if t in body: raise ValueError(f"tmpl {i}")
        if re.search(r".{1,8}面第\d+步[，,]", body) or re.match(r"^第\d+步[，,]", body):
            raise ValueError(f"step {i}")
        m = re.match(r"^([^：:]{1,12})[：:]", body)
        if m and not m.group(1).endswith(("是", "為", "在於", "說", "問", "提醒", "表示", "指出")):
            short_colon.append(i)
        cleaned.append(f"{i:03d}、{body}")
    if len(short_colon) >= 3: raise ValueError(f"colon {short_colon}")
    if len(set(bodies)) != len(bodies): raise ValueError("dup")
    starts = Counter(b[:18] for b in bodies if len(b) >= 18)
    if starts and starts.most_common(1)[0][1] >= 4: raise ValueError(starts.most_common(3))
    for label, value in (("title", title), ("author", author)):
        if value and sum(value in b for b in bodies) >= 2: raise ValueError(label)
    return cleaned

