def numbered(bodies: list[str]) -> list[str]:
    return [f"{i:03d}、{body}" for i, body in enumerate(bodies, 1)]


def local_check(book_id: str, bodies: list[str], title: str, author: str) -> None:
    if len(bodies) != 150:
        raise SystemExit(f"{book_id} count={len(bodies)}")
    starts = Counter(b[:18] for b in bodies if len(b) >= 18)
    bad = [(k, n) for k, n in starts.items() if n >= 4]
    if bad:
        raise SystemExit(f"{book_id} repeated starts: {bad[:8]}")
    validate_highlights(book_id, numbered(bodies), title, author)


