def to_lines(bodies: list[str]) -> list[str]:
    return [f"{i:03d}、{body}" for i, body in enumerate(bodies, 1)]


def precheck(book_id: str, title: str, author: str, bodies: list[str]) -> None:
    if len(bodies) != 150:
        raise SystemExit(f"{book_id} count={len(bodies)}")
    if len(set(bodies)) != len(bodies):
        dupes = [body for body, count in Counter(bodies).items() if count > 1]
        raise SystemExit(f"{book_id} exact dups: {dupes[:3]}")
    starts = Counter(body[:18] for body in bodies if len(body) >= 18)
    bad = [(start, n) for start, n in starts.items() if n >= 4]
    if bad:
        raise SystemExit(f"{book_id} repeated starts: {bad[:8]}")
    short = [i for i, body in enumerate(bodies, 1) if len(body) < 12]
    if short:
        raise SystemExit(f"{book_id} short lines: {short[:8]}")
    for i, body in enumerate(bodies, 1):
        if "｜" in body or "*" in body or "**" in body:
            raise SystemExit(f"{book_id} #{i} forbidden mark")
        if any(x in body for x in ("本書", "作者指出", "本章", "這一章")):
            raise SystemExit(f"{book_id} #{i} forbidden prefix")
    validate_highlights(book_id, to_lines(bodies), title, author)


def complete_one(book_id: str, lines: list[str]) -> None:
    results_path = TOOLS / f".findbook_results_grok_{book_id}.json"
    payload = {"id": book_id, "highlights": lines}
    results_path.write_text(
        json.dumps(payload, ensure_ascii=False, indent=2) + "\n",
        encoding="utf-8",
    )
    cmd = [
        sys.executable,
        str(TOOLS / "findbook_writer.py"),
        "complete",
        "--category-id",
        "02_psychology_growth",
        "--results",
        str(results_path),
    ]
    proc = subprocess.run(cmd, cwd=str(ROOT), capture_output=True, text=True, encoding="utf-8")
    sys.stdout.write(proc.stdout or "")
    if proc.returncode != 0:
        sys.stderr.write(proc.stderr or "")
        raise SystemExit(f"complete failed for {book_id}: {proc.returncode}")
    book_path = ROOT / "Books" / "02_psychology_growth" / f"{book_id}.json"
    book = json.loads(book_path.read_text(encoding="utf-8-sig"))
    if book.get("chatgptStatus") != "complete":
        raise SystemExit(f"{book_id} status not complete")
    if book.get("highlightsSource") != "grok":
        raise SystemExit(f"{book_id} source not grok")
    if len(book.get("chatgptHighlights") or []) != 150:
        raise SystemExit(f"{book_id} saved count wrong")


