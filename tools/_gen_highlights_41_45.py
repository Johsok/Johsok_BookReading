NUMBER_RE = re.compile(r"^\d{3}、")


def numbered(lines: list[str]) -> list[str]:
    out = []
    for i, body in enumerate(lines, 1):
        text = body.strip()
        if text[:4].isdigit() and "、" in text[:5]:
            text = NUMBER_RE.sub("", text, count=1).strip()
        out.append(f"{i:03d}、{text}")
    return out


