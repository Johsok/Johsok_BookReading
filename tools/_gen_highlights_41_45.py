def scrub(lines: list[str]) -> list[str]:
    cleaned = []
    for line in lines:
        line = line.replace("  ", " ").replace("protot", "").replace("vis", "")
        line = line.replace("bell", "").replace("ped", "")
        line = re.sub(r"\s+", "", line) if False else line
        line = re.sub(r" {2,}", "", line)
        line = line.replace("perfect ion", "完美主義")
        cleaned.append(line.strip())
    return cleaned


