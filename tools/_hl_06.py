def numbered() -> list[str]:
    assert len(BODIES) == 150, len(BODIES)
    return [f"{i:03d}、{body}" for i, body in enumerate(BODIES, 1)]


def validate(lines: list[str]) -> tuple[list[str], list[tuple[str, int]], list[str]]:
    errors: list[str] = []
    if len(lines) != 150:
        errors.append(f"count={len(lines)}")
    short_colon = []
    bodies = []
    for i, line in enumerate(lines, 1):
        exp = f"{i:03d}、"
        if not line.startswith(exp):
            errors.append(f"{i} bad number")
            continue
        if any(ch in line for ch in "\n\r｜*`#"):
            errors.append(f"{i} forbidden format")
        body = line[len(exp) :].strip()
        if len(body) < 20:
            errors.append(f"{i} short {len(body)} {body}")
        for w in FORBIDDEN:
            if w in body or w in line:
                errors.append(f"{i} forbidden {w}")
        if TITLE in body:
            errors.append(f"{i} title")
        if AUTHOR in body:
            errors.append(f"{i} author")
        if SIMP_RE.search(body):
            errors.append(f"{i} simplified {SIMP_RE.findall(body)}")
        m = re.match(r"^([^：:]{1,12})[：:]", body)
        if m and not m.group(1).endswith(PUNCT_OK_COLON):
            short_colon.append(i)
        bodies.append(body)
    if len(short_colon) >= 3:
        errors.append(f"short_colon {short_colon}")
    if len(set(bodies)) != len(bodies):
        errors.append("duplicate bodies")
    starts = Counter(b[:18] for b in bodies if len(b) >= 18)
    bad = [(k, v) for k, v in starts.items() if v >= 4]
    if bad:
        errors.append(f"repeat18 {bad}")
    three = [(k, v) for k, v in starts.items() if v == 3]
    return errors, three, bodies


def main() -> None:
    lines = numbered()
    errors, three, bodies = validate(lines)
    payload = {"id": BID, "highlights": lines}
    OUT.write_text(json.dumps(payload, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    print(f"wrote {OUT}")
    print(f"count {len(lines)}")
    print(f"min_len {min(len(b) for b in bodies)} max_len {max(len(b) for b in bodies)}")
    print(f"three_same18 {three}")
    if errors:
        print("FAIL")
        for e in errors:
            print(e)
        raise SystemExit(1)
    print("PASS")


if __name__ == "__main__":
    main()
