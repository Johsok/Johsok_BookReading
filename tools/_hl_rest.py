# -*- coding: utf-8 -*-
from __future__ import annotations

import json
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
WRITER = ROOT / "tools" / "findbook_writer.py"


def numbered(bodies: list[str]) -> list[str]:
    if len(bodies) != 150:
        raise SystemExit(f"expected 150, got {len(bodies)}")
    return [f"{i:03d}、{body}" for i, body in enumerate(bodies, 1)]


def write_and_complete(book_id: str, bodies: list[str]) -> None:
    payload = {"id": book_id, "highlights": numbered(bodies)}
    results = ROOT / "tools" / f".findbook_results_grok_{book_id}.json"
    results.write_text(json.dumps(payload, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    cmd = [
        sys.executable,
        str(WRITER),
        "complete",
        "--category-id",
        "02_psychology_growth",
        "--results",
        str(results),
    ]
    print(f"RUN {book_id}", flush=True)
    completed = subprocess.run(cmd, cwd=str(ROOT), check=False)
    if completed.returncode != 0:
        raise SystemExit(completed.returncode)


