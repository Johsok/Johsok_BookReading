def soften_early_colons(body: str) -> str:
    match = re.match(r"^([^：:]{1,12})([：:])(.*)$", body)
    if match and not match.group(1).endswith(("是", "為", "在於", "說", "問", "提醒", "表示", "指出")):
        return f"{match.group(1)}，{match.group(3)}"
    return body


def check_against_book99(bodies: list[str]) -> list[str]:
    book99 = read_json(ROOT / "Books/02_psychology_growth/02_psychology_growth-20260717-99.json")
    old = {line.split("、", 1)[1] for line in book99.get("chatgptHighlights", []) if "、" in line}
    return [body for body in bodies if body in old]


def lint_english(bodies: list[str]) -> list[tuple[int, str]]:
    import re
    bad = []
    for i, body in enumerate(bodies, 1):
        if re.search(r"[A-Za-z]{3,}", body) and "AI" not in body:
            bad.append((i, body))
    return bad


