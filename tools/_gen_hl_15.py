def main() -> None:
    assert len(BODIES) == 150, len(BODIES)
    nat = ("是", "為", "在於", "說", "問", "提醒", "表示", "指出")
    bad = []
    for i, body in enumerate(BODIES, 1):
        if len(body) < 12:
            raise SystemExit(f"short {i} {body}")
        if "｜" in body:
            raise SystemExit(f"bar {i}")
        for p in (
            "本書",
            "作者指出",
            "本章",
            "這一章",
            "以「商業理財」作為",
            "落到具體情境，再用可觀察的結果確認做法是否有效",
            "先界定目標，再把",
        ):
            if p in body:
                raise SystemExit(f"forbidden {i} {p}")
        m = re.match(r"^([^：:]{1,12})[：:]", body)
        if m and not m.group(1).endswith(nat):
            bad.append((i, body))
    if bad:
        raise SystemExit(f"colon {bad}")
    if len(set(BODIES)) != 150:
        # find dups
        from collections import defaultdict
        d = defaultdict(list)
        for i, b in enumerate(BODIES, 1):
            d[b].append(i)
        dups = {k: v for k, v in d.items() if len(v) > 1}
        raise SystemExit(f"dup {dups}")
    rep = Counter(b[:18] for b in BODIES)
    if rep.most_common(1)[0][1] >= 4:
        raise SystemExit(str(rep.most_common(5)))
    if sum(TITLE in b for b in BODIES) >= 2 or sum(AUTHOR in b for b in BODIES) >= 2:
        raise SystemExit("title/author")
    # also avoid short title fragment spam
    highlights = [f"{i:03d}、{b}" for i, b in enumerate(BODIES, 1)]
    out = ROOT / "tools" / f".findbook_results_grok_{BOOK_ID}.json"
    out.write_text(
        json.dumps({"id": BOOK_ID, "highlights": highlights}, ensure_ascii=False, indent=2)
        + "\n",
        encoding="utf-8",
    )
    print(f"wrote {out} {len(highlights)}")


if __name__ == "__main__":
    main()
