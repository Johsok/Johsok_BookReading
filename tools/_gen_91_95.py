def numbered(bodies: list[str]) -> list[str]:
    return [f"{i:03d}、{b.strip()}" for i, b in enumerate(bodies, 1)]


def extra_checks(book_id: str, title: str, author: str, bodies: list[str]) -> None:
    if len(bodies) != 150:
        raise ValueError(f"{book_id} count {len(bodies)}")
    if len(set(bodies)) != 150:
        dups = [b for b, n in Counter(bodies).items() if n > 1]
        raise ValueError(f"{book_id} dup {dups[:3]}")
    starts = Counter(b[:18] for b in bodies if len(b) >= 18)
    bad = [(k, v) for k, v in starts.items() if v >= 4]
    if bad:
        raise ValueError(f"{book_id} repeated starts {bad[:3]}")
    for i, body in enumerate(bodies, 1):
        if len(body) < 12:
            raise ValueError(f"{book_id} short {i} {body}")
        for p in FORBIDDEN:
            if p in body:
                raise ValueError(f"{book_id} forbidden {i} {p}")
    title_hits = sum(title in b for b in bodies) if title else 0
    author_hits = sum(author in b for b in bodies) if author else 0
    if title_hits >= 2:
        raise ValueError(f"{book_id} title repeated {title_hits}")
    if author_hits >= 2:
        raise ValueError(f"{book_id} author repeated {author_hits}")


def write_and_complete() -> None:
    written = []
    errors = []
    for book in BOOKS:
        bid = book["id"]
        bodies = [b.strip() for b in book["bodies"] if b.strip()]
        try:
            extra_checks(bid, book["title"], book["author"], bodies)
            highlights = numbered(bodies)
            validate_highlights(bid, highlights, book["title"], book["author"])
            if "--check" in sys.argv:
                written.append(bid)
                print(f"ok\t{bid}")
                continue
            out = TOOLS / f".findbook_results_grok_{bid}.json"
            out.write_text(
                json.dumps({"id": bid, "highlights": highlights}, ensure_ascii=False, indent=2) + "\n",
                encoding="utf-8",
            )
            proc = subprocess.run(
                [
                    sys.executable,
                    str(TOOLS / "findbook_writer.py"),
                    "complete",
                    "--category-id",
                    "02_psychology_growth",
                    "--results",
                    str(out),
                ],
                cwd=str(ROOT),
                capture_output=True,
                text=True,
                encoding="utf-8",
            )
            if proc.returncode != 0:
                raise RuntimeError((proc.stdout or "") + "\n" + (proc.stderr or ""))
            written.append(bid)
            print(proc.stdout.strip())
        except Exception as exc:
            errors.append(f"{bid}: {exc}")
            print(f"ERROR {bid}: {exc}")
    print("WRITTEN", written)
    print("ERRORS", errors)


if __name__ == "__main__":
    write_and_complete()
