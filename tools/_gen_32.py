def validate(bodies: list[str]) -> None:
    """Validate highlight bodies against project rules."""
    assert len(bodies) == 150, len(bodies)
    phrases = [
        "落到具體情境，再用可觀察的結果確認做法是否有效",
        "作為判斷線索時",
        "先界定目標，再把",
        "先盤點條件，再把",
    ]
    for phrase in phrases:
        assert all(phrase not in body for body in bodies)
    assert all(len(body) >= 12 for body in bodies)
    assert len(set(bodies)) == 150
    starts = Counter(body[:18] for body in bodies if len(body) >= 18)
    assert starts.most_common(1)[0][1] < 4, starts.most_common(3)
    assert sum(TITLE in body for body in bodies) < 2
    assert sum(AUTHOR in body for body in bodies) < 2
    short_colon = 0
    for body in bodies:
        match = re.match(r"^([^：:]{1,12})[：:]", body)
        if match and not match.group(1).endswith(("是", "為", "在於", "說", "問", "提醒", "表示", "指出")):
            short_colon += 1
    assert short_colon < 3, short_colon


def main() -> None:
    """Write results JSON for the writer."""
    validate(BODIES)
    highlights = [f"{index:03d}、{body}" for index, body in enumerate(BODIES, 1)]
    out = Path(__file__).resolve().parent / f".findbook_results_grok_{BOOK_ID}.json"
    out.write_text(
        json.dumps({"id": BOOK_ID, "highlights": highlights}, ensure_ascii=False, indent=2),
        encoding="utf-8",
    )
    print(f"wrote {out} count={len(highlights)}")


if __name__ == "__main__":
    main()
