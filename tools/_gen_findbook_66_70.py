def numbered(bodies: list[str]) -> list[str]:
    return [f"{i:03d}、{body}" for i, body in enumerate(bodies, 1)]


def main() -> int:
    errors = []
    for book in BOOKS:
        book_id = book["id"]
        n = len(book["bodies"])
        print(f"count\t{book_id}\t{n}")
        if n != 150:
            errors.append(f"{book_id} has {n} bodies, need 150")
            continue
        try:
            highlights = numbered(book["bodies"])
            validate_highlights(book_id, highlights, book["title"], book["author"])
        except ValueError as exc:
            errors.append(str(exc))
            continue
        out = TOOLS / f".findbook_results_grok_{book_id}.json"
        out.write_text(
            json.dumps({"id": book_id, "highlights": highlights}, ensure_ascii=False, indent=2)
            + "\n",
            encoding="utf-8",
        )
        print(f"wrote\t{out.name}")
    if errors:
        print("ERRORS:")
        for item in errors:
            print(item)
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
