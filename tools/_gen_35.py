def validate(bodies: list[str]) -> None:
    """Validate highlight bodies against project rules."""
    fixed = []
    for body in bodies:
        body = body.replace("不 consum 亡者隱私", "不消費亡者隱私")
        body = body.replace("在残酷裡", "在殘酷裡")
        body = body.replace("代号教学现场让尊重与距离并存，是行业隐性训练。", "代號教學現場讓尊重與距離並存，是行業隱性訓練。")
        body = body.replace("第一線曝光白幕，是為看见而不是為了獵奇打卡。", "第一線曝光白幕，是為看見而不是為了獵奇打卡。")
        fixed.append(body)
    assert len(fixed) == 150, len(fixed)
    phrases = [
        "落到具體情境，再用可觀察的結果確認做法是否有效",
        "作為判斷線索時",
        "先界定目標，再把",
        "先盤點條件，再把",
    ]
    for phrase in phrases:
        assert all(phrase not in body for body in fixed)
    assert all(len(body) >= 12 for body in fixed), [b for b in fixed if len(b) < 12]
    assert len(set(fixed)) == 150
    starts = Counter(body[:18] for body in fixed if len(body) >= 18)
    assert starts.most_common(1)[0][1] < 4, starts.most_common(3)
    assert sum(TITLE in body for body in fixed) < 2
    assert sum(AUTHOR in body for body in fixed) < 2
    short_colon = 0
    for body in fixed:
        match = re.match(r"^([^：:]{1,12})[：:]", body)
        if match and not match.group(1).endswith(("是", "為", "在於", "說", "問", "提醒", "表示", "指出")):
            short_colon += 1
    assert short_colon < 3, short_colon
    return fixed


def main() -> None:
    """Write results JSON for the writer."""
    fixed = validate(BODIES)
    highlights = [f"{index:03d}、{body}" for index, body in enumerate(fixed, 1)]
    out = Path(__file__).resolve().parent / f".findbook_results_grok_{BOOK_ID}.json"
    out.write_text(
        json.dumps({"id": BOOK_ID, "highlights": highlights}, ensure_ascii=False, indent=2),
        encoding="utf-8",
    )
    print(f"wrote {out} count={len(highlights)}")


if __name__ == "__main__":
    main()
