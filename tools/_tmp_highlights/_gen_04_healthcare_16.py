OUT = Path(__file__).resolve().parent / f"{BOOK_ID}.json"


def main() -> None:
    if len(BODIES) != 150:
        raise SystemExit(f"count={len(BODIES)}")
    highlights = [f"{i:03d}、{body}" for i, body in enumerate(BODIES, 1)]
    validate_highlights(BOOK_ID, highlights, TITLE, AUTHOR)

    joined = "".join(BODIES)
    for banned in ("本書", "作者指出", "本章", "這一章", "｜", "二手書", "蘇珊．桑塔格", "疾病的隱喻"):
        if banned in joined:
            raise SystemExit(f"banned:{banned}")
    simp_hits = []
    for i, body in enumerate(BODIES, 1):
        hit = sorted(set(body) & SIMP)
        if hit:
            simp_hits.append((i, "".join(hit), body[:40]))
    if simp_hits:
        raise SystemExit(f"simp:{simp_hits[:10]}")
    starts = Counter(b[:18] for b in BODIES)
    top = starts.most_common(5)
    print("top_starts", top)
    print("minlen", min(len(b) for b in BODIES))
    print("author_count", sum(AUTHOR in b for b in BODIES))
    print("title_count", sum(TITLE in b for b in BODIES))

