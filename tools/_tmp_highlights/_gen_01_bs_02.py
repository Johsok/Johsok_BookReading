    errors: list[str] = []
    if len(BODIES) != 150:
        errors.append(f"count={len(BODIES)}")
    if len(set(BODIES)) != len(BODIES):
        errors.append("duplicate bodies")
    starts = Counter(b[:18] for b in BODIES)
    for s, n in starts.most_common():
        if n >= 4:
            errors.append(f"start x{n}: {s}")
    short_colon = []
    for i, b in enumerate(BODIES, 1):
        n = len(b)
        if n < 45 or n > 95:
            errors.append(f"{i:03d} len={n} {b[:40]}")
        if "\n" in b or "\r" in b or "｜" in b or "**" in b:
            errors.append(f"{i:03d} bad format")
        if FORBIDDEN.search(b):
            errors.append(f"{i:03d} forbidden {FORBIDDEN.search(b).group()}")
        hit = sorted(set(b) & SIMP)
        if hit:
            errors.append(f"{i:03d} simp {''.join(hit)}")
        m = COLON_RE.match(b)
        if m and not m.group(1).endswith(NATURAL_COLON_SUFFIXES):
            short_colon.append(i)
        if re.search(r".{1,8}面第\d+步[，,]", b) or re.match(r"^第\d+步[，,]", b):
            errors.append(f"{i:03d} step wording")
        if re.match(r"^(Delta|Gamma|Theta|Vega|IV|TIPS|WAIT|Call|Put|ATM|OTM)\b", b):
            errors.append(f"{i:03d} english label start")
    if len(short_colon) >= 3:
        errors.append(f"short colon {short_colon}")
    joined = "".join(BODIES)
    for w in NEED:
        if w not in joined:
            errors.append(f"missing {w}")
    highlights = [f"{i:03d}、{b}" for i, b in enumerate(BODIES, 1)]
    payload = {"id": BOOK_ID, "highlights": highlights}
