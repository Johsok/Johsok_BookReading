def main() -> None:
    data = json.loads(SRC.read_text(encoding="utf-8"))
    hs = data["highlights"]
    assert len(hs) == 150 == len(ADDS)
    new_hs = []
    for i, (line, add) in enumerate(zip(hs, ADDS), 1):
        prefix = f"{i:03d}、"
        assert line.startswith(prefix)
        body = line[len(prefix) :]
        if body.endswith("。") and add:
            merged = body[:-1] + "，" + add
        else:
            merged = body + add
        n = len(merged)
        if not (45 <= n <= 95):
            raise SystemExit(f"{i} LEN {n} {merged}")
        new_hs.append(prefix + merged)

    bodies = [h.split("、", 1)[1] for h in new_hs]
    if len(set(bodies)) != 150:
        raise SystemExit("duplicate bodies")
    starts = Counter(b[:18] for b in bodies)
    bad18 = [(k, v) for k, v in starts.items() if v >= 4]
    if bad18:
        raise SystemExit(f"start18 {bad18}")
    dang = [i for i, b in enumerate(bodies, 1) if b.startswith("當你")]
    if dang:
        raise SystemExit(f"dangni {dang}")
    simp = set("这们为发从对会开关学经点线国种还现时样体机进应条产长门东车头么无与问说个后启战报历愿爱乐处办让该连达过")
    for i, b in enumerate(bodies, 1):
        hit = sorted(set(b) & simp)
        if hit:
            raise SystemExit(f"simp {i} {hit} {b}")
        if "本書" in b or "作者指出" in b or "本章" in b or "這一章" in b or "｜" in b:
            raise SystemExit(f"forbidden {i}")
        if re.search(r"第\d+章", b):
            raise SystemExit(f"chapter {i}")

    payload = {"id": "02_psychology_growth-20260830-04", "highlights": new_hs}
    validate_highlights(
        payload["id"],
        new_hs,
        "世界上最神奇的24堂課【經典新譯版】（The Master Key System）",
        "查爾斯．哈尼爾",
    )
    OUT.write_text(json.dumps(payload, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    lens = [len(b) for b in bodies]
    print(f"OK n={len(new_hs)} min={min(lens)} max={max(lens)}")
    print("FIRST", new_hs[0])
    print("LAST", new_hs[-1])


if __name__ == "__main__":
    main()
