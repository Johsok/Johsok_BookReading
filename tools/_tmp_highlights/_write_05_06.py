def scrub_placeholders(lines: list[str]) -> list[str]:
    """Catch accidental placeholder tokens left during drafting."""
    bad = ("simultaneous", "sym  ", "ent  ", "扰动", "overlapping  ")
    for i, line in enumerate(lines, 1):
        for token in bad:
            if token in line:
                raise ValueError(f"placeholder {token!r} in line {i}: {line}")
    return lines


