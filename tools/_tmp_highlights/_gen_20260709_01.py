def write_book(spec: dict) -> Path:
    bodies = spec["bodies"]
    if len(bodies) != 150:
        raise SystemExit(f"{spec['id']} bodies={len(bodies)}")
    highlights = [f"{i:03d}、{b}" for i, b in enumerate(bodies, 1)]
    validate_highlights(spec["id"], highlights, spec["title"], spec["author"])
    starts = Counter(b[:18] for b in bodies)
    top = starts.most_common(1)[0]
    if top[1] >= 4:
        raise SystemExit(f"{spec['id']} prefix {top}")
    out = OUT_DIR / f"{spec['id']}.json"
    out.write_text(
        json.dumps({"id": spec["id"], "highlights": highlights}, ensure_ascii=False, indent=2) + "\n",
        encoding="utf-8",
        newline="\n",
    )
    print("ok", spec["id"], len(highlights), "max_start", top)
    print("wrote", out)
    return out


def main() -> int:
    write_book(BOOK1)
    write_book(BOOK2)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
