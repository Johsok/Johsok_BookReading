def pack(items: list[str]) -> list[str]:
    return [f"{i:03d}、{t}" for i, t in enumerate(items, 1)]


def validate(book_id: str, lines: list[str], title: str, author: str) -> None:
    if len(lines) != 150:
        raise ValueError(f"{book_id} count={len(lines)}")
    short_colon = []
    bodies = []
    for i, line in enumerate(lines, 1):
        expected = f"{i:03d}、"
        if not line.startswith(expected):
            raise ValueError(f"{book_id} #{i} numbering")
        if "\n" in line or "\r" in line or "｜" in line:
            raise ValueError(f"{book_id} #{i} forbidden format")
        if any(ch in line for ch in "*#`"):
            raise ValueError(f"{book_id} #{i} markdown")
        body = NUMBER_RE.sub("", line, count=1).strip()
        if len(body) < 12:
            raise ValueError(f"{book_id} #{i} too short: {body}")
        if any(p in body for p in FORBIDDEN):
            raise ValueError(f"{book_id} #{i} forbidden prefix")
        if CHAPTER_RE.search(body):
            raise ValueError(f"{book_id} #{i} chapter ref")
        if STEP_RE.search(body) or re.match(r"^第\d+步[，,]", body):
            raise ValueError(f"{book_id} #{i} step wording")
        match = re.match(r"^([^：:]{1,12})[：:]", body)
        if match and not match.group(1).endswith(NATURAL):
            short_colon.append(i)
        bodies.append(body)
    if len(short_colon) >= 3:
        raise ValueError(f"{book_id} short-colon {short_colon}")
    if len(set(bodies)) != len(bodies):
        raise ValueError(f"{book_id} exact duplicates")
    starts = Counter(b[:18] for b in bodies if len(b) >= 18)
    bad = [(k, v) for k, v in starts.items() if v >= 4]
    if bad:
        raise ValueError(f"{book_id} repeated starts {bad[:5]}")
    for label, value in (("title", title), ("author", author)):
        if value and sum(value in b for b in bodies) >= 2:
            raise ValueError(f"{book_id} repeats {label}")


def extra_feynman_checks(bodies: list[str]) -> None:
    full = sum("理查．費曼" in b for b in bodies)
    if full >= 2:
        raise ValueError(f"Feynman full name x{full}")
    fee_starts = sum(b.startswith("費曼") for b in bodies)
    if fee_starts >= 4:
        raise ValueError(f"starts with 費曼 x{fee_starts}")
    banned = ("挑戰者", "O環", "O-ring", "橡皮環", "固態火箭")
    for i, b in enumerate(bodies, 1):
        if any(x in b for x in banned):
            raise ValueError(f"Feynman Challenger leak #{i}")


def extra_lane_checks(bodies: list[str]) -> None:
    wrapper = sum(b.startswith("十大關鍵") or "十大關鍵之一" in b for b in bodies)
    if wrapper:
        raise ValueError("Lane used 十大關鍵 wrapper")


def write_one(book_id: str, items: list[str], title: str, author: str) -> None:
    if len(items) != 150:
        raise ValueError(f"{book_id} raw count={len(items)}")
    lines = pack(items)
    validate(book_id, lines, title, author)
    bodies = [NUMBER_RE.sub("", ln, count=1) for ln in lines]
    if book_id.endswith("-09"):
        extra_feynman_checks(bodies)
    if book_id.endswith("-10"):
        extra_lane_checks(bodies)
    out = OUT / f"{book_id}.json"
    out.write_text(
        json.dumps({"id": book_id, "highlights": lines}, ensure_ascii=False, indent=2)
        + "\n",
        encoding="utf-8",
    )
    print(f"{out} {len(lines)}")


