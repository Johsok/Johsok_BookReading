def extra_check(book_id: str, title: str, author: str, bodies: list[str]) -> None:
    if len(bodies) != 150:
        raise ValueError(f"{book_id} count={len(bodies)}")
    if len(set(bodies)) != 150:
        raise ValueError(f"{book_id} duplicate bodies")
    starts = Counter(b[:18] for b in bodies if len(b) >= 18)
    worst = starts.most_common(1)[0]
    if worst[1] >= 4:
        raise ValueError(f"{book_id} repeated start {worst}")
    for i, body in enumerate(bodies, 1):
        if len(body) < 12:
            raise ValueError(f"{book_id} #{i} short")
        for token in FORBIDDEN:
            if token in body:
                raise ValueError(f"{book_id} #{i} forbidden {token}")
        if any(ch.isascii() and ch.isalpha() for ch in body):
            raise ValueError(f"{book_id} #{i} leftover english")
        for banned in (title, author) + TITLES_AUTHORS:
            if banned and banned in body:
                raise ValueError(f"{book_id} #{i} contains {banned}")


def main() -> None:
    results_dir = TOOLS
    written_files: list[Path] = []
    for book_id, title, author, bodies in BOOKS:
        extra_check(book_id, title, author, bodies)
        highlights = numbered(bodies)
        validate_highlights(book_id, highlights, title, author)
        out = results_dir / f".findbook_results_grok_{book_id}.json"
        out.write_text(
            json.dumps({"id": book_id, "highlights": highlights}, ensure_ascii=False, indent=2)
            + "\n",
            encoding="utf-8",
        )
        written_files.append(out)
        print(f"wrote {out.name}")

    writer = TOOLS / "findbook_writer.py"
    errors: list[str] = []
    written_ids: list[str] = []
    for path in written_files:
        proc = subprocess.run(
            [
                sys.executable,
                str(writer),
                "complete",
                "--category-id",
                "02_psychology_growth",
                "--results",
                str(path),
            ],
            cwd=str(ROOT),
            capture_output=True,
            text=True,
            encoding="utf-8",
        )
        text = (proc.stdout or "") + (proc.stderr or "")
        print(text.strip())
        if proc.returncode != 0:
            errors.append(text.strip() or f"exit {proc.returncode} for {path.name}")
        else:
            for line in (proc.stdout or "").splitlines():
                if line.startswith("written\t"):
                    written_ids.append(line.split("\t", 1)[1])
    if errors:
        raise SystemExit("\n".join(errors))
    print("OK " + ",".join(written_ids))


if __name__ == "__main__":
    main()
