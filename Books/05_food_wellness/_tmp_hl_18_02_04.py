def numbered(sentences):
    assert len(sentences) == 150, len(sentences)
    assert len(set(sentences)) == 150
    forbidden = ("本書", "作者指出", "本章")
    for i, s in enumerate(sentences, 1):
        for w in forbidden:
            if w in s:
                raise SystemExit(f"forbidden {w} in {i}: {s}")
        if "simultaneous" in s or " sucré" in s:
            raise SystemExit(f"latin leftover {i}: {s}")
    return [f"{i:03d}、{s}" for i, s in enumerate(sentences, 1)]


