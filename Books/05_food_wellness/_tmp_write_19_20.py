def numbered(items, tag):
    assert len(items) == 150, (tag, len(items))
    out = []
    for i, t in enumerate(items, 1):
        s = t.strip()
        assert "｜" not in s
        assert "本書" not in s
        assert "作者指出" not in s
        out.append(f"{i:03d}、{s}")
    from collections import Counter
    opens = [x.split("、", 1)[1][:3] for x in out]
    dups = [k for k, v in Counter(opens).items() if v > 1]
    if dups:
        lines = [tag]
        for x in out:
            o = x.split("、", 1)[1][:3]
            if o in dups:
                lines.append(x[:80])
        Path(r"C:\Users\johso\OneDrive\Desktop\Johsok_BookReading\Books\05_food_wellness\_dup.txt").write_text("\n".join(lines), encoding="utf-8")
        raise AssertionError("dup3")
    return out


