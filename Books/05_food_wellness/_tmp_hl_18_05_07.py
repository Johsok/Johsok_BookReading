def _clean(items):
    out = []
    for s in items:
        t = s.replace(" simultaneously ", "同時").replace(" sucré  pulldown ", "甜味拉").replace(" hinter ", "")
        t = t.replace(" quant ", "需")
        t = " ".join(t.split())
        out.append(t)
    return out


def numbered(items, name=""):
    print(name, "raw", len(items))
    return _numbered_impl(items)


def _numbered_impl(items):
    items = _clean(items)
    if len(items) != 150:
        raise SystemExit(f"expected 150 got {len(items)}")
    rows = []
    for i, text in enumerate(items, 1):
        row = f"{i:03d}、{text}"
        if not row.endswith("。"):
            raise SystemExit(f"not complete sentence: {row[:40]}")
        for bad in FORBIDDEN:
            if bad in row:
                raise SystemExit(f"forbidden {bad}: {row[:50]}")
        rows.append(row)
    if len(set(rows)) != 150:
        raise SystemExit("duplicate rows")
    bodies = [PREFIX.sub("", r) for r in rows]
    if len(set(bodies)) != 150:
        raise SystemExit("duplicate bodies")
    starts = [b[:6] for b in bodies]
    if len(set(starts)) < 80:
        raise SystemExit(f"too many similar openings {len(set(starts))}")
    return rows


