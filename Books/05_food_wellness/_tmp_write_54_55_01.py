def numbered(items):
    assert len(items) == 150, len(items)
    out = [f"{i:03d}、{t}" for i, t in enumerate(items, 1)]
    bodies = [t for t in items]
    if len(set(bodies)) != 150:
        raise SystemExit(f"duplicate bodies: {len(set(bodies))}")
    banned = ["本書", "作者指出", "本章"]
    for t in items:
        for b in banned:
            if b in t:
                raise SystemExit(f"banned {b}: {t}")
    return out


