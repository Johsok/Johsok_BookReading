def first_chars(s, n=4):
    return s[:n]


def validate(name, texts):
    assert len(texts) == 150, (name, len(texts))
    opens = [first_chars(t, 2) for t in texts]
    dup = {}
    for i, o in enumerate(opens, 1):
        dup.setdefault(o, []).append(i)
    dups = {k: v for k, v in dup.items() if len(v) > 1}
    banned = []
    for i, t in enumerate(texts, 1):
        if "本書" in t or "作者指出" in t or "｜" in t or "|" in t:
            banned.append(i)
        if "、" in t[:2]:
            banned.append(("sep", i))
    # unique full text
    if len(set(texts)) != 150:
        from collections import Counter
        c = Counter(texts)
        raise SystemExit(f"{name} duplicate texts: {[k for k,v in c.items() if v>1]}")
    if dups:
        raise SystemExit(f"{name} duplicate openings: {dups}")
    if banned:
        raise SystemExit(f"{name} banned: {banned}")
    print(name, "OK", len(texts), "unique openings", len(set(opens)))


