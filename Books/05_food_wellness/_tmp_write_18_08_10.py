def nfkc(s):
    import unicodedata
    return unicodedata.normalize("NFKC", s)


def validate(name, arr):
    assert len(arr) == 150, (name, len(arr))
    uniq = len(set(arr))
    assert uniq == 150, (name, uniq)
    for i, line in enumerate(arr, 1):
        assert line.startswith(f"{i:03d}、"), (name, i, line[:20])
        body = line[4:]
        for bad in ("本書", "作者指出", "本章"):
            assert bad not in body, (name, i, bad)
        assert body, (name, i)
    # catch accidental English leftovers except allowed terms
    return len(arr), uniq, arr[0], arr[-1]


def write_book(filename, highlights):
    path = ROOT / filename
    data = json.loads(path.read_text(encoding="utf-8"))
    data["chatgptHighlights"] = highlights
    data["chatgptStatus"] = "complete"
    data["highlightsSource"] = "grok"
    data["highlightsCapturedAt"] = STAMP
    data["updatedAt"] = UPDATED
    path.write_text(json.dumps(data, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    return path


