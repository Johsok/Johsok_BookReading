def validate_items(book_id: str, items: list[str], title: str, author: str) -> list[str]:
    if len(items) != 150:
        raise SystemExit(f"{book_id} need 150, got {len(items)}")
    bodies: list[str] = []
    numbered: list[str] = []
    short_colon = []
    for i, raw in enumerate(items, 1):
        t = raw.strip()
        if t.startswith(f"{i:03d}、"):
            t = t.split("、", 1)[1].strip()
        if not t:
            raise SystemExit(f"{book_id} empty {i}")
        if len(t) < 12:
            raise SystemExit(f"{book_id} short {i} {t}")
        if "\n" in t or "\r" in t:
            raise SystemExit(f"{book_id} newline {i}")
        for b in BANNED:
            if b in t:
                raise SystemExit(f"{book_id} banned {b!r} in {i}")
        if STEP_RE.search(t) or re.match(r"^第\d+步[，,]", t):
            raise SystemExit(f"{book_id} step phrasing {i}")
        if t.startswith("標籤："):
            raise SystemExit(f"{book_id} label prefix {i}")
        if "：" in t[:10] or ":" in t[:10]:
            raise SystemExit(f"{book_id} colon in first 10 chars {i}")
        m = SHORT_COLON_RE.match(t)
        if m and not m.group(1).endswith(NATURAL_COLON_SUFFIXES):
            short_colon.append(i)
        bodies.append(t)
        numbered.append(f"{i:03d}、{t}")
    if len(short_colon) >= 3:
        raise SystemExit(f"{book_id} short-colon labels {short_colon[:8]}")
    if len(set(bodies)) != 150:
        seen: dict[str, int] = {}
        for i, t in enumerate(bodies, 1):
            if t in seen:
                raise SystemExit(f"{book_id} duplicate {seen[t]} {i}")
            seen[t] = i
    prefixes = [t[:18] for t in bodies]
    if len(set(prefixes)) != 150:
        c = Counter(prefixes)
        clash = [(p, n) for p, n in c.items() if n > 1]
        raise SystemExit(f"{book_id} prefix18 clash {clash[:6]}")
    for label, value in (("title", title), ("author", author)):
        normalized = str(value).strip()
        if normalized and sum(normalized in t for t in bodies) >= 2:
            raise SystemExit(f"{book_id} repeats full {label}")
    return numbered


def patch(filename: str, items: list[str], summary: str) -> None:
    path = ROOT / filename
    data = json.loads(path.read_text(encoding="utf-8-sig"))
    numbered = validate_items(data.get("id", filename), items, data.get("title", ""), data.get("author", ""))
    data["chatgptHighlights"] = numbered
    data["chatgptStatus"] = "complete"
    data["highlightsSource"] = "grok"
    data["highlightsCapturedAt"] = STAMP
    data["updatedAt"] = UPDATED
    data["summary"] = summary
    tmp = path.with_suffix(".json.tmp")
    tmp.write_text(json.dumps(data, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    tmp.replace(path)
    saved = json.loads(path.read_text(encoding="utf-8-sig"))
    validate_items(saved["id"], saved["chatgptHighlights"], saved.get("title", ""), saved.get("author", ""))
    if saved.get("chatgptStatus") != "complete" or saved.get("highlightsSource") != "grok":
        raise SystemExit(f"{filename} post-write status mismatch")
    print(f"OK {filename} n=150 stamp={saved['highlightsCapturedAt']}")


