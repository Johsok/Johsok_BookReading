def numbered(items):
    errs = []
    if len(items) != 150:
        errs.append(f"need 150, got {len(items)}")
    seen = set()
    for i, t in enumerate(items, 1):
        n = len(t)
        if n < 22 or n > 58:
            errs.append(f"len {n} #{i}: {t}")
        if "：" in t or ":" in t:
            errs.append(f"colon #{i}: {t}")
        if t in seen:
            errs.append(f"duplicate #{i}: {t}")
        seen.add(t)
        for b in BANNED:
            if b in t:
                errs.append(f"banned {b} #{i}")
    if errs:
        raise SystemExit("\n".join(errs))
    return [f"{i:03d}、{t}" for i, t in enumerate(items, 1)]


def patch(filename, items, summary):
    path = ROOT / filename
    data = json.loads(path.read_text(encoding="utf-8"))
    keep_keys = set(data.keys())
    data["chatgptHighlights"] = numbered(items)
    data["chatgptStatus"] = "complete"
    data["highlightsSource"] = "grok"
    data["highlightsCapturedAt"] = STAMP
    data["updatedAt"] = UPDATED
    data["summary"] = summary
    if set(data.keys()) != keep_keys:
        raise SystemExit(f"keys changed in {filename}")
    tmp = path.with_suffix(".json.tmp")
    tmp.write_text(json.dumps(data, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    tmp.replace(path)
    print(f"OK {filename} n={len(data['chatgptHighlights'])} captured={STAMP}")
    print(f"SUMMARY {summary}")


