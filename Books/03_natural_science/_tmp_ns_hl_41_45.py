def validate(items, name):
    if len(items) != 150:
        raise SystemExit(f"{name}: need 150, got {len(items)}")
    if len(set(items)) != 150:
        seen = {}
        for i, t in enumerate(items, 1):
            if t in seen:
                raise SystemExit(f"{name}: duplicate {seen[t]} and {i}")
            seen[t] = i
    prefixes = {}
    for i, t in enumerate(items, 1):
        if len(t) < 12:
            raise SystemExit(f"{name}: short {i} len={len(t)} {t}")
        head10 = t[:10]
        if "：" in head10 or ":" in head10:
            raise SystemExit(f"{name}: colon in first 10 chars at {i}: {t}")
        if t.startswith(("重點：", "摘要：", "結論：", "注意：", "提示：")):
            raise SystemExit(f"{name}: label colon at {i}")
        for b in BANNED:
            if b in t:
                raise SystemExit(f"{name}: banned {b!r} at {i}")
        if STEP_RE.search(t):
            raise SystemExit(f"{name}: step wording at {i}: {t}")
        p = t[:18]
        if p in prefixes:
            raise SystemExit(f"{name}: prefix18 clash {prefixes[p]} and {i}: {p}")
        prefixes[p] = i
    return [f"{i:03d}、{t}" for i, t in enumerate(items, 1)]


