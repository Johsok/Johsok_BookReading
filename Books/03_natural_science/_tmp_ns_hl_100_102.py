def _check(name, payload):
    items = payload["items"]
    print(f"{name}: {len(items)}")
    if len(items) != 150:
        raise SystemExit(f"{name} expected 150, got {len(items)}")
    seen = set()
    heads = set()
    for i, t in enumerate(items, 1):
        if t in seen:
            raise SystemExit(f"{name} duplicate at {i}: {t}")
        seen.add(t)
        h = t[:18]
        if h in heads:
            raise SystemExit(f"{name} duplicate prefix at {i}: {h}")
        heads.add(h)
        for w in ("本書", "作者指出", "本章", "第X章", "｜"):
            if w in t:
                raise SystemExit(f"{name} {i} forbidden {w}")


