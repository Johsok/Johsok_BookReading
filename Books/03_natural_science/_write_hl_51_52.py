def numbered(items):
    seen = {}
    out = []
    for i, t in enumerate(items, 1):
        t = t.strip()
        if not t:
            raise SystemExit(f"empty {i}")
        if len(t) < 12:
            raise SystemExit(f"short {i} {len(t)} {t}")
        if t in seen:
            raise SystemExit(f"dup {seen[t]} {i} {t}")
        seen[t] = i
        for b in BANNED:
            if b in t:
                raise SystemExit(f"banned {b!r} in {i}: {t}")
        out.append(f"{i:03d}、{t}")
    if len(out) != 150:
        raise SystemExit(f"count {len(out)}")
    if not out[0].startswith("001、"):
        raise SystemExit("first")
    if not out[-1].startswith("150、"):
        raise SystemExit("last")
    return out


def atomic_write(path, data):
    tmp = path.with_suffix(path.suffix + ".tmp")
    text = json.dumps(data, ensure_ascii=False, indent=2) + "\n"
    tmp.write_text(text, encoding="utf-8")
    tmp.replace(path)


