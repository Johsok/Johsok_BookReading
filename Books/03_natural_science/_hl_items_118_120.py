def _han_count(s: str) -> int:
    return sum(1 for ch in s if "\u4e00" <= ch <= "\u9fff")


def _check_book(name, items):
    if len(items) != 150:
        raise SystemExit(f"{name}: count={len(items)}")
    if len(set(items)) != 150:
        raise SystemExit(f"{name}: duplicate strings")
    seen = set()
    for i, t in enumerate(items, 1):
        if t[0].isdigit():
            raise SystemExit(f"{name} {i:03d} starts with digit")
        for w in ("本書", "作者指出", "本章", "這一章", "｜"):
            if w in t:
                raise SystemExit(f"{name} {i:03d} forbidden {w}")
        n = _han_count(t)
        if n < 28 or n > 55:
            raise SystemExit(f"{name} {i:03d} han={n} {t}")
        p = t[:18]
        if p in seen:
            raise SystemExit(f"{name} {i:03d} dup first18 {p}")
        seen.add(p)


