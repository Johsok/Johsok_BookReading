def _check(tag, summary, items):
    """Validate highlight payload before printing lengths."""
    forbidden = ("本書", "作者指出", "本章", "這一章", "｜")
    if not summary or "本書" in summary:
        raise SystemExit(f"{tag} bad summary")
    if len(items) != 150:
        raise SystemExit(f"{tag} need 150, got {len(items)}")
    seen = set()
    opens = set()
    for i, t in enumerate(items, 1):
        if t in seen:
            raise SystemExit(f"{tag} duplicate {i}: {t}")
        seen.add(t)
        if t[0].isdigit():
            raise SystemExit(f"{tag} numbered start {i}")
        op = t[:18]
        if op in opens:
            raise SystemExit(f"{tag} dup first18 at {i}: {op}")
        opens.add(op)
        n = len(t)
        if n < 28 or n > 55:
            raise SystemExit(f"{tag} {i:03d} len {n}: {t}")
        for w in forbidden:
            if w in t:
                raise SystemExit(f"{tag} {i:03d} forbidden {w}")
        if "實作面第" in t or ("第" in t[:6] and "步" in t[:12]):
            raise SystemExit(f"{tag} {i:03d} step phrasing")


