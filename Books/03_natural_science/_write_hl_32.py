FORBIDDEN = [
    "本書",
    "作者指出",
    "本章",
    "這一章",
    "｜",
    "第1步",
    "第2步",
    "第3步",
]


def body_ok(s: str) -> str | None:
    if len(s) < 12:
        return "short"
    for w in FORBIDDEN:
        if w in s:
            return f"forbidden:{w}"
    if re.search(r"第\d+步", s) or re.search(r".面第\d+步", s):
        return "step"
    if "蘋果才沒有砸在牛頓頭上" in s:
        return "full-title"
    if "安托萬" in s or "侯盧" in s or "Houlou" in s:
        return "author"
    if "：" in s or ":" in s:
        return "colon"
    return None


