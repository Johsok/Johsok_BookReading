def cjk_prefix(s: str, n: int = 8) -> str:
    chars = re.findall(r"[\u4e00-\u9fff]", s)
    return "".join(chars[:n])


def pad_to_len(s: str, idx: int) -> str:
    s = s.rstrip()
    if not s.endswith(("。", "！", "？")):
        s += "。"
    pads = [
        "，實作時再微調即可。",
        "，多做幾次就熟練。",
        "，記下成功比例最穩。",
        "，失敗經驗同樣寶貴。",
        "，口味可依家人調整。",
    ]
    n = 0
    while len(s) < 25 and n < 6:
        s = s[:-1] + pads[(idx + n) % len(pads)]
        n += 1
    if len(s) > 55:
        s = s[:54].rstrip("，、； ") + "。"
    return s


def validate(name: str, items: list[str]) -> None:
    if len(items) != 150:
        raise SystemExit(f"{name}: count {len(items)}")
    if len(set(items)) != 150:
        dups = [x for x, c in Counter(items).items() if c > 1]
        raise SystemExit(f"{name}: dups {dups[:3]}")
    for i, t in enumerate(items, 1):
        for b in BANNED:
            if b in t:
                raise SystemExit(f"{name} #{i}: banned {b}")
        if COLON_RE.search(t):
            raise SystemExit(f"{name} #{i}: colon")
        if re.match(r"^\d{3}、", t):
            raise SystemExit(f"{name} #{i}: numbered")
        if not (25 <= len(t) <= 55):
            raise SystemExit(f"{name} #{i}: len {len(t)} {t}")
    pref = Counter(cjk_prefix(t) for t in items if cjk_prefix(t))
    bad = [(k, v) for k, v in pref.items() if v >= 4]
    if bad:
        raise SystemExit(f"{name}: prefix8 {bad[:5]}")


def prepare(raw: list[str]) -> list[str]:
    if len(raw) < 150:
        raise SystemExit(f"prepare need 150+, got {len(raw)}")
    out = [pad_to_len(s, i) for i, s in enumerate(raw[:150])]
    return out


def emit(items: list[str], var: str) -> str:
    lines = [f"{var} = ["]
    for s in items:
        lines.append(f'    "{s}",')
    lines.append("]")
    return "\n".join(lines)


