def fmt(bodies: list[str]) -> list[str]:
    return [f"{i:03d}、{b}" for i, b in enumerate(bodies, 1)]


def colon_count(text: str) -> int:
    return len(COLON_RE.findall(text))


def validate(bid: str, bodies: list[str]) -> list[str]:
    errors: list[str] = []
    if len(bodies) != 150:
        errors.append(f"{bid} len={len(bodies)}")
    if len(bodies) != len(set(bodies)):
        errors.append(f"{bid} dup_body")
        seen = {}
        for i, b in enumerate(bodies, 1):
            seen.setdefault(b, []).append(i)
        for b, ids in seen.items():
            if len(ids) > 1:
                errors.append(f"{bid} dup {ids}")
    groups: dict[str, list[int]] = defaultdict(list)
    colon_hits = 0
    for i, b in enumerate(bodies, 1):
        if len(b) < 20:
            errors.append(f"{bid} short_{i}:{len(b)}")
        for bad in BANNED:
            if bad in b:
                errors.append(f"{bid} ban_{i}:{bad}")
        if "第" in b and "章" in b:
            errors.append(f"{bid} chapter_{i}")
        cc = colon_count(b)
        if cc:
            colon_hits += cc
            if cc > 2:
                errors.append(f"{bid} colons_{i}:{cc}")
        groups[b[:18]].append(i)
    if colon_hits > 2:
        errors.append(f"{bid} colon_total={colon_hits}")
    for p, ids in groups.items():
        if len(ids) >= 4:
            errors.append(f"{bid} prefix18 x{len(ids)}: {p} -> {ids}")
    return errors


def fix_numbering(bodies: list[str]) -> list[str]:
    cleaned = []
    for b in bodies:
        cleaned.append(re.sub(r"^\d{3}、", "", b).strip())
    return cleaned


def auto_fix(bodies: list[str]) -> list[str]:
    """Fix banned substrings and 18-char opening collisions."""
    tweaks = [
        "其實", "當時", "後來", "結果", "於是", "此外", "相對", "尤其",
        "往往", "至此", "可是", "倘若", "只要", "一旦", "甚至", "終究",
        "現場", "隔年", "事後", "事前",
    ]
    out = []
    for b in bodies:
        b = b.replace("這本書", "此冊").replace("一本書", "一冊").replace("十本書", "十冊")
        b = b.replace("本書", "此冊")
        b = b.replace("：", "，").replace(":", "，")
        out.append(b)
    groups: dict[str, list[int]] = defaultdict(list)
    for i, b in enumerate(out):
        groups[b[:18]].append(i)
    for _p, ids in groups.items():
        if len(ids) < 4:
            continue
        for n, idx in enumerate(ids[3:], start=3):
            prefix = tweaks[n % len(tweaks)]
            out[idx] = prefix + out[idx]
    return out


