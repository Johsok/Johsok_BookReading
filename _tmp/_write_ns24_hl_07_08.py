def lengthen(bodies: list[str], tails: list[str]) -> list[str]:
    """Append unique-enough clauses until each body is 28-70 chars."""
    out: list[str] = []
    k = 0
    for body in bodies:
        text = body
        guard = 0
        while len(text) < 28 and guard < 6:
            piece = tails[k % len(tails)]
            k += 1
            if text.endswith("。"):
                text = text[:-1] + "，" + piece
            else:
                text = text + piece
            guard += 1
        if len(text) > 70:
            text = text[:69].rstrip("，、； ") + "。"
        if len(text) < 28:
            raise SystemExit(f"still short {len(text)} {text}")
        out.append(text)
    return out


def validate(book_id: str, bodies: list[str], title: str, author: str) -> None:
    if len(bodies) != 150:
        raise SystemExit(f"{book_id} count={len(bodies)}")
    if len(set(bodies)) != 150:
        dups = [b for b, c in Counter(bodies).items() if c > 1]
        raise SystemExit(f"{book_id} dups={dups[:3]}")
    short_colon = []
    for i, body in enumerate(bodies, 1):
        if "\n" in body or "\r" in body or "｜" in body:
            raise SystemExit(f"{book_id} format {i}")
        if len(body) < 12:
            raise SystemExit(f"{book_id} short {i} {body}")
        if any(p in body for p in FORBIDDEN):
            raise SystemExit(f"{book_id} forbidden {i} {body[:40]}")
        if re.search(r".{1,8}面第\d+步[，,]", body) or re.match(r"^第\d+步[，,]", body):
            raise SystemExit(f"{book_id} step {i}")
        if re.search(r"第[一二三四五六七八九十\d]+章", body):
            raise SystemExit(f"{book_id} chapter {i}")
        match = re.match(r"^([^：:]{1,12})[：:]", body)
        if match and not match.group(1).endswith(NATURAL_COLON_SUFFIXES):
            short_colon.append(i)
        for ban in EXTRA_BAN:
            if ban in body:
                raise SystemExit(f"{book_id} extra-ban {i} {ban}")
        if title and title in body:
            raise SystemExit(f"{book_id} title hit {i}")
        if author and author in body:
            raise SystemExit(f"{book_id} author hit {i}")
    if len(short_colon) >= 3:
        raise SystemExit(f"{book_id} short-colon {short_colon[:10]}")
    starts = Counter(b[:18] for b in bodies if len(b) >= 18)
    worst = starts.most_common(3)
    if worst and worst[0][1] >= 4:
        raise SystemExit(f"{book_id} repeated starts {worst}")
