import re
from collections import Counter

def _cjk_prefix(s, n=8):
    chars = re.findall(r"[\u4e00-\u9fff]", s)
    return "".join(chars[:n])

def _check(name, items):
    banned = ("本書", "作者指出", "本章", "這一章", "｜", "《", "》")
    assert len(items) == 150, (name, len(items))
    assert len(set(items)) == 150, name
    for i, t in enumerate(items, 1):
        for b in banned:
            assert b not in t, (name, i, b)
        assert 25 <= len(t) <= 55, (name, i, len(t), t)
    oc = Counter(_cjk_prefix(t) for t in items if _cjk_prefix(t))
    bad = [(k, v) for k, v in oc.items() if v >= 4]
    assert not bad, (name, bad[:10])

_check("BOOK55", BOOK55)
_check("BOOK56", BOOK56)
print("ok")
