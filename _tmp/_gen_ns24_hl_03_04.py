BANNED_RE = re.compile(
    r"本書|作者指出|本章|這一章|｜|\|".replace("｜", "｜")
)
STEP_RE = re.compile(r".面第\d+步|第\d+步")
COLON_OK = ("是", "為", "在於", "說", "問", "提醒", "表示", "指出")


def check(bodies, label, extra_bans=()):
    errs = []
    if len(bodies) != 150:
        errs.append(f"count {len(bodies)}")
    if len(set(bodies)) != 150:
        errs.append("dup")
    p18 = Counter(s[:18] for s in bodies)
    bad18 = [f"{k!r}:{v}" for k, v in p18.items() if v >= 4]
    if bad18:
        errs.append(f"p18 {bad18}")
    cjk8 = Counter("".join(re.findall(r"[\u4e00-\u9fff]", s)[:8]) for s in bodies)
    bad8 = [f"{k}:{v}" for k, v in cjk8.items() if v >= 4]
    if bad8:
        errs.append(f"p8 {bad8}")
    for i, s in enumerate(bodies, 1):
        if not s.endswith("。"):
            errs.append(f"{i} no period")
        if len(s) < 12:
            errs.append(f"{i} short {len(s)}")
        if len(s) > 90:
            errs.append(f"{i} long {len(s)} {s}")
        if BANNED_RE.search(s) or STEP_RE.search(s):
            errs.append(f"{i} banned {s[:20]}")
        if s.startswith(("001", "1、")) or (len(s) >= 3 and s[:3].isdigit()):
            errs.append(f"{i} numbered")
        for t in list(BANNED_TITLES) + list(extra_bans):
            if t and t in s:
                errs.append(f"{i} title/author {t}")
        if "：" in s or ":" in s:
            left = s.split("：", 1)[0] if "：" in s else s.split(":", 1)[0]
            if not any(left.endswith(x) for x in COLON_OK):
                errs.append(f"{i} colon {s}")
            if len(left) <= 6:
                errs.append(f"{i} short-colon {s}")
        if "vernacular" in s or "dec 定" in s or " ent " in s:
            errs.append(f"{i} leftover {s}")
    print(label, "minmax", min(map(len, bodies)), max(map(len, bodies)), "errs", errs or "none")
    return errs


