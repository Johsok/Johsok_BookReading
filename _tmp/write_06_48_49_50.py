def validate(name: str, bodies: list[str]) -> list[str]:
    errs: list[str] = []
    if len(bodies) != 150:
        errs.append(f"{name} count={len(bodies)}")
    seen: set[str] = set()
    for i, b in enumerate(bodies, 1):
        if not b or b != b.strip():
            errs.append(f"{name} {i:03d} whitespace")
        if b[:3].isdigit() and "、" in b[:4]:
            errs.append(f"{name} {i:03d} already numbered")
        for ban in BANNED:
            if ban in b:
                errs.append(f"{name} {i:03d} banned {ban}")
        if "面第" in b and "步" in b:
            errs.append(f"{name} {i:03d} step pattern")
        if b in seen:
            errs.append(f"{name} {i:03d} dup")
        seen.add(b)
    return errs


def fmt(bodies: list[str]) -> list[str]:
    return [f"{i:03d}、{b}" for i, b in enumerate(bodies, 1)]


def write_book(path: Path, bodies: list[str]) -> None:
    data = json.loads(path.read_text(encoding="utf-8"))
    data["chatgptHighlights"] = fmt(bodies)
    data["chatgptStatus"] = "complete"
    data["highlightsSource"] = "grok"
    data["highlightsCapturedAt"] = STAMP
    data["updatedAt"] = UPDATED
    path.write_text(json.dumps(data, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")


