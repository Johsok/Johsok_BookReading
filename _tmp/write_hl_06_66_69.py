def validate(label: str, bodies: list[str]) -> list[str]:
    errs: list[str] = []
    if len(bodies) != 150:
        errs.append(f"{label}: count={len(bodies)} != 150")
    for i, b in enumerate(bodies, 1):
        if not b.strip():
            errs.append(f"{label}: empty {i}")
        for ban in BANNED:
            if ban in b:
                errs.append(f"{label}:{i} banned {ban}")
        if COLON_RE.search(b):
            errs.append(f"{label}:{i} colon")
        if "面第" in b and "步" in b:
            errs.append(f"{label}:{i} step-pattern")
    # duplicate full text
    seen: dict[str, int] = {}
    for i, b in enumerate(bodies, 1):
        if b in seen:
            errs.append(f"{label}: dup {seen[b]} & {i}")
        else:
            seen[b] = i
    # repeated openings
    prefixes: dict[str, list[int]] = defaultdict(list)
    for i, b in enumerate(bodies, 1):
        prefixes[b[:12]].append(i)
    for p, ids in prefixes.items():
        if len(ids) >= 4:
            errs.append(f"{label}: same-prefix×{len(ids)} '{p}' @ {ids[:6]}")
    return errs


def fmt(bodies: list[str]) -> list[str]:
    return [f"{i:03d}、{b}" for i, b in enumerate(bodies, 1)]


def write_json_atomic(path: Path, payload: dict) -> None:
    text = json.dumps(payload, ensure_ascii=False, indent=2) + "\n"
    handle = tempfile.NamedTemporaryFile(
        mode="w",
        encoding="utf-8",
        newline="\n",
        dir=path.parent,
        prefix=f".{path.name}.",
        suffix=".tmp",
        delete=False,
    )
    temp_path = Path(handle.name)
    try:
        with handle:
            handle.write(text)
            handle.flush()
            os.fsync(handle.fileno())
        json.loads(temp_path.read_text(encoding="utf-8"))
        for attempt in range(4):
            try:
                os.replace(temp_path, path)
                break
            except PermissionError:
                if attempt == 3:
                    raise
                time.sleep(0.1 * (attempt + 1))
    finally:
        if temp_path.exists():
            temp_path.unlink(missing_ok=True)


def update_book(stem: str, bodies: list[str], captured_at: str) -> dict:
    path = BOOK_DIR / f"{stem}.json"
    data = json.loads(path.read_text(encoding="utf-8-sig"))
    highlights = fmt(bodies)
    assert len(highlights) == 150
    assert highlights[0].startswith("001、")
    assert highlights[-1].startswith("150、")
    data["chatgptHighlights"] = highlights
    data["chatgptStatus"] = "complete"
    data["highlightsSource"] = "grok"
    data["highlightsCapturedAt"] = captured_at
    data["updatedAt"] = "2026-08-18"
    write_json_atomic(path, data)
    # verify
    again = json.loads(path.read_text(encoding="utf-8-sig"))
    hl = again["chatgptHighlights"]
    ok = (
        len(hl) == 150
        and hl[0].startswith("001、")
        and hl[-1].startswith("150、")
        and again["chatgptStatus"] == "complete"
        and again["highlightsSource"] == "grok"
        and again["updatedAt"] == "2026-08-18"
    )
    return {"file": path.name, "count": len(hl), "ok": ok, "title": again.get("title", "")}


