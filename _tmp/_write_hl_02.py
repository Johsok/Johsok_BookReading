import re
CJK = re.compile(r"[\u4e00-\u9fff]")

def first_n_cjk(s, n):
    chars = CJK.findall(s)
    return "".join(chars[:n])

print("count", len(lines))
print("lens", min(len(s) for s in lines), max(len(s) for s in lines))
c8 = Counter(first_n_cjk(s, 8) for s in lines)
c18 = Counter(first_n_cjk(s, 18) for s in lines)
print("dup8", [(k,v) for k,v in c8.items() if v>1])
print("max8", max(c8.values()), "max18", max(c18.values()))
print("unique8", len(c8), "unique18", len(c18))

