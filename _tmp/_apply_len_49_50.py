    missing = []
    for old, new in pairs:
        if old not in text:
            missing.append(old[:24])
        else:
            text = text.replace(old, new, 1)
    if missing:
        print("MISSING", path.name, len(missing))
        for m in missing[:8]:
            print(" ", m)
    path.write_text(text, encoding="utf-8")
    print("patched", path.name, "pairs", len(pairs), "missing", len(missing))


