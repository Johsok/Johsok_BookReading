def _validate(bodies: list[str], label: str) -> list[str]:
    assert len(bodies) == 150, f"{label} count {len(bodies)}"
    texts = []
    for i, body in enumerate(bodies, 1):
        assert not body.startswith(("0", "1")), f"{label} {i} has number in body"
        assert "｜" not in body and "|" not in body, f"{label} {i} pipe"
        for b in BANNED:
            assert b not in body, f"{label} {i} banned {b}"
        assert "本書" not in body and "作者指出" not in body and "本章" not in body
        assert body.endswith("。"), f"{label} {i} no period"
        line = f"{i:03d}、{body}"
        texts.append(line)
    assert len(texts) == 150
    assert len(set(texts)) == 150, f"{label} duplicate full lines"
    assert len(set(bodies)) == 150, f"{label} duplicate bodies"
    nums = [t[:3] for t in texts]
    assert nums == [f"{i:03d}" for i in range(1, 151)]
    return texts


def _write(path: Path, highlights: list[str]) -> None:
    data = json.loads(path.read_text(encoding="utf-8"))
    data["chatgptHighlights"] = highlights
    data["chatgptStatus"] = "complete"
    data["highlightsSource"] = "grok"
    data["highlightsCapturedAt"] = "2026-08-18T09:10:00+08:00"
    data["updatedAt"] = "2026-08-18"
    text = json.dumps(data, ensure_ascii=False, indent=2) + "\n"
    path.write_text(text, encoding="utf-8")
    back = json.loads(path.read_text(encoding="utf-8"))
    hl = back["chatgptHighlights"]
    assert len(hl) == 150
    assert back["chatgptStatus"] == "complete"
    assert back["highlightsSource"] == "grok"
    assert back["highlightsCapturedAt"] == "2026-08-18T09:10:00+08:00"
    assert back["updatedAt"] == "2026-08-18"
    assert [x[:3] for x in hl] == [f"{i:03d}" for i in range(1, 151)]
    assert len(set(hl)) == 150
    for x in hl:
        assert "｜" not in x and "本書" not in x and "作者指出" not in x and "本章" not in x


