def load_lists(src: str) -> dict[str, list[str]]:
    tree = ast.parse(src)
    out: dict[str, list[str]] = {}
    for node in tree.body:
        if isinstance(node, ast.Assign) and isinstance(node.targets[0], ast.Name):
            name = node.targets[0].id
            if name in {"B17", "B18"}:
                out[name] = [ast.literal_eval(elt) for elt in node.value.elts]
    return out


def dump_list(name: str, bodies: list[str]) -> str:
    lines = [f"{name} = ["]
    for body in bodies:
        lines.append("    " + json.dumps(body, ensure_ascii=False) + ",")
    lines.append("]")
    return "\n".join(lines)


