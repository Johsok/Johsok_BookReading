def lengthen(body: str) -> str:
    extras = ("其實", "往往", "仍然", "真正", "究竟", "顯然", "至少")
    n = 0
    while len(body) < 35 and n < 10:
        extra = extras[n % len(extras)]
        if "，" in body:
            body = body.replace("，", f"，{extra}", 1)
        elif "；" in body:
            body = body.replace("；", f"；{extra}", 1)
        elif body.endswith("。"):
            body = body[:-1] + extra + "。"
        else:
            body = extra + body
        n += 1
    return body


