def body_len(h: str) -> int:
    return len(h.split("、", 1)[1])


def validate(book_id: str, hs: list[str]) -> list[str]:
    errs: list[str] = []
    if len(hs) != 150:
        errs.append(f"{book_id}: count {len(hs)}")
    prefixes: dict[str, list[int]] = defaultdict(list)
    colon_hits = 0
    seen = set()
    for i, h in enumerate(hs, 1):
        prefix = f"{i:03d}、"
        if not h.startswith(prefix):
            errs.append(f"{book_id} {i}: bad number")
            continue
        body = h[len(prefix) :]
        n = len(body)
        if n < 30 or n > 70:
            errs.append(f"{book_id} {i}: len {n} {body}")
        if body in seen:
            errs.append(f"{book_id} {i}: duplicate")
        seen.add(body)
        head18 = body[:18]
        prefixes[head18].append(i)
        for w in BANNED:
            if w in h:
                errs.append(f"{book_id} {i}: banned {w}")
        for t in TITLES:
            if t in h:
                errs.append(f"{book_id} {i}: title {t}")
        if re.search(r"^.{1,8}：", body):
            colon_hits += 1
            errs.append(f"{book_id} {i}: colon {body[:20]}")
        if "第" in body and "章" in body:
            errs.append(f"{book_id} {i}: chapter ref")
    if colon_hits > 2:
        errs.append(f"{book_id}: short-label colons {colon_hits}")
    for head, ids in prefixes.items():
        if len(ids) >= 4:
            errs.append(f"{book_id}: first18 x{len(ids)} {head!r} {ids}")
    return errs


