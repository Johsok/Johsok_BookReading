def numbered(bodies: list[str]) -> list[str]:
    assert len(bodies) == 150, len(bodies)
    out = []
    seen = set()
    for i, body in enumerate(bodies, 1):
        for w in BANNED:
            if w in body:
                raise SystemExit(f"banned {w!r} in {i}: {body}")
        if "第" in body and "章" in body:
            raise SystemExit(f"chapter-like {i}: {body}")
        if body in seen:
            raise SystemExit(f"dup body {i}: {body}")
        seen.add(body)
        out.append(f"{i:03d}、{body}")
    return out


