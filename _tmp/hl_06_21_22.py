def _zh_len(s: str) -> int:
    """Count characters in a highlight body."""
    return len(s)


def _validate(name: str, items: list[str], titles: tuple[str, ...], authors: tuple[str, ...]) -> list[str]:
    """Return validation failure messages for one highlight list."""
    errors: list[str] = []
    if len(items) != 150:
        errors.append(f"{name}: count {len(items)} != 150")
    seen: set[str] = set()
    prefixes: list[str] = []
    short_colon = 0
    for i, body in enumerate(items, 1):
        if not isinstance(body, str):
            errors.append(f"{name} {i}: not str")
            continue
        if "\n" in body or "\r" in body or "｜" in body:
            errors.append(f"{name} {i}: newline or ｜")
        n = _zh_len(body)
        if n < 12:
            errors.append(f"{name} {i}: len {n} < 12")
        if n < 28 or n > 78:
            errors.append(f"{name} {i}: prefer 28-78 got {n} :: {body[:40]}")
        if body in seen:
            errors.append(f"{name} {i}: duplicate")
        seen.add(body)
        if len(body) >= 18:
            prefixes.append(body[:18])
        for bad in ("本書", "作者指出", "本章", "這一章"):
            if bad in body:
                errors.append(f"{name} {i}: forbidden {bad}")
        if re.search(r"第[0-9一二三四五六七八九十百零]+章", body):
            errors.append(f"{name} {i}: 第X章")
        if re.search(r".{1,8}面第\d+步[，,]", body) or re.match(r"^第\d+步[，,]", body):
            errors.append(f"{name} {i}: step template")
        m = re.match(r"^([^：:]{1,12})[：:]", body)
        if m and not m.group(1).endswith(("是", "為", "在於", "說", "問", "提醒", "表示", "指出")):
            short_colon += 1
            errors.append(f"{name} {i}: short-label colon :: {body[:20]}")
        for t in titles:
            if t and t in body:
                errors.append(f"{name} {i}: full title")
        for a in authors:
            if a and a in body:
                errors.append(f"{name} {i}: author name")
    bag = Counter(prefixes)
    repeats = [f"{p!r} x{c}" for p, c in bag.items() if c >= 4]
    if repeats:
        errors.append(f"{name}: 18-char prefix 4+ {repeats[:8]}")
    if short_colon:
        errors.append(f"{name}: short-label colon count {short_colon}")
    return errors


