def body_of(item: str) -> str:
    """Return highlight body after the ideographic numbering prefix."""
    return item.split("、", 1)[1] if "、" in item else item


def is_short_label_colon(body: str) -> bool:
    """Detect a short label ending with a fullwidth colon near the start."""
    return bool(re.match(r"^.{1,8}：", body))


def numbered(bodies: list[str]) -> list[str]:
    """Prefix bodies with 001、 style numbering."""
    return [f"{i:03d}、{b}" for i, b in enumerate(bodies, 1)]


def validate(book_id: str, items: list[str]) -> list[str]:
    """Return human-readable validation errors for one book."""
    errors: list[str] = []
    if len(items) != 150:
        errors.append(f"{book_id}: count {len(items)} != 150")
    seen = set()
    prefixes: list[str] = []
    colon_hits = 0
    for i, item in enumerate(items, 1):
        expect = f"{i:03d}、"
        if not item.startswith(expect):
            errors.append(f"{book_id} {i}: bad prefix")
        body = body_of(item)
        n = len(body)
        if not (30 <= n <= 70):
            errors.append(f"{book_id} {i}: len {n} :: {body}")
        if body in seen:
            errors.append(f"{book_id} {i}: duplicate body")
        seen.add(body)
        prefixes.append(body[:18])
        for w in FORBIDDEN + TITLE_AUTHOR:
            if w in item:
                errors.append(f"{book_id} {i}: forbidden {w}")
        if is_short_label_colon(body):
            colon_hits += 1
        if "：" in body[:12] and body.index("：") <= 8:
            pass
    bad = [p for p, c in Counter(prefixes).items() if c >= 4]
    if bad:
        errors.append(f"{book_id}: 18-char prefix x4+ {bad[:5]}")
    if colon_hits > 2:
        errors.append(f"{book_id}: short-label colons {colon_hits} > 2")
    return errors


def ascii_leak(body: str) -> list[str]:
    """Find leftover Latin letters that should be Traditional Chinese."""
    if re.search(r"[A-Za-z]", body):
        return ["latin"]
    return []


