def _stitch(body: str, add: str) -> str:
    """Append a complete clause so the body falls within 30-70 characters."""
    core = body[:-1] if body.endswith("。") else body
    out = f"{core}，{add}。"
    if len(out) > 70:
        out = out[:69] + "。"
    if len(out) < 30:
        raise RuntimeError(f"still short {len(out)} {out}")
    return out


def expand_short(bodies: list[str], clauses: list[str]) -> list[str]:
    """Lengthen undersized bodies with unique, grammatical clauses."""
    need = sum(1 for b in bodies if len(b) < 30)
    if len(clauses) < need:
        raise RuntimeError(f"need {need} clauses, have {len(clauses)}")
    it = iter(clauses)
    out: list[str] = []
    for b in bodies:
        if len(b) < 30:
            out.append(_stitch(b, next(it)))
        else:
            out.append(b)
    return out


