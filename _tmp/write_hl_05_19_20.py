def numbered(items: list[str]) -> list[str]:
    bodies = []
    out = []
    for i, raw in enumerate(items, 1):
        t = raw.strip()
        assert t, i
        assert not re.match(r"^\d{3}、", t)
        for b in BANNED:
            assert b not in t, (b, t[:50])
        assert not CHAP_RE.search(t), t[:40]
        bodies.append(t)
        out.append(f"{i:03d}、{t}")
    assert len(items) == 150, len(items)
    assert len(set(bodies)) == 150, len(set(bodies))
    c = Counter(t[:6] for t in bodies)
    heavy = [k for k, v in c.items() if v >= 4]
    assert not heavy, heavy
    return out


