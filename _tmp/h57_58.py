BANNED = ("本書", "作者指出", "本章", "這一章", "｜", "《", "》")

def cjk_prefix(s, n=8):
    chars = re.findall(r"[\u4e00-\u9fff]", s)
    return "".join(chars[:n])

def check(name, items):
    assert len(items) == 150
    assert len(set(items)) == 150
    for s in items:
        assert 25 <= len(s) <= 55, (name, len(s), s)
        for b in BANNED:
            assert b not in s
    pref = Counter(cjk_prefix(s) for s in items if cjk_prefix(s))
    bad = [k for k, v in pref.items() if v >= 4]
    assert not bad, (name, bad)

