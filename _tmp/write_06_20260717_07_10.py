def validate(name: str, lines: list[str]) -> list[str]:
    assert len(lines) == 150, (name, len(lines))
    highlights = [f"{i:03d}、{text.strip()}" for i, text in enumerate(lines, 1)]
    bodies = []
    short_colon = []
    for i, line in enumerate(highlights, 1):
        assert line.startswith(f"{i:03d}、"), (name, line[:12])
        body = line.split("、", 1)[1]
        assert len(body) >= 12, (name, i, body)
        assert "｜" not in body
        for p in ("本書", "作者指出", "本章", "這一章"):
            assert p not in body, (name, i, p)
        assert re.search(r".{1,8}面第\d+步[，,]", body) is None
        m = re.match(r"^([^：:]{1,12})[：:]", body)
        if m and not m.group(1).endswith(("是", "為", "在於", "說", "問", "提醒", "表示", "指出")):
            short_colon.append((i, body[:24]))
        bodies.append(body)
    assert len(short_colon) < 3, (name, short_colon)
    assert len(set(bodies)) == 150, (name, 150 - len(set(bodies)))
    prefixes = Counter(b[:10] for b in bodies)
    assert prefixes.most_common(1)[0][1] < 4, (name, prefixes.most_common(8))
    return highlights


def atomic_write(path: Path, data: dict) -> None:
    text = json.dumps(data, ensure_ascii=False, indent=2) + "\n"
    fd, tmp_name = tempfile.mkstemp(prefix=path.stem + ".", suffix=".tmp", dir=str(path.parent))
    tmp_path = Path(tmp_name)
    try:
        with open(fd, "w", encoding="utf-8", newline="\n") as f:
            f.write(text)
        tmp_path.replace(path)
    except Exception:
        if tmp_path.exists():
            tmp_path.unlink()
        raise


def main() -> None:
    results = []
    for filename, lines in BOOKS.items():
        path = BASE / filename
        highlights = validate(filename, lines)
        raw = path.read_text(encoding="utf-8-sig")
        data = json.loads(raw)
        data["chatgptHighlights"] = highlights
        data["chatgptStatus"] = "complete"
        data["highlightsSource"] = "grok"
        data["highlightsCapturedAt"] = CAPTURED
        data["updatedAt"] = UPDATED
        atomic_write(path, data)
        # verify
        check = json.loads(path.read_text(encoding="utf-8-sig"))
        ok = (
            len(check["chatgptHighlights"]) == 150
            and check["chatgptStatus"] == "complete"
            and check["highlightsSource"] == "grok"
            and check["updatedAt"] == UPDATED
            and check["chatgptHighlights"][0].startswith("001、")
            and check["chatgptHighlights"][-1].startswith("150、")
        )
        results.append((filename, len(check["chatgptHighlights"]), ok))
        print(f"{filename}\t{len(check['chatgptHighlights'])}\t{'OK' if ok else 'FAIL'}")
    if not all(r[2] for r in results):
        raise SystemExit(1)


if __name__ == "__main__":
    main()
