def check_body(body: str, tag: str) -> str:
    body = bump(body, tag)
    n = len(body)
    if n < 35 or n > 70:
        raise SystemExit(f"{tag} len {n} {body}")
    if any(c.isascii() and c.isalpha() for c in body):
        raise SystemExit(f"{tag} latin {body}")
    if re.search(r"往往其實|其實其實|仍然往往|本書|作者指出|本章|步驟面向", body):
        raise SystemExit(f"{tag} filler {body}")
    return body


