def cjk_chars(s):
    return re.findall(r"[\u4e00-\u9fff]", s)

def first_n_cjk(s, n):
    c = cjk_chars(s)
    return "".join(c[:n])

def validate(name, items):
    errors = []
    if len(items) != 150:
        errors.append(f"{name}: len={len(items)} != 150")
    if len(set(items)) != len(items):
        errors.append(f"{name}: duplicate strings")
    for i, s in enumerate(items):
        for fb in FORBIDDEN:
            if fb in s:
                errors.append(f"{name}[{i}]: forbidden '{fb}'")
        for fn in FORBIDDEN_NAMES:
            if fn in s:
                errors.append(f"{name}[{i}]: forbidden name '{fn}'")
        if re.search(r"第\d+步", s):
            errors.append(f"{name}[{i}]: step pattern")
        n = len(cjk_chars(s))
        if n < 20 or n > 60:
            errors.append(f"{name}[{i}]: cjk len {n}")
    # first 8 cjk: no 4 share same prefix
    p8 = [first_n_cjk(s, 8) for s in items]
    for p, cnt in Counter(p8).items():
        if cnt >= 4:
            errors.append(f"{name}: prefix8 '{p}' x{cnt}")
    # first 18 chars (not just cjk) repeat 4+
    p18 = [s[:18] for s in items]
    for p, cnt in Counter(p18).items():
        if cnt >= 4:
            errors.append(f"{name}: prefix18 '{p}' x{cnt}")
    # adjacent semantic dup - basic check same first 12 cjk
    for i in range(len(items) - 1):
        if first_n_cjk(items[i], 12) == first_n_cjk(items[i + 1], 12):
            errors.append(f"{name}: adjacent similar at {i}")
    return errors

