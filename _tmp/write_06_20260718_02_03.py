def numbered(bodies: list[str]) -> list[str]:
    if len(bodies) != 150:
        raise SystemExit(f"expected 150 bodies, got {len(bodies)}")
    return [f"{i:03d}、{body}" for i, body in enumerate(bodies, 1)]


def write_book(path: Path, book_id: str, title: str, author: str, bodies: list[str]) -> None:
    highlights = numbered(bodies)
    validate_highlights(book_id, highlights, title, author)
    data = json.loads(path.read_text(encoding="utf-8-sig"))
    data["chatgptHighlights"] = highlights
    data["chatgptStatus"] = "complete"
    data["highlightsSource"] = "grok"
    data["highlightsCapturedAt"] = CAPTURED
    data["updatedAt"] = UPDATED
    path.write_text(
        json.dumps(data, ensure_ascii=False, indent=2) + "\n",
        encoding="utf-8-sig",
    )
    again = json.loads(path.read_text(encoding="utf-8-sig"))
    validate_highlights(book_id, again["chatgptHighlights"], title, author)
    assert again["chatgptStatus"] == "complete"
    assert again["highlightsSource"] == "grok"
    assert again["highlightsCapturedAt"] == CAPTURED
    assert again["updatedAt"] == UPDATED
    print("PASS", book_id, len(again["chatgptHighlights"]))
    print(again["chatgptHighlights"][0])
    print(again["chatgptHighlights"][1])


