STEP_RE = re.compile(r".{1,8}面第\d+步[，,]|^第\d+步[，,]")
SHORT_COLON_RE = re.compile(r"^([^：:]{1,12})[：:]")
NATURAL_COLON_SUFFIXES = ("是", "為", "在於", "說", "問", "提醒", "表示", "指出")


def validate(name: str, bodies: list[str]) -> list[str]:
    """Return validation errors for one highlight body list."""
    errors: list[str] = []
    if len(bodies) != 150:
        errors.append(f"{name}: count {len(bodies)} != 150")
    if len(set(bodies)) != len(bodies):
        errors.append(f"{name}: duplicate bodies")
        seen: set[str] = set()
        for i, body in enumerate(bodies, 1):
            if body in seen:
                errors.append(f"{name} {i}: dup {body[:24]}")
            seen.add(body)
    prefixes = Counter(b[:18] for b in bodies if len(b) >= 18)
    bad = [p for p, c in prefixes.items() if c >= 4]
    if bad:
        errors.append(f"{name}: 18-char prefix x4+ {bad[:8]}")
    colon_hits = 0
    title_hits = {t: 0 for t in TITLE_AUTHOR if t}
    for i, body in enumerate(bodies, 1):
        n = len(body)
        if n < 12:
            errors.append(f"{name} {i}: len {n} < 12")
        if n < 28 or n > 78:
            errors.append(f"{name} {i}: len {n} not in 28-78 :: {body}")
        for w in FORBIDDEN:
            if w in body:
                errors.append(f"{name} {i}: forbidden {w}")
        for t in title_hits:
            if t in body:
                title_hits[t] += 1
        if STEP_RE.search(body):
            errors.append(f"{name} {i}: step wording")
        match = SHORT_COLON_RE.match(body)
        if match and not match.group(1).endswith(NATURAL_COLON_SUFFIXES):
            colon_hits += 1
            errors.append(f"{name} {i}: short-label colon :: {body[:20]}")
    for t, c in title_hits.items():
        if c >= 2:
            errors.append(f"{name}: title/author spam {t!r} x{c}")
    if colon_hits >= 3:
        errors.append(f"{name}: short-label colons {colon_hits} >= 3")
    return errors


