def _fit(body: str, idx: int) -> str:
    s = body.rstrip()
    if not s.endswith(("。", "！", "？")):
        s += "。"
    n = 0
    while len(s) < 25 and n < 6:
        extra = PADS[(idx + n) % len(PADS)]
        s = s[:-1] + extra
        n += 1
    if len(s) > 72:
        s = s[:71].rstrip("，、； ") + "。"
    return s


def _prepare(bodies: list[str]) -> list[str]:
    fitted = [_fit(b, i) for i, b in enumerate(bodies)]
    if len(fitted) > 150:
        fitted = fitted[:148] + fitted[-2:]
    return fitted


def _validate(name: str, bodies: list[str]) -> list[str]:
    errs: list[str] = []
    if len(bodies) != 150:
        errs.append(f"{name} count={len(bodies)}")
    if len(set(bodies)) != len(bodies):
        seen: dict[str, int] = {}
        for i, b in enumerate(bodies, 1):
            if b in seen:
                errs.append(f"{name} dup {seen[b]:03d}/{i:03d} {b[:24]}")
            else:
                seen[b] = i
    starts10 = [b[:10] for b in bodies]
    for k, n in Counter(starts10).items():
        if n > 1:
            idxs = [i + 1 for i, s in enumerate(starts10) if s == k]
            errs.append(f"{name} first10 {k!r} x{n} {idxs}")
    starts4 = [b[:4] for b in bodies]
    for k, n in Counter(starts4).items():
        if n > 1:
            idxs = [i + 1 for i, s in enumerate(starts4) if s == k]
            errs.append(f"{name} first4 {k!r} x{n} {idxs}")
    for i, b in enumerate(bodies, 1):
        n = len(b)
        if not (25 <= n <= 80):
            errs.append(f"{name} {i:03d} len={n} {b}")
        if b[-1] not in "。！？":
            errs.append(f"{name} {i:03d} end {b[-1]!r}")
        for w in BANNED:
            if w in b:
                errs.append(f"{name} {i:03d} banned {w}")
        if COLON_RE.search(b):
            errs.append(f"{name} {i:03d} colon")
        if CHAP_RE.search(b):
            errs.append(f"{name} {i:03d} chapter")
        if "章" in b:
            errs.append(f"{name} {i:03d} 章")
        if LATIN_RE.search(b):
            errs.append(f"{name} {i:03d} latin {LATIN_RE.findall(b)}")
    return errs


def _numbered(bodies: list[str]) -> list[str]:
    return [f"{i:03d}、{b}" for i, b in enumerate(bodies, 1)]


def _write(path: Path, highlights: list[str]) -> dict:
    data = json.loads(path.read_text(encoding="utf-8-sig"))
    data["chatgptHighlights"] = highlights
    data["chatgptStatus"] = "complete"
    data["highlightsSource"] = "grok"
    data["highlightsCapturedAt"] = STAMP
    data["updatedAt"] = UPDATED
    raw = json.dumps(data, ensure_ascii=False, indent=2) + "\n"
    fd, tmp = tempfile.mkstemp(suffix=".json", dir=str(path.parent))
    try:
        with os.fdopen(fd, "w", encoding="utf-8", newline="\n") as f:
            f.write(raw)
        os.replace(tmp, path)
    except Exception:
        if os.path.exists(tmp):
            os.remove(tmp)
        raise
    return json.loads(path.read_text(encoding="utf-8-sig"))


