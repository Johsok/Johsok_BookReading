def numbered(bodies: list[str]) -> list[str]:
    if len(bodies) != 150:
        raise SystemExit(f"expected 150 bodies, got {len(bodies)}")
    return [f"{i:03d}、{body}" for i, body in enumerate(bodies, 1)]


def apply(rel: str, book_id: str, bodies: list[str], title: str, author: str) -> None:
    path = ROOT / rel
    book = json.loads(path.read_text(encoding="utf-8-sig"))
    highlights = numbered(bodies)
    validate_highlights(book_id, highlights, title, author)
    book["chatgptHighlights"] = highlights
    book["chatgptStatus"] = "complete"
    book["highlightsSource"] = "grok"
    book["highlightsCapturedAt"] = HL_AT
    book["updatedAt"] = UPDATED
    path.write_text(json.dumps(book, ensure_ascii=False, indent=2) + "\n", encoding="utf-8-sig")
    saved = json.loads(path.read_text(encoding="utf-8-sig"))
    validate_highlights(book_id, saved["chatgptHighlights"], saved["title"], saved["author"])
    assert saved["chatgptStatus"] == "complete"
    assert saved["highlightsSource"] == "grok"
    assert saved["updatedAt"] == UPDATED
    print("PASS", book_id, len(saved["chatgptHighlights"]))
    print("  ", saved["chatgptHighlights"][0])
    print("  ", saved["chatgptHighlights"][1])


