def numbered(bodies: list[str]) -> list[str]:
    if len(bodies) != 150:
        raise SystemExit(f"expected 150 bodies, got {len(bodies)}")
    return [f"{i:03d}、{body}" for i, body in enumerate(bodies, 1)]


def patch(path: Path, book_id: str, title: str, author: str, bodies: list[str]) -> None:
    highlights = numbered(bodies)
    validate_highlights(book_id, highlights, title, author)
    data = json.loads(path.read_text(encoding="utf-8-sig"))
    data["chatgptHighlights"] = highlights
    data["chatgptStatus"] = "complete"
    data["highlightsSource"] = "grok"
    data["highlightsCapturedAt"] = CAPTURED
    data["updatedAt"] = UPDATED
    path.write_text(
        json.dumps(data, ensure_ascii=False, indent=2) + "\n",
        encoding="utf-8-sig",
    )
    saved = json.loads(path.read_text(encoding="utf-8-sig"))
    validate_highlights(book_id, saved["chatgptHighlights"], title, author)
    if saved.get("chatgptStatus") != "complete" or saved.get("highlightsSource") != "grok":
        raise SystemExit(f"{book_id} metadata mismatch")
    print(f"PASS\t{book_id}\tcount={len(saved['chatgptHighlights'])}")
    print(saved["chatgptHighlights"][0])
    print(saved["chatgptHighlights"][1])


