def validate_bodies(book_id: str, bodies: list[str], title: str, authors: tuple[str, ...] | str) -> None:
    if len(bodies) != 150:
        raise SystemExit(f"{book_id} count={len(bodies)}")
    if len(set(bodies)) != 150:
        dup = [b for b, c in Counter(bodies).items() if c > 1]
        raise SystemExit(f"{book_id} duplicate: {dup[:2]}")
    for i, body in enumerate(bodies, 1):
        if len(body) < 12:
            raise SystemExit(f"{book_id} #{i} short {len(body)}")
        if any(x in body for x in FORBIDDEN):
            raise SystemExit(f"{book_id} #{i} forbidden")
        if "\n" in body or "\r" in body:
            raise SystemExit(f"{book_id} #{i} newline")
        if re.search(r".{1,8}面第\d+步[，,]", body) or re.match(r"^第\d+步[，,]", body):
            raise SystemExit(f"{book_id} #{i} step wording")
        match = re.match(r"^([^：:]{1,12})[：:]", body)
        if match and not match.group(1).endswith(NATURAL_COLON_SUFFIXES):
            raise SystemExit(f"{book_id} #{i} bad colon {match.group(1)}")
        if title and title in body:
            raise SystemExit(f"{book_id} #{i} full title")
    auth_list = (authors,) if isinstance(authors, str) else authors
    for a in auth_list:
        if a and any(a in b for b in bodies):
            raise SystemExit(f"{book_id} author/title fragment {a}")
    starts = Counter(b[:18] for b in bodies)
    bad = [(s, n) for s, n in starts.items() if n >= 4]
    if bad:
        raise SystemExit(f"{book_id} prefix>=4 {bad[:8]}")
    # extra: 108課綱 as opening
    if book_id.endswith("06"):
        for i, b in enumerate(bodies, 1):
            if b.startswith("108課綱"):
                raise SystemExit(f"{book_id} #{i} starts with 108課綱")


