def _bodies_ok(name: str, items: list[str], title: str, author: str, extra_frags: tuple[str, ...]) -> list[str]:
    """Return validation error strings for one highlight list."""
    errors: list[str] = []
    if len(items) != 150:
        errors.append(f"{name}: count {len(items)} != 150")
    seen: set[str] = set()
    prefixes: list[str] = []
    for i, body in enumerate(items, 1):
        if not isinstance(body, str):
            errors.append(f"{name} {i}: not str")
            continue
        if "\n" in body or "\r" in body:
            errors.append(f"{name} {i}: newline")
        if "｜" in body:
            errors.append(f"{name} {i}: pipe")
        n = len(body)
        if n < 12:
            errors.append(f"{name} {i}: len {n} < 12")
        if body in seen:
            errors.append(f"{name} {i}: duplicate")
        seen.add(body)
        prefixes.append(body[:18])
        for w in FORBIDDEN:
            if w in body:
                errors.append(f"{name} {i}: forbidden {w}")
        if title and title in body:
            errors.append(f"{name} {i}: full title")
        if author and author in body:
            errors.append(f"{name} {i}: full author")
        for w in extra_frags:
            if w in body:
                errors.append(f"{name} {i}: author fragment {w}")
        if re.search(r"面第\d+步", body) or re.search(r"第\d+步，", body):
            errors.append(f"{name} {i}: step pattern")
        if re.search(r"第[一二三四五六七八九十百零〇兩]+步，", body):
            errors.append(f"{name} {i}: cjk step pattern")
        if re.match(r"^.{1,8}：", body):
            errors.append(f"{name} {i}: short label colon")
    bad = [p for p, c in Counter(prefixes).items() if c >= 4]
    if bad:
        errors.append(f"{name}: 18-char prefix x4+ {bad[:8]}")
    pref = [len(b) for b in items if isinstance(b, str)]
    if pref:
        lo, hi = min(pref), max(pref)
        if lo < 28 or hi > 78:
            # Preferred band is reported only when outside; still FAIL if <12 (already).
            # Keep preferred as hard check so drafts stay in band.
            outside = [f"{i}:{len(b)}" for i, b in enumerate(items, 1) if not (28 <= len(b) <= 78)]
            if outside:
                errors.append(f"{name}: len outside 28-78 -> {outside[:12]} (n={len(outside)})")
    return errors


