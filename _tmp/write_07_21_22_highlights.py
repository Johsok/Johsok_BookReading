def _assert_ok(name, hs):
    assert len(hs) == 150, f"{name} count {len(hs)}"
    texts = []
    for i, line in enumerate(hs, 1):
        prefix = f"{i:03d}、"
        assert line.startswith(prefix), f"{name} {i} prefix: {line[:20]}"
        body = line[len(prefix):]
        assert body.strip(), f"{name} {i} empty"
        assert "｜" not in line
        assert "本書" not in line
        assert "作者指出" not in line
        assert "本章" not in line
        assert "第" not in line or "第" in body  # allow 第三者 etc; check chapter pattern below
        texts.append(body)
    banned = ("第1章", "第2章", "第3章", "第4章", "第X章", "第一章", "第二章")
    for line in hs:
        for b in banned:
            assert b not in line, line
    assert hs[0].startswith("001、")
    assert hs[-1].startswith("150、")
    assert len(set(hs)) == 150, f"{name} duplicate full lines"
    assert len(set(texts)) == 150, f"{name} duplicate bodies"


def _write(path: Path, highlights):
    data = json.loads(path.read_text(encoding="utf-8-sig"))
    data["chatgptHighlights"] = highlights
    data["chatgptStatus"] = "complete"
    data["highlightsSource"] = "grok"
    data["highlightsCapturedAt"] = STAMP
    data["updatedAt"] = UPDATED
    raw = json.dumps(data, ensure_ascii=False, indent=2) + "\n"
    fd, tmp = tempfile.mkstemp(suffix=".json", dir=str(path.parent))
    try:
        with os.fdopen(fd, "w", encoding="utf-8", newline="\n") as f:
            f.write(raw)
        os.replace(tmp, path)
    except Exception:
        if os.path.exists(tmp):
            os.remove(tmp)
        raise
    check = json.loads(path.read_text(encoding="utf-8-sig"))
    hs = check["chatgptHighlights"]
    print(path.name)
    print("count", len(hs))
    print("status", check["chatgptStatus"], check["highlightsSource"], check["highlightsCapturedAt"], check["updatedAt"])
    print("FIRST", hs[0])
    print("LAST", hs[-1])
    print("keys", list(check.keys()))


