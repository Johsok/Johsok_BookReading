def _fix_typos(items: list[str]) -> list[str]:
    """Remove leftover English fragments introduced while drafting."""
    out = []
    for t in items:
        t = t.replace(" isol ated ", "單獨")
        t = t.replace(" equally ", "同樣")
        t = t.replace(" lev er ", "槓桿")
        t = t.replace(" Bal 平衡", "平衡")
        t = t.replace(" spar 級", "遠距")
        t = t.replace(" ent 規則", "既有規則")
        t = t.replace(" cop 盛行率", "盛行率")
        t = t.replace(" clarithromycin ", "clarithromycin")
        out.append(t)
    return out


def validate(name: str, items: list[str]) -> None:
    if len(items) != 150:
        raise SystemExit(f"{name}: expected 150, got {len(items)}")
    for i, text in enumerate(items, 1):
        for b in BANNED:
            if b in text:
                raise SystemExit(f"{name} #{i}: banned `{b}`")
        if COLON_RE.search(text):
            raise SystemExit(f"{name} #{i}: colon found")
        if STEP_RE.search(text):
            raise SystemExit(f"{name} #{i}: step pattern")
        if re.match(r"^\d{3}、", text):
            raise SystemExit(f"{name} #{i}: already numbered?")
        if len(text) < 12:
            raise SystemExit(f"{name} #{i}: too short")
        if "  " in text:
            raise SystemExit(f"{name} #{i}: double space")
        if re.search(r"[A-Za-z]{3,}\s+[A-Za-z]{3,}", text):
            raise SystemExit(f"{name} #{i}: leftover english phrase: {text}")
    c = Counter(items)
    dups = [k for k, v in c.items() if v > 1]
    if dups:
        raise SystemExit(f"{name}: duplicate lines: {dups[:3]}")

    def cjk_prefix(s: str, n: int = 8) -> str:
        chars = re.findall(r"[\u4e00-\u9fff]", s)
        return "".join(chars[:n])

    open_c = Counter(cjk_prefix(t) for t in items if cjk_prefix(t))
    bad = [(k, v) for k, v in open_c.items() if v >= 4]
    if bad:
        raise SystemExit(f"{name}: repeated openings: {bad[:5]}")
    starts = Counter(t[:18] for t in items if len(t) >= 18)
    if starts and starts.most_common(1)[0][1] >= 4:
        raise SystemExit(f"{name}: repeated 18-prefix {starts.most_common(1)[0]}")


def atomic_write(path: Path, data: dict) -> None:
    text = json.dumps(data, ensure_ascii=False, indent=2) + "\n"
    fd, tmp = tempfile.mkstemp(prefix=path.name + ".", suffix=".tmp", dir=str(path.parent))
    try:
        with os.fdopen(fd, "w", encoding="utf-8", newline="\n") as f:
            f.write(text)
            f.flush()
            os.fsync(f.fileno())
        os.replace(tmp, path)
    finally:
        if os.path.exists(tmp):
            try:
                os.remove(tmp)
            except OSError:
                pass


def write_book(filename: str, highlights: list[str]) -> dict:
    path = ROOT / filename
    with path.open("r", encoding="utf-8-sig") as f:
        data = json.load(f)
    numbered = [f"{i:03d}、{t}" for i, t in enumerate(highlights, 1)]
    data["chatgptHighlights"] = numbered
    data["chatgptStatus"] = "complete"
    data["highlightsSource"] = "grok"
    data["highlightsCapturedAt"] = CAPTURED
    data["updatedAt"] = UPDATED
    atomic_write(path, data)
    with path.open("r", encoding="utf-8-sig") as f:
        check = json.load(f)
    ok = (
        len(check["chatgptHighlights"]) == 150
        and check["chatgptHighlights"][0].startswith("001、")
        and check["chatgptHighlights"][-1].startswith("150、")
    )
    return {"file": filename, "count": len(check["chatgptHighlights"]), "ok": ok}


