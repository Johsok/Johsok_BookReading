def check(name, bodies):
    errors = []
    if len(bodies) != 150:
        errors.append(f"{name} len={len(bodies)}")
    if len(set(bodies)) != len(bodies):
        dup = [b for b, c in Counter(bodies).items() if c > 1]
        errors.append(f"{name} dup {dup[:5]}")
    pref = Counter(b[:18] for b in bodies)
    badp = {k: v for k, v in pref.items() if v >= 4}
    if badp:
        errors.append(f"{name} prefix {badp}")
    for i, b in enumerate(bodies):
        if len(b) < 12:
            errors.append(f"{name}[{i}] short {len(b)} {b}")
        for w in BANNED:
            if w in b:
                errors.append(f"{name}[{i}] banned {w}")
        if b.startswith("#") or "**" in b or "`" in b:
            errors.append(f"{name}[{i}] md")
        if "：" in b[:8] or ":" in b[:6]:
            head = b.split("：")[0] if "：" in b else b.split(":")[0]
            if not any(head.endswith(x) for x in ("是", "為", "在於", "說", "問", "提醒", "表示", "指出")):
                errors.append(f"{name}[{i}] colon {b[:20]}")
        if "第" in b[:6] and "步" in b[:12]:
            errors.append(f"{name}[{i}] step {b[:20]}")
    # adjacent similarity: first 8 chars
    for i in range(1, len(bodies)):
        if bodies[i][:8] == bodies[i - 1][:8]:
            errors.append(f"{name} adj {i} {bodies[i][:12]}")
    return errors, pref.most_common(5), [len(b) for b in bodies]


