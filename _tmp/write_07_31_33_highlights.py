def numbered(bodies: list[str]) -> list[str]:
    if len(bodies) != 150:
        raise ValueError(f"expected 150, got {len(bodies)}")
    return [f"{i:03d}、{b}" for i, b in enumerate(bodies, 1)]


def write_book(rel: str, bodies: list[str]) -> dict:
    path = ROOT / rel
    data = json.loads(path.read_text(encoding="utf-8-sig"))
    highlights = numbered(bodies)
    validate_highlights(
        str(data.get("id", path.stem)),
        highlights,
        str(data.get("title", "")),
        str(data.get("author", "")),
    )
    data["chatgptHighlights"] = highlights
    data["updatedAt"] = UPDATED
    path.write_text(
        json.dumps(data, ensure_ascii=False, indent=2) + "\n",
        encoding="utf-8-sig",
    )
    return {
        "id": data["id"],
        "ok": True,
        "count": len(highlights),
        "samples": highlights[:3],
    }


