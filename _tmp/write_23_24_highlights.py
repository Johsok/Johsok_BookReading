def numbered(lines):
    if len(lines) != 150:
        raise SystemExit(f"expected 150, got {len(lines)}")
    bodies = [x.split("、", 1)[-1] if x[:4].isdigit() else x for x in lines]
    if len(set(bodies)) != 150:
        raise SystemExit("duplicate highlight bodies")
    forbidden = ("本書", "作者指出", "本章")
    for i, t in enumerate(bodies, 1):
        for f in forbidden:
            if f in t:
                raise SystemExit(f"forbidden {f} in {i}")
    return [f"{i:03d}、{t}" for i, t in enumerate(bodies, 1)]


def patch(path, highlights):
    with path.open(encoding="utf-8-sig") as f:
        data = json.load(f)
    data["chatgptHighlights"] = numbered(highlights)
    data["chatgptStatus"] = "complete"
    data["highlightsSource"] = "grok"
    data["highlightsCapturedAt"] = STAMP
    data["updatedAt"] = DATE
    with path.open("w", encoding="utf-8", newline="\n") as f:
        json.dump(data, f, ensure_ascii=False, indent=2)
