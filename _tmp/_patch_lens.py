def patch(path, repl):
    p = Path(path)
    lines = [ln.strip() for ln in p.read_text(encoding="utf-8").splitlines() if ln.strip()]
    out = [repl.get(x, x) for x in lines]
    missing = [k for k in repl if k not in lines]
    p.write_text("\n".join(out) + "\n", encoding="utf-8")
    return missing

