def numbered(items):
    assert len(items) == 150, len(items)
    out = []
    bodies = []
    for i, t in enumerate(items, 1):
        assert t and t[-1] not in "：:", t
        assert "：" not in t and ":" not in t, t[:50]
        for b in BANNED:
            assert b not in t, (b, t[:40])
        assert not CHAP_RE.search(t), t[:40]
        assert not STEP_RE.search(t), t[:40]
        bodies.append(t)
        out.append(f"{i:03d}、{t}")
    assert len(set(bodies)) == 150
    prefixes = [t[:6] for t in bodies]
    c = Counter(prefixes)
    heavy = [k for k, v in c.items() if v >= 4]
    assert not heavy, heavy
    return out


def patch(path: Path, items):
    data = json.loads(path.read_text(encoding="utf-8"))
    data["chatgptHighlights"] = numbered(items)
    data["chatgptStatus"] = "complete"
    data["highlightsSource"] = "grok"
    data["highlightsCapturedAt"] = STAMP
    data["updatedAt"] = "2026-08-18"
    text = json.dumps(data, ensure_ascii=False, indent=2) + "\n"
    path.write_text(text, encoding="utf-8")
    hl = data["chatgptHighlights"]
    assert len(hl) == 150
    assert hl[0].startswith("001、")
    assert hl[-1].startswith("150、")
    return hl


