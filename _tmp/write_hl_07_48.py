def cjk_len(s: str) -> int:
    return len(CJK_RE.findall(s))


def validate(bodies: list[str]) -> list[str]:
    errors: list[str] = []
    if len(bodies) != 150:
        errors.append(f"len={len(bodies)}")
    if len(bodies) != len(set(bodies)):
        errors.append("dup_body")
    groups: dict[str, list[int]] = defaultdict(list)
    colon_hits = 0
    sea_starts = 0
    for i, b in enumerate(bodies, 1):
        n = cjk_len(b)
        if not (32 <= n <= 68):
            errors.append(f"cjk_{i}:{n}:{b}")
        for bad in BANNED:
            if bad in b:
                errors.append(f"ban_{i}:{bad}")
        if re.search(r"第[0-9一二三四五六七八九十百零〇兩]+章", b):
            errors.append(f"chapter_{i}")
        cc = len(COLON_RE.findall(b))
        if cc:
            colon_hits += cc
        groups[b[:18]].append(i)
        if b.startswith("在海上"):
            sea_starts += 1
    if sea_starts:
        errors.append(f"sea_starts={sea_starts}")
    if colon_hits > 2:
        errors.append(f"colon_total={colon_hits}")
    for p, ids in groups.items():
        if len(ids) >= 4:
            errors.append(f"prefix18 x{len(ids)}: {p} -> {ids}")
    return errors


def expand(bodies: list[str]) -> list[str]:
    """Lengthen short lines with unique concrete clauses."""
    pad_i = 0
    out = []
    for b in bodies:
        n = cjk_len(b)
        while n < 32:
            extra = PAD[pad_i % len(PAD)]
            pad_i += 1
            b = b.rstrip("。") + "，" + extra.rstrip("。") + "。"
            n = cjk_len(b)
            if n > 68:
                raise SystemExit(f"overlong after pad: {n} {b}")
        out.append(b)
    return out


