def validate(book_id: str, bodies: list[str], title: str, authors: list[str]) -> None:
    if len(bodies) != 150:
        raise SystemExit(f"{book_id} count={len(bodies)}")
    if len(set(bodies)) != 150:
        dup = [b for b, c in Counter(bodies).items() if c > 1]
        raise SystemExit(f"{book_id} dups: {dup[:2]}")
    short_colon = []
    starts = []
    why = 0
    for i, body in enumerate(bodies, 1):
        if not isinstance(body, str):
            raise SystemExit(f"{book_id} #{i} not str")
        if "\n" in body or "\r" in body or "｜" in body:
            raise SystemExit(f"{book_id} #{i} bad format")
        if len(body) < 12:
            raise SystemExit(f"{book_id} #{i} short {len(body)}")
        if any(p in body for p in FORBIDDEN):
            raise SystemExit(f"{book_id} #{i} forbidden")
        if re.search(r".{1,8}面第\d+步[，,]", body) or re.match(r"^第\d+步[，,]", body):
            raise SystemExit(f"{book_id} #{i} step wording")
        match = re.match(r"^([^：:]{1,12})[：:]", body)
        if match and not match.group(1).endswith(NATURAL_COLON_SUFFIXES):
            short_colon.append(i)
        if body.startswith("為什麼") and (len(body) < 18 or True):
            if body[:18].startswith("為什麼") or body.startswith("為什麼"):
                why += 1
        starts.append(body[:18] if len(body) >= 18 else body)
        if title and title in body:
            raise SystemExit(f"{book_id} #{i} full title")
        for a in authors:
            if a and a in body:
                raise SystemExit(f"{book_id} #{i} author {a}")
    if len(short_colon) >= 3:
        raise SystemExit(f"{book_id} short-colon {short_colon}")
    bad = [(k, v) for k, v in Counter(starts).items() if v >= 4]
    if bad:
        raise SystemExit(f"{book_id} prefix {bad[:6]}")
    if why > 3:
        raise SystemExit(f"{book_id} 為什麼 starts {why}")
    comic = sum(1 for b in bodies if b.startswith("漫畫裡"))
    if comic:
        print(f"WARN {book_id} 漫畫裡 starts {comic}")
    print(
        f"OK {book_id} n=150 min={min(len(b) for b in bodies)} max={max(len(b) for b in bodies)} "
        f"why_start={why} colon={len(short_colon)} unique18={len(set(starts))}"
    )


