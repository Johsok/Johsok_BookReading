def content(s: str) -> str:
    return s.split("、", 1)[1]


def validate(name, items):
    errors = []
    if len(items) != 150:
        errors.append(f"{name}: count={len(items)}")
    nums = []
    opens = []
    bodies = []
    for i, s in enumerate(items, 1):
        m = re.match(r"^(\d{3})、(.+)$", s)
        if not m:
            errors.append(f"{name} {i}: bad format")
            continue
        n = int(m.group(1))
        nums.append(n)
        body = m.group(2)
        bodies.append(body)
        ln = len(body)
        if not (35 <= ln <= 70):
            errors.append(f"{name} {i}: len={ln} {body[:20]}")
        for w in FORBIDDEN:
            if w in s:
                errors.append(f"{name} {i}: forbidden {w}")
        if LABEL_RE.search(s):
            errors.append(f"{name} {i}: label")
        if re.search(r"[A-Za-z]", body) and "ppm" not in body:
            errors.append(f"{name} {i}: latin {body}")
        opens.append(body[:4])
    if nums != list(range(1, 151)):
        errors.append(f"{name}: numbering")
    c = Counter(opens)
    rotated = [k for k, v in c.items() if v >= 4]
    if rotated:
        errors.append(f"{name}: repeated openings {rotated}")
    # semantic near-dup: identical bodies
    bc = Counter(bodies)
    dups = [k for k, v in bc.items() if v > 1]
    if dups:
        errors.append(f"{name}: dup bodies")
    return errors, c


