def pad_list(src, padmap):
    out = []
    for i, s in enumerate(src):
        s = REPL.get(s, s)
        if len(s) < 28:
            extra = padmap.get(i, "，這一點要回到生活節奏來看")
            # forbidden 這一章 - don't use 這一
            if extra.startswith("，這一"):
                extra = "，要回到生活節奏裡核對"
            s = s + extra
        if len(s) < 28:
            s = s + "才能看出真正的因果"
        if len(s) > 55:
            raise SystemExit(f"too long {i} {len(s)} {s}")
        out.append(s)
    return out


def add_more(lst, adds, need):
    have = set(lst)
    have18 = {x[:18] for x in lst}
    for a in adds:
        if len(lst) >= need:
            break
        if a in have or a[:18] in have18:
            continue
        if len(a) < 28 or len(a) > 55:
            raise SystemExit("add bad len " + a)
        lst.append(a)
        have.add(a)
        have18.add(a[:18])
    if len(lst) != need:
        raise SystemExit(f"count {len(lst)}")
    return lst


