def force_min(bodies: list[str]) -> list[str]:
    """Append a method tag only when CJK count is below 32."""
    k = 0
    out = []
    for b in bodies:
        n = cjk_len(b)
        while n < 32:
            piece = TAILS[k % len(TAILS)]
            k += 1
            b = b[:-1] + "，" + piece + "。" if b.endswith("。") else b + piece
            n = cjk_len(b)
        out.append(b)
    return out


def fmt(bodies: list[str]) -> list[str]:
    return [f"{i:03d}、{b}" for i, b in enumerate(bodies, 1)]


def validate(bodies: list[str]) -> list[str]:
    errors: list[str] = []
    if len(bodies) != 150:
        errors.append(f"count={len(bodies)}")
    if len(set(bodies)) != 150:
        dups = [b[:20] for b, n in Counter(bodies).items() if n > 1]
        errors.append(f"dup_body {dups[:5]}")
    groups: dict[str, list[int]] = defaultdict(list)
    colon_hits = 0
    yanyi = 0
    for i, b in enumerate(bodies, 1):
        n = cjk_len(b)
        if n < 32 or n > 68:
            errors.append(f"len_{i}:{n} {b}")
        for bad in BANNED:
            if bad in b:
                errors.append(f"ban_{i}:{bad}")
        if re.search(r"第[一二三四五六七八九十百零\d]+章", b) or "這一章" in b:
            errors.append(f"chapter_{i}")
        cc = len(COLON_RE.findall(b))
        if cc:
            colon_hits += cc
            errors.append(f"colon_{i}:{cc}")
        if b.startswith("演義"):
            yanyi += 1
        groups[b[:18]].append(i)
    if colon_hits > 2:
        errors.append(f"colon_total={colon_hits}")
    if yanyi >= 15:
        errors.append(f"yanyi_open={yanyi}")
    for p, ids in groups.items():
        if len(ids) >= 4:
            errors.append(f"prefix18 x{len(ids)}: {p} -> {ids}")
    return errors


