def numbered_ok(items):
    assert len(items) == 150, len(items)
    for i, s in enumerate(items, 1):
        assert s.startswith(f"{i:03d}、"), s[:10]
    texts = [s.split("、", 1)[1] for s in items]
    assert len(set(texts)) == 150
    assert len(set(items)) == 150
    return True


def openings(items):
    return [s.split("、", 1)[1][:2] for s in items]


def update(path: Path, highlights):
    numbered_ok(highlights)
    data = json.loads(path.read_text(encoding="utf-8-sig"))
    data["chatgptHighlights"] = highlights
    data["chatgptStatus"] = "complete"
    data["highlightsSource"] = "grok"
    data["highlightsCapturedAt"] = STAMP
    data["updatedAt"] = DATE
    path.write_text(
        json.dumps(data, ensure_ascii=False, indent=2) + "\n",
        encoding="utf-8",
        newline="\n",
    )


