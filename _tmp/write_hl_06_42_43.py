def fmt(bodies: list[str]) -> list[str]:
    assert len(bodies) == 150, len(bodies)
    return [f"{i:03d}、{b}" for i, b in enumerate(bodies, 1)]


def validate(label: str, bodies: list[str]) -> list[str]:
    errors: list[str] = []
    if len(bodies) != 150:
        errors.append(f"{label} count {len(bodies)}")
    if len(set(bodies)) != len(bodies):
        errors.append(f"{label} duplicate bodies")
    groups: dict[str, list[int]] = defaultdict(list)
    for i, b in enumerate(bodies, 1):
        if not b.strip():
            errors.append(f"{label} empty {i}")
        for w in BANNED:
            if w in b:
                errors.append(f"{label} banned {w} @ {i}")
        if CHAP_RE.search(b):
            errors.append(f"{label} chapter @ {i}")
        if COLON_RE.search(b):
            errors.append(f"{label} colon @ {i}")
        if "面第" in b and "步" in b:
            errors.append(f"{label} step-tag @ {i}")
        groups[b[:10]].append(i)
    for p, ids in groups.items():
        if len(ids) >= 3:
            errors.append(f"{label} same-prefix {p!r} {ids}")
    return errors


def write_book(path: Path, bodies: list[str]) -> None:
    data = json.loads(path.read_text(encoding="utf-8"))
    hl = fmt(bodies)
    data["chatgptHighlights"] = hl
    data.update(META)
    path.write_text(json.dumps(data, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    back = json.loads(path.read_text(encoding="utf-8"))
    got = back["chatgptHighlights"]
    assert len(got) == 150
    assert got == hl
    texts = [x.split("、", 1)[1] for x in got]
    assert all(x.startswith(f"{i:03d}、") for i, x in enumerate(got, 1))
    assert len(texts) == len(set(texts))
    assert back["chatgptStatus"] == "complete"
    assert back["highlightsSource"] == "grok"
    assert back["highlightsCapturedAt"] == "2026-08-18T09:10:00+08:00"
    assert back["updatedAt"] == "2026-08-18"


